"""
Domain Models for Auto-Connect Application Discovery & A2A Ecosystem
"""

from typing import Dict, Any, List, Optional
from datetime import datetime, timezone
import uuid
from pydantic import BaseModel, Field, field_validator


class DiscoveredEndpointTool(BaseModel):
    """Callable tool extracted automatically from application metadata."""
    tool_name: str = Field(description="Snake_case name of the capability")
    http_method: str = Field(description="GET, POST, PUT, DELETE, etc.")
    endpoint_path: str = Field(description="Target URL path")
    description: str = Field(description="When and why an agent should call this endpoint")
    required_parameters: List[str] = Field(default_factory=list, description="Mandatory input parameters")
    optional_parameters: List[str] = Field(default_factory=list, description="Optional parameters")
    can_resolve_issues: List[str] = Field(
        default_factory=list,
        description="Types of banking blockers/issues this endpoint can fix automatically",
    )
    mcp_tool_schema: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Standard MCP JSON Schema for model tool invocation",
    )

    @field_validator("required_parameters", "optional_parameters", mode="before")
    @classmethod
    def _parameter_names(cls, value: Any) -> Any:
        # LLMs often return parameters as {"name": ..., "type": ...} objects; keep just the name.
        if isinstance(value, list):
            return [v.get("name") or v.get("parameter_name") or str(v) if isinstance(v, dict) else v for v in value]
        return value


class AutoGeneratedAgentCard(BaseModel):
    """Standard A2A Agent Card generated automatically when the Brain analyzes a bank app."""
    agent_id: str = Field(description="Unique agent identifier, e.g. 'agent_trade_finance_doka'")
    application_name: str = Field(description="Human readable name of the connected application")
    banking_department: str = Field(description="Primary banking department (e.g. TRADE_FINANCE, CREDIT_RISK)")
    system_instruction: str = Field(
        description="Complete system prompt instructing this newly spawned agent how to operate the app and collaborate with colleagues"
    )
    discovered_tools: List[DiscoveredEndpointTool] = Field(default_factory=list)
    peer_departments_to_collaborate_with: List[str] = Field(default_factory=list)
    well_known_uri: str = Field(default="/.well-known/agent.json")
    version: str = Field(default="1.0.0")
    supported_protocols: List[str] = Field(default_factory=lambda: ["A2A", "MCP", "REST"])
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class VaultCredential(BaseModel):
    """Zero-trust credential managed by HashiCorp Vault / GCP Secret Manager."""
    app_id: str
    base_url: str
    auth_type: str = Field(default="Bearer", description="'Bearer', 'mTLS', 'API_KEY', 'OAuth2', 'None'")
    token: Optional[str] = Field(default=None, description="Secret value, or a reference: 'env:NAME' / 'file:/path'")
    client_cert: Optional[str] = None
    allowed_departments: List[str] = Field(default_factory=lambda: ["*"])
    rate_limit_per_minute: int = 120
    # OAuth 2.0 client credentials (bank API gateway, Microsoft Entra ID, SAP BTP ...)
    oauth_token_url: Optional[str] = None
    oauth_client_id: Optional[str] = None
    oauth_client_secret: Optional[str] = Field(default=None, description="Secret or 'env:NAME' / 'file:/path'")
    oauth_scope: Optional[str] = None
    # real mutual TLS: the client certificate/key presented in the TLS handshake (PEM files)
    client_cert_file: Optional[str] = None
    client_key_file: Optional[str] = None
    ca_bundle_file: Optional[str] = Field(default=None, description="CA bundle to verify the server (bank PKI)")
    # how messages travel: HTTP (REST), FILE (shared hot folder), SFTP, IBM_MQ (via the MQ REST messaging API)
    transport: str = Field(default="HTTP", description="'HTTP', 'FILE', 'SFTP', 'IBM_MQ'")
    transport_target: Optional[str] = Field(default=None, description="FILE/SFTP: outbound folder; IBM_MQ: 'QMGR/QUEUE'")
    transport_reply: Optional[str] = Field(default=None, description="FILE/SFTP: reply folder; IBM_MQ: 'QMGR/REPLY.QUEUE'")
    transport_format: str = Field(default="JSON", description="'JSON' envelope, or 'RAW:<param>' to send that parameter as is "
                                                              "(e.g. RAW:fin_text for SWIFT hot folders)")
    reply_timeout_seconds: float = 30.0


class ApplicationRegistration(BaseModel):
    """Registration record of an application exposed to the bank API Gateway."""
    app_id: str
    name: str
    base_url: str
    spec_format: str = Field(default="openapi_3", description="'openapi_3', 'swagger_2', 'sap_odata', 'legacy_screen'")
    raw_specification: Dict[str, Any]
    department_hint: Optional[str] = None


class MeshMessage(BaseModel):
    """Agent-to-Agent (A2A) protocol message."""
    message_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    sender_agent_id: str
    target_agent_id: str
    intent: str = Field(description="e.g. 'REQUEST_CREDIT_REALLOCATION', 'REQUEST_DISCREPANCY_WAIVER'")
    payload: Dict[str, Any]
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    status: str = "DELIVERED"
    response_payload: Optional[Dict[str, Any]] = None


class ResolutionStep(BaseModel):
    """Single execution step in resolving a multi-app banking event."""
    step_number: int
    executing_agent_id: str
    department: str
    action: str
    tool_called: Optional[str] = None
    parameters: Dict[str, Any] = Field(default_factory=dict)
    result: Dict[str, Any] = Field(default_factory=dict)
    status: str = "SUCCESS"


class ResolutionTrace(BaseModel):
    """Audit trace of an autonomous end-to-end banking resolution."""
    event_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    business_problem: str
    primary_agent_id: str
    collaborating_agents: List[str] = Field(default_factory=list)
    steps: List[ResolutionStep] = Field(default_factory=list)
    final_outcome: str = ""
    is_fully_resolved: bool = True
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

