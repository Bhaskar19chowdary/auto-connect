def _has_term(text: str, terms: List[str]) -> bool:
    """
    Keyword test used by the semantic engine.
    Short terms (<= 3 chars such as "pd", "lc", "aml", "crr") must match a whole
    word, otherwise "pd" would match "update" and "lc" would match "calculate".
    """
    import re

    for term in terms:
        if len(term) <= 3:
            if re.search(r"(?<![a-z0-9])" + re.escape(term) + r"(?![a-z0-9])", text):
                return True
        elif term in text:
            return True
    return False


def get_gemini_client():
    """Returns Gemini client if API key is provided, else None."""
    try:
        from dotenv import load_dotenv
        load_dotenv()
    except Exception:
        pass

    if os.environ.get("GOOGLE_GENAI_USE_VERTEXAI", "").strip().lower() in ("1", "true", "yes"):
        # Bank set-up: Gemini on Vertex AI in the bank's own Google Cloud project (EU region, no API key,
        # credentials from the service account / workload identity, data not used for model training)
        try:
            from google import genai
            from google.genai import types

            return genai.Client(vertexai=True, project=os.environ.get("GOOGLE_CLOUD_PROJECT"),
                                location=os.environ.get("GOOGLE_CLOUD_LOCATION", "europe-west3"),
                                http_options=types.HttpOptions(timeout=60_000))
        except Exception as e:
            logger.warning(f"Could not initialize Vertex AI Gemini client: {e}")
            return None
    api_key = os.environ.get("GEMINI_API_KEY")
    if not api_key or api_key.startswith("YOUR_") or len(api_key.strip()) < 10:
        return None
    try:
        from google import genai
        from google.genai import types

        # Fail fast (60s) instead of hanging when a model is overloaded; the rules engine takes over.
        return genai.Client(api_key=api_key.strip(), http_options=types.HttpOptions(timeout=60_000))
    except Exception as e:
        logger.warning(f"Could not initialize google-genai client: {e}")
        return None


def _gemini_config():
    try:
        from google.genai import types

        return types.GenerateContentConfig(response_mime_type="application/json", temperature=0.0)
    except ImportError:
        return {"response_mime_type": "application/json", "temperature": 0.0}


class AutonomousEcosystemBrain:
    """
    Scans any newly connected bank application, analyzes its API/schema/UI,
    automatically spawns a specialized agent for it, registers its MCP tools,
    and connects it to all other agents in the bank's A2A mesh.
    """

    def __init__(
        self,
        vault: Optional[ZeroTrustVault] = None,
        mesh: Optional[A2AEcosystemMesh] = None,
        executor: Optional[UniversalAPIExecutor] = None,
        preferred_model: Optional[str] = None,
    ):
        self.vault = vault or ZeroTrustVault()
        self.mesh = mesh or A2AEcosystemMesh()
        self.executor = executor or UniversalAPIExecutor(self.vault)
        from .settings import gemini_model
        self.preferred_model = preferred_model or gemini_model()
        self.client = get_gemini_client()
        # How each application was analysed: {agent_id: {"engine": "GEMINI"|"RULES", "model", "error"}}
        self.analysis_log: Dict[str, Dict[str, Any]] = {}
        self.last_analysis: Dict[str, Any] = {}

    async def analyze_and_assimilate_application_async(
        self, raw_app_specification: Dict[str, Any], app_id_hint: Optional[str] = None
    ) -> AutoGeneratedAgentCard:
        """Same as analyze_and_assimilate_application but runs the (blocking) Gemini call in a worker thread."""
        import asyncio

        return await asyncio.to_thread(self.analyze_and_assimilate_application, raw_app_specification, app_id_hint)

    def read_documents(self, files) -> Dict[str, Any]:
        """Intelligent document recognition: Gemini when available, else the built-in PDF/OCR reader (blocking)."""
        from .document_reader import DocumentReader

        return DocumentReader(self).read(files)

    def gemini_status(self) -> Dict[str, Any]:
        used = [v for v in self.analysis_log.values() if v.get("engine") == "GEMINI"]
        failed = [v for v in self.analysis_log.values() if v.get("gemini_error")]
        return {
            "configured": self.client is not None,
            "model": self.preferred_model,
            "apps_analysed_by_gemini": len(used),
            "apps_analysed_by_rules": len(self.analysis_log) - len(used),
            "last_gemini_error": failed[-1]["gemini_error"] if failed else None,
        }

    def analyze_and_assimilate_application(
        self, raw_app_specification: Dict[str, Any], app_id_hint: Optional[str] = None
    ) -> AutoGeneratedAgentCard:
        """
        Reads raw OpenAPI/Swagger spec, SAP OData metadata, or UI screen descriptor,
        and automatically generates a fully configured Agent + Toolset in the ecosystem.
        """
        # If Gemini client is available, use live LLM introspection
        if self.client:
            try:
                prompt = f"""
You are the Master Ecosystem Architect Brain for a Tier-1 Universal Bank (Demo Bank).
A banking application has just been connected to the enterprise gateway.
Analyze its raw technical specification below, determine its exact banking domain,
extract all operational endpoints into callable tools, identify what cross-department
issues it can resolve (in 'can_resolve_issues'), and generate its complete A2A Agent Card
so it can immediately communicate with all other applications in the bank.
{"IMPORTANT: Set agent_id to exactly: " + app_id_hint if app_id_hint else ""}

Set banking_department to exactly one of: TRADE_FINANCE, CREDIT_RISK, CLIENT_ENGAGEMENT, COMPLIANCE_AML,
OFFICE_COMMUNICATION, FINANCIAL_REPORTING, CLIENT_RELATIONSHIP, TRADE_REPORTING, PAYMENTS_SWIFT,
CORPORATE_PAYMENTS_EBICS, TREASURY_MARKETS (market data, FX / exchange rates), REGULATORY_REPORTING,
TREASURY_MANAGEMENT (cash & liquidity), WEALTH_MANAGEMENT, CUSTOMER_DATA (customer master, KYC), CORE_BANKING.

Use standard issue tags in 'can_resolve_issues' where applicable:
- UCP600_DISCREPANCY_CHECK, DOCUMENTARY_EXAMINATION_BLOCKER
- CREDIT_LIMIT_SHORTFALL, FACILITY_CAPACITY_BREACH
- MISSING_TRADE_DOCUMENT, DISCREPANCY_WAIVER_REQUIRED
- SANCTIONS_CHECK_HOLD, UNRATED_COUNTERPARTY
- EXECUTIVE_SLIDE_DECK, EMAIL_SUMMARY_DISPATCH
- CROSS_BORDER_PAYMENT_EXECUTION, MARKET_DATA_VALUATION
- REGULATORY_CAPITAL_CHECK, LIQUIDITY_POSITION_CHECK
- WEALTH_CLIENT_KYC, EMIR_TRADE_REPORT

Return valid JSON with these fields:
agent_id, application_name, banking_department, system_instruction, discovered_tools (list of tool_name, http_method, endpoint_path, description, required_parameters, optional_parameters, can_resolve_issues; required_parameters and optional_parameters are lists of plain parameter-name strings), peer_departments_to_collaborate_with.

RAW APPLICATION SPECIFICATION:
{json.dumps(raw_app_specification, indent=2)}
"""
                response = self.client.models.generate_content(
                    model=self.preferred_model,
                    contents=prompt,
                    config=_gemini_config(),
                )
                raw_text = response.text.strip()
                if raw_text.startswith("```"):
                    raw_text = raw_text.split("```")[1]
                    if raw_text.startswith("json"):
                        raw_text = raw_text[4:].strip()
                agent_card = AutoGeneratedAgentCard.model_validate_json(raw_text)
                if app_id_hint:
                    agent_card.agent_id = app_id_hint
                if not agent_card.discovered_tools:
                    raise ValueError("Gemini returned no tools")
                # keep exact paths/methods from the spec (the model may paraphrase them)
                rules_card = self._semantic_banking_analyzer(raw_app_specification, app_id_hint)
                spec_paths = {(t.http_method, t.endpoint_path) for t in rules_card.discovered_tools}
                if not all((t.http_method.upper(), t.endpoint_path) in spec_paths for t in agent_card.discovered_tools):
                    agent_card.discovered_tools = rules_card.discovered_tools
                self.last_analysis = {"engine": "GEMINI", "model": self.preferred_model, "gemini_error": None}
                self.analysis_log[agent_card.agent_id] = self.last_analysis
                self.mesh.register_agent(agent_card)
                return agent_card
            except Exception as e:
                gemini_error = f"{type(e).__name__}: {str(e)[:300]}"
                logger.warning(f"Gemini LLM analysis encountered error ({e}); using Banking Semantic Engine fallback.")
        else:
            gemini_error = None

        # High-Fidelity Banking Semantic Engine Fallback
        agent_card = self._semantic_banking_analyzer(raw_app_specification, app_id_hint)
        self.last_analysis = {"engine": "RULES", "model": None, "gemini_error": gemini_error}
        self.analysis_log[agent_card.agent_id] = self.last_analysis
        self.mesh.register_agent(agent_card)
        return agent_card

    def assimilate_legacy_screen(
        self,
        screen_input: str,
        app_id_hint: str = "agent_legacy_mainframe",
        terminal_url: str = "terminal://3270.core.internal.bank.example",
    ) -> AutoGeneratedAgentCard:
        """
        Parses a 30-year-old mainframe green-screen (IBM 3270 / VT100 / Desktop GUI)
        without APIs using Gemini Vision / Terminal Introspection, and turns it into
        a callable agent in the bank's mesh.
        """
        parsed = ApplicationIntrospector.parse_terminal_screen_text(screen_input)
        title = parsed["title"]
        ep = parsed["endpoints"][0]
        fields = ep["parameters"]
        action_key = parsed["raw_spec"].get("action_key", "F3")

        tool = DiscoveredEndpointTool(
            tool_name=f"submit_screen_{action_key.lower()}",
            http_method="UI_ACTION",
            endpoint_path=ep["path"],
            description=ep["summary"],
            required_parameters=fields,
            can_resolve_issues=["LEGACY_CORE_PAYMENT_EXECUTION", "MAINFRAME_ACCOUNT_POSTING"],
            mcp_tool_schema={
                "type": "object",
                "properties": {f: {"type": "string", "description": f"Mainframe screen field: {f}"} for f in fields},
                "required": fields,
            },
        )

        agent_card = AutoGeneratedAgentCard(
            agent_id=app_id_hint,
            application_name=f"IBM 3270 Mainframe ({title})",
            banking_department="CORE_BANKING",
            system_instruction=(
                f"You are the Specialist Mainframe Agent operating screen {title}. "
                "Because this legacy banking system has no REST API, you simulate terminal input into screen "
                f"fields ({', '.join(fields)}) and send keystroke [{action_key}] to post core ledger updates."
            ),
            discovered_tools=[tool],
            peer_departments_to_collaborate_with=["TRADE_FINANCE", "PAYMENTS", "TREASURY"],
        )

        # Ensure Zero-Trust credential for the terminal session is provisioned
        from .models import VaultCredential
        self.vault.store_credential(VaultCredential(
            app_id=app_id_hint,
            base_url=terminal_url,
            auth_type="TN3270_TERMINAL_SESSION",
            token="tn3270_session_authenticated_vt100",
            allowed_departments=["*"],
        ))

        self.mesh.register_agent(agent_card)
        return agent_card

