"""
Agent-to-Agent (A2A) Ecosystem Mesh & Directory
Enables autonomous agent discovery, issue resolution indexing, and cross-department messaging.
"""

from typing import Dict, List, Optional, Tuple, Any
from datetime import datetime, timezone
import logging
from .models import AutoGeneratedAgentCard, DiscoveredEndpointTool, MeshMessage

logger = logging.getLogger("auto_connect.mesh")


class A2AEcosystemMesh:
    """
    Central Bank Mesh Directory.
    Manages A2A Agent Cards, maps business issues to resolving agents,
    and handles inter-agent communication.
    """

    def __init__(self):
        # agent_id -> AutoGeneratedAgentCard
        self.active_agents: Dict[str, AutoGeneratedAgentCard] = {}
        # Message ledger for audit and trace
        self.message_ledger: List[MeshMessage] = []

    def register_agent(self, card: AutoGeneratedAgentCard) -> None:
        """Publishes an agent into the bank's active directory."""
        self.active_agents[card.agent_id] = card
        logger.info(f"Registered Agent '{card.agent_id}' ({card.application_name}) with {len(card.discovered_tools)} tools.")

    def unregister_agent(self, agent_id: str) -> bool:
        """Removes an agent from the active bank directory."""
        if agent_id in self.active_agents:
            del self.active_agents[agent_id]
            logger.info(f"Unregistered Agent '{agent_id}' from bank mesh.")
            return True
        return False

    def get_agent(self, agent_id: str) -> Optional[AutoGeneratedAgentCard]:
        return self.active_agents.get(agent_id)

    def list_agents(self) -> List[AutoGeneratedAgentCard]:
        return list(self.active_agents.values())

    def find_agents_for_issue(self, issue_description: str) -> List[Tuple[AutoGeneratedAgentCard, DiscoveredEndpointTool]]:
        """
        Synthesizes routing by matching an issue/blocker to agents whose tools
        advertise capability in `can_resolve_issues`. Supports both snake_case constants
        and natural language descriptions with strict precision ranking.
        """
        issue_lower = issue_description.lower().strip()
        issue_clean = issue_lower.replace("_", " ")

        STOP_WORDS = {
            "check", "hold", "required", "blocker", "validation", "issue", "pending",
            "status", "data", "call", "screening", "executive", "corporate", "enterprise",
            "department", "client", "trade", "execution", "posting", "settlement"
        }
        issue_words = set(w for w in issue_clean.split() if len(w) > 3 and w not in STOP_WORDS)

        exact_matches: List[Tuple[AutoGeneratedAgentCard, DiscoveredEndpointTool]] = []
        substring_matches: List[Tuple[AutoGeneratedAgentCard, DiscoveredEndpointTool]] = []
        fuzzy_matches: List[Tuple[AutoGeneratedAgentCard, DiscoveredEndpointTool]] = []

        for agent in self.active_agents.values():
            for tool in agent.discovered_tools:
                matched_tier = None
                for can_fix in tool.can_resolve_issues:
                    can_fix_lower = can_fix.lower().strip()
                    can_fix_clean = can_fix_lower.replace("_", " ")

                    if can_fix_lower == issue_lower or can_fix_clean == issue_clean:
                        matched_tier = "exact"
                        break
                    elif can_fix_lower in issue_lower or issue_lower in can_fix_lower:
                        if matched_tier != "exact":
                            matched_tier = "substring"
                    else:
                        fix_words = set(w for w in can_fix_clean.split() if len(w) > 3 and w not in STOP_WORDS)
                        overlap = fix_words & issue_words
                        if overlap and len(overlap) >= 2:
                            if not matched_tier:
                                matched_tier = "fuzzy"

                if matched_tier == "exact":
                    exact_matches.append((agent, tool))
                elif matched_tier == "substring":
                    substring_matches.append((agent, tool))
                elif matched_tier == "fuzzy":
                    fuzzy_matches.append((agent, tool))
                else:
                    # Fallback keyword checks on tool name & description
                    if any(term in issue_lower for term in ["credit", "limit", "shortfall", "capacity"]) and "reallocate" in tool.tool_name.lower():
                        fuzzy_matches.append((agent, tool))
                    elif any(term in issue_lower for term in ["waiver", "missing", "discrepancy"]) and ("waiver" in tool.tool_name.lower() or "missing" in tool.tool_name.lower()):
                        fuzzy_matches.append((agent, tool))
                    elif any(term in issue_lower for term in ["sanction", "aml", "ofac", "pep"]) and "sanction" in tool.tool_name.lower():
                        fuzzy_matches.append((agent, tool))
                    elif any(term in issue_lower for term in ["rating", "default", "moody", "scoring"]) and ("rating" in tool.tool_name.lower() or "counterparty" in tool.tool_name.lower()):
                        fuzzy_matches.append((agent, tool))
                    elif any(term in issue_lower for term in ["mail", "email", "summary"]) and "mail" in tool.tool_name.lower():
                        fuzzy_matches.append((agent, tool))
                    elif any(term in issue_lower for term in ["slide", "presentation", "deck", "powerpoint"]) and "presentation" in tool.tool_name.lower():
                        fuzzy_matches.append((agent, tool))
                    elif any(term in issue_lower for term in ["swift", "payment", "mt103", "cross_border"]) and ("swift" in tool.tool_name.lower() or "mt103" in tool.tool_name.lower()):
                        fuzzy_matches.append((agent, tool))
                    elif any(term in issue_lower for term in ["bloomberg", "market", "valuation", "fx_spot"]) and ("market" in tool.tool_name.lower() or "valuation" in tool.tool_name.lower()):
                        fuzzy_matches.append((agent, tool))
                    elif any(term in issue_lower for term in ["regulatory", "capital", "basel", "onesumx", "cet1"]) and ("regulatory" in tool.tool_name.lower() or "capital" in tool.tool_name.lower()):
                        fuzzy_matches.append((agent, tool))
                    elif any(term in issue_lower for term in ["treasury", "liquidity", "cash_pool", "finastra"]) and ("liquidity" in tool.tool_name.lower() or "cash" in tool.tool_name.lower()):
                        fuzzy_matches.append((agent, tool))
                    elif any(term in issue_lower for term in ["kyc", "due_diligence", "fatca"]) and "kyc" in tool.tool_name.lower():
                        fuzzy_matches.append((agent, tool))
                    elif any(term in issue_lower for term in ["wealth", "portfolio", "avaloq", "private_banking"]) and "portfolio" in tool.tool_name.lower():
                        fuzzy_matches.append((agent, tool))
                    elif any(term in issue_lower for term in ["dtcc", "emir", "mifid", "trade_report", "uti"]) and "emir" in tool.tool_name.lower():
                        fuzzy_matches.append((agent, tool))

        if exact_matches:
            return exact_matches
        if substring_matches:
            return substring_matches
        return fuzzy_matches

    def send_a2a_message(
        self,
        sender_agent_id: str,
        target_agent_id: str,
        intent: str,
        payload: Dict[str, Any],
        response_payload: Optional[Dict[str, Any]] = None,
    ) -> MeshMessage:
        """Sends and records an A2A message in the bank's mesh ledger."""
        msg = MeshMessage(
            sender_agent_id=sender_agent_id,
            target_agent_id=target_agent_id,
            intent=intent,
            payload=payload,
            status="RESOLVED" if response_payload else "DELIVERED",
            response_payload=response_payload,
        )
        self.message_ledger.append(msg)
        return msg

    def export_mcp_tool_definitions(self) -> List[Dict[str, Any]]:
        """
        Exports all auto-generated tools as standard Model Context Protocol (MCP) definitions.
        """
        mcp_tools = []
        for agent in self.active_agents.values():
            for tool in agent.discovered_tools:
                schema = tool.mcp_tool_schema or {
                    "type": "object",
                    "properties": {param: {"type": "string", "description": f"Banking parameter {param}"} for param in tool.required_parameters},
                    "required": tool.required_parameters,
                }
                mcp_tools.append({
                    "name": f"{agent.agent_id}__{tool.tool_name}",
                    "description": f"[{agent.banking_department}] {tool.description}",
                    "inputSchema": schema,
                })
        return mcp_tools

    def get_agent_card_json(self, agent_id: str) -> Optional[Dict[str, Any]]:
        """Returns standard A2A Agent Card formatted for /.well-known/agent.json."""
        agent = self.get_agent(agent_id)
        if not agent:
            return None
        return agent.model_dump()

