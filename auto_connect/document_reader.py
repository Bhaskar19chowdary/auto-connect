"""
Intelligent Document Recognition (IDR) for trade documents.

Turns presented documents (PDF, image or text) into the structured `PresentedDocument` data the UCP 600 /
URDG 758 examination works on: document type, issue date, originals/copies and the fields an examiner checks
(invoice amount, parties, goods; B/L on-board date, ports, carrier signature, clean; insurance cover ...).

Engines, best first:
1. Gemini (multimodal) - reads the document like an examiner (layout, tables, stamps), when a key/quota is available.
2. Built-in reader - text layer of digital PDFs (pypdf) or OCR of scans (Tesseract, if installed), then
   rule-based field extraction. No AI and no internet needed.

Every result carries a confidence and the list of fields that could not be read, so a human document checker
verifies uncertain readings before anything is examined or paid (four-eyes, as in a real trade back office).
"""

