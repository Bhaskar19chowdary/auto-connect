GEMINI_PROMPT = """You are a senior documentary credit examiner at a German bank. Read the attached trade document(s)
and return JSON: {"documents": [ ... ]} with one object per document found (a file may contain several), each:
{"doc_type": one of COMMERCIAL_INVOICE, BILL_OF_LADING, AIR_WAYBILL, INSURANCE_DOCUMENT, PACKING_LIST,
 CERTIFICATE_OF_ORIGIN, INSPECTION_CERTIFICATE, BENEFICIARY_STATEMENT, DEMAND, STATEMENT_OF_BREACH,
 NOTICE_OF_DEFAULT, EVIDENCE_OF_CLAIM, OTHER,
 "issue_date": "YYYY-MM-DD" or null, "issuer": string or null, "originals": int, "copies": int,
 "confidence": 0..1,
 "fields": {only fields printed on the document, as written:
   invoice: amount (number only), currency (ISO), beneficiary_name, beneficiary_address, applicant_name,
            goods_description, lc_number, invoice_number, country_of_origin;
   bill of lading / air waybill: on_board_date (YYYY-MM-DD), port_of_loading, port_of_discharge, vessel,
            vessel_imo (IMOnnnnnnn), carrier, signed_by (CARRIER, MASTER or AGENT), originals_issued (int),
            clean (false if any clause declares a defective condition of goods or packaging), transhipment (bool),
            goods_description;
   insurance: coverage_amount (number), currency, covers_from, covers_to, risks;
   certificate of origin: country_of_origin;
   demand: amount, currency, guarantee_ref, breach_statement}}
Never invent values: omit a field that is not on the document."""


class DocumentReader:
    agent_id = "tf_document_reader"

    def __init__(self, brain=None):
        self.brain = brain

    def agent_card(self) -> AutoGeneratedAgentCard:
        return AutoGeneratedAgentCard(
            agent_id=self.agent_id,
            application_name="Intelligent Document Recognition (trade documents)",
            banking_department="TRADE_FINANCE",
            system_instruction=("You read presented trade documents (invoice, bill of lading, insurance, packing list, "
                                "certificates, guarantee demands) and turn them into structured data for the UCP 600 / "
                                "URDG 758 examination. Uncertain readings go to a human document checker."),
            discovered_tools=[DiscoveredEndpointTool(
                tool_name="read_documents", http_method="POST", endpoint_path="/api/v1/tf/documents/read",
                description="Classify documents and extract the fields an examiner checks",
                required_parameters=["files"], can_resolve_issues=["DOCUMENTARY_EXAMINATION_BLOCKER", "MISSING_TRADE_DOCUMENT"])],
            peer_departments_to_collaborate_with=["TRADE_FINANCE", "COMPLIANCE_AML"],
        )

    @staticmethod
    def decode(files: List[Dict[str, Any]]) -> List[Tuple[str, bytes]]:
        out = []
        for f in files:
            name = f.get("filename") or "document"
            if f.get("content_base64"):
                out.append((name, base64.b64decode(f["content_base64"])))
            elif f.get("text") is not None:
                out.append((name, str(f["text"]).encode("utf-8")))
        return out

    def read(self, files: List[Tuple[str, bytes]]) -> Dict[str, Any]:
        """Blocking (Gemini / OCR); call from a worker thread."""
        docs, notes, engines = [], [], set()
        for name, data in files:
            mime = mime_of(name, data)
            got, engine, note = None, None, None
            if self.brain is not None and getattr(self.brain, "client", None) is not None and mime != "text/plain":
                try:
                    got, engine = self._gemini(data, mime), f"Gemini ({self.brain.preferred_model})"
                except Exception as e:
                    note = f"{name}: Gemini could not read it ({type(e).__name__}: {str(e)[:120]}); built-in reader used"
            if got is None:
                got, engine, why = self._builtin(name, data, mime)
                if why:
                    note = (note + "; " if note else f"{name}: ") + why
            for d in got:
                d["source_file"] = name
                d["engine"] = engine
                self._assess(d)
                docs.append(d)
            engines.add(engine)
            if note:
                notes.append(note)
        return {"engines": sorted(e for e in engines if e), "documents": docs, "notes": notes,
                "needs_review": [f"{d['source_file']}: {d['doc_type']} - {d['review_reason']}" for d in docs if d["needs_review"]]}

    def _gemini(self, data: bytes, mime: str) -> List[Dict[str, Any]]:
        from google.genai import types

        resp = self.brain.client.models.generate_content(
            model=self.brain.preferred_model,
            contents=[types.Part.from_bytes(data=data, mime_type=mime), GEMINI_PROMPT],
            config=types.GenerateContentConfig(response_mime_type="application/json", temperature=0.0))
        raw = json.loads(resp.text)
        items = raw.get("documents", []) if isinstance(raw, dict) else raw
        out = []
        for it in items:
            fields = {k: v for k, v in (it.get("fields") or {}).items() if v not in (None, "", [])}
            for k in ("amount", "coverage_amount"):
                if k in fields:
                    amt, _ = parse_amount(str(fields[k]))
                    fields[k] = str(amt) if amt is not None else fields[k]
            out.append({"doc_type": it.get("doc_type") or "OTHER", "issue_date": it.get("issue_date"),
                        "issuer": it.get("issuer"), "originals": int(it.get("originals") or 1),
                        "copies": int(it.get("copies") or 0), "fields": fields,
                        "model_confidence": float(it.get("confidence") or 0.8)})
        if not out:
            raise ValueError("no document recognised")
        return out

    def _builtin(self, name: str, data: bytes, mime: str):
        if mime == "application/pdf":
            text, how = pdf_text(data), "PDF text layer"
            if len(text.strip()) < 20:
                text, how = ocr_pdf(data), "Tesseract OCR of scanned PDF"
        elif mime.startswith("image/"):
            text, how = ocr_image(data, "." + mime.split("/")[1]), "Tesseract OCR"
        else:
            text, how = data.decode("utf-8", errors="replace"), "plain text"
        if len(text.strip()) < 20:
            why = ("scanned document but no OCR engine available - install Tesseract (brew install tesseract) "
                   "or enable Gemini" if mime != "text/plain" else "empty document")
            return [{"doc_type": "OTHER", "issue_date": None, "issuer": None, "originals": 1, "copies": 0, "fields": {},
                     "unreadable": True}], "built-in reader", why
        doc_type = classify(text)
        fields = extract_fields(doc_type, text)
        issue = None
        for k, v in _label_values(text):
            if k in COMMON_LABELS["issue_date"]:
                issue = parse_date(v)
                if issue:
                    break
        orig, cop = _originals(text)
        if doc_type == "BILL_OF_LADING" and fields.get("originals_issued") and orig == 1:
            orig = fields["originals_issued"]
        return [{"doc_type": doc_type, "issue_date": issue.isoformat() if issue else None, "issuer": fields.get("beneficiary_name"),
                 "originals": orig, "copies": cop, "fields": fields}], f"built-in reader ({how})", None

    @staticmethod
    def _assess(d: Dict[str, Any]):
        need = KEY_FIELDS.get(d["doc_type"], [])
        missing = [f for f in need if f not in d["fields"]]
        if d.get("unreadable"):
            d["confidence"], d["missing_fields"], d["needs_review"], d["review_reason"] = 0.0, need, True, "document could not be read"
            return
        conf = (len(need) - len(missing)) / len(need) if need else (0.6 if d["doc_type"] == "OTHER" else 0.9)
        if "model_confidence" in d:
            conf = min(conf, d.pop("model_confidence"))
        d["confidence"] = round(conf, 2)
        d["missing_fields"] = missing
        d["needs_review"] = bool(missing) or d["doc_type"] == "OTHER" or conf < 0.75
        d["review_reason"] = ("could not read: " + ", ".join(missing)) if missing else \
            ("document type not recognised" if d["doc_type"] == "OTHER" else ("low confidence" if d["needs_review"] else ""))


def to_presented(d: Dict[str, Any]) -> Dict[str, Any]:
    """Reader output -> PresentedDocument payload."""
    issue = d.get("issue_date")
    try:
        issue = date.fromisoformat(issue).isoformat() if issue else None
    except ValueError:
        issue = None
    return {"doc_type": d["doc_type"] if d["doc_type"] != "OTHER" else "OTHER", "originals": d.get("originals", 1),
            "copies": d.get("copies", 0), "issue_date": issue, "issuer": d.get("issuer"), "fields": d.get("fields", {})}
