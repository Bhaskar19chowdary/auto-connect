# ---------------------------------------------------------------------------- parsing helpers
def parse_amount(text: str) -> Tuple[Optional[Decimal], Optional[str]]:
    """'EUR 300,000.00' / '300.000,00 EUR' / 'USD 1,234' -> (Decimal, currency)."""
    if not text:
        return None, None
    ccy = next((c for c in CURRENCIES if re.search(rf"\b{c}\b", text.upper())), None)
    m = re.search(r"\d[\d.,' ]*\d|\d", text)
    if not m:
        return None, ccy
    num = m.group(0).replace(" ", "").replace("'", "")
    if "," in num and "." in num:
        num = num.replace(".", "").replace(",", ".") if num.rfind(",") > num.rfind(".") else num.replace(",", "")
    elif "," in num:
        head, _, tail = num.rpartition(",")
        num = num.replace(",", ".") if len(tail) == 2 and head.count(",") == 0 else num.replace(",", "")
    elif num.count(".") > 1 or (num.count(".") == 1 and len(num.split(".")[1]) == 3):
        num = num.replace(".", "")
    try:
        return Decimal(num), ccy
    except InvalidOperation:
        return None, ccy


def parse_date(text: str) -> Optional[date]:
    if not text:
        return None
    t = text.strip()
    for rx, order in [(r"(\d{4})-(\d{1,2})-(\d{1,2})", "ymd"), (r"(\d{1,2})[./](\d{1,2})[./](\d{4})", "dmy")]:
        m = re.search(rx, t)
        if m:
            a, b, c = (int(x) for x in m.groups())
            try:
                return date(a, b, c) if order == "ymd" else date(c, b, a)
            except ValueError:
                pass
    m = re.search(r"(\d{1,2})\s*([A-Za-z]{3,9})\.?,?\s*(\d{4})", t)  # 8 November 2026
    if m and m.group(2)[:3].lower() in MONTHS:
        return date(int(m.group(3)), MONTHS[m.group(2)[:3].lower()], int(m.group(1)))
    m = re.search(r"([A-Za-z]{3,9})\.?\s+(\d{1,2}),?\s*(\d{4})", t)  # Nov 8, 2026
    if m and m.group(1)[:3].lower() in MONTHS:
        return date(int(m.group(3)), MONTHS[m.group(1)[:3].lower()], int(m.group(2)))
    return None


def classify(text: str) -> str:
    title = " ".join([l for l in text.splitlines() if l.strip()][:2]).lower()  # documents name themselves at the top
    for part in (title, text[:600].lower(), text.lower()):
        for doc_type, rx in DOC_TYPE_PATTERNS:
            if re.search(rx, part):
                return doc_type
    return "OTHER"


def _label_values(text: str) -> List[Tuple[str, str]]:
    out = []
    for line in text.splitlines():
        m = re.match(r"\s*([A-Za-z][A-Za-z /'().-]{1,40}?)\s*[:]\s*(.+?)\s*$", line)
        if m:
            out.append((m.group(1).strip().lower().rstrip("."), m.group(2).strip()))
    return out


def extract_fields(doc_type: str, text: str) -> Dict[str, Any]:
    pairs = _label_values(text)
    labels = {**COMMON_LABELS, **LABELS.get(doc_type, {})}
    found: Dict[str, Any] = {}
    for field, names in labels.items():
        for name in names:  # most specific synonym first
            val = next((v for k, v in pairs if k == name), None) or next((v for k, v in pairs if k.startswith(name)), None)
            if val:
                found[field] = val
                break
    low = text.lower()
    fields: Dict[str, Any] = {}
    for k, v in found.items():
        if k in ("amount", "coverage_amount"):
            amt, ccy = parse_amount(v)
            if amt is not None:
                fields[k] = str(amt)
            if ccy:
                fields["currency"] = ccy
        elif k in ("on_board_date",):
            d = parse_date(v)
            if d:
                fields[k] = d.isoformat()
        elif k == "originals_issued":
            m = re.search(r"(\d+)", v) or re.search(r"\b(one|two|three|four)\b", v.lower())
            if m:
                fields[k] = int(m.group(1)) if m.group(1).isdigit() else WORD_NUM[m.group(1)]
        elif k == "issue_date":
            continue
        else:
            fields[k] = v
    if "currency" not in fields:
        ccy = next((c for c in CURRENCIES if re.search(rf"\b{c}\b", text)), None)
        if ccy and doc_type in ("COMMERCIAL_INVOICE", "INSURANCE_DOCUMENT", "DEMAND"):
            fields["currency"] = ccy
    if doc_type == "BILL_OF_LADING":
        fields["clean"] = not re.search(r"\b(unclean|claused|damaged|torn|wet|stained|insufficient packing)\b", low)
        if "signed_by" in fields:
            s = fields["signed_by"].lower()
            fields["signed_by"] = "CARRIER" if "carrier" in s else "MASTER" if "master" in s else "AGENT" if "agent" in s else fields["signed_by"]
        elif re.search(r"as\s+carrier", low):
            fields["signed_by"] = "CARRIER"
        if re.search(r"transhipment\s*(:|-)?\s*(yes|will|effected)", low):
            fields["transhipment"] = True
    imo = re.search(r"IMO\s*:?\s*(\d{7})", text)
    if imo:
        fields["vessel_imo"] = f"IMO{imo.group(1)}"
    return fields


def _originals(text: str) -> Tuple[int, int]:
    low = text.lower()
    m = re.search(r"(\d+|one|two|three|four)\s*(\(\d\))?\s*originals?", low)
    orig = (int(m.group(1)) if m and m.group(1).isdigit() else WORD_NUM.get(m.group(1), 1)) if m else 1
    m = re.search(r"(\d+|one|two|three|four)\s*(\(\d\))?\s*cop(y|ies)", low)
    cop = (int(m.group(1)) if m.group(1).isdigit() else WORD_NUM.get(m.group(1), 0)) if m else 0
    if re.search(r"\b(copy|non[- ]negotiable copy)\b", low[:300]) and not re.search(r"\boriginal\b", low[:300]):
        orig = 0
    return orig, cop


# ---------------------------------------------------------------------------- text extraction
def pdf_text(data: bytes) -> str:
    try:
        from pypdf import PdfReader
    except ImportError:
        return ""
    try:
        return "\n".join((p.extract_text() or "") for p in PdfReader(io.BytesIO(data)).pages)
    except Exception as e:
        logger.warning(f"PDF text extraction failed: {e}")
        return ""


def _ocr_languages(exe: str) -> str:
    """OCR_LANGUAGES (e.g. 'deu+eng'), limited to the language packs actually installed."""
    wanted = os.environ.get("OCR_LANGUAGES", "deu+eng").split("+")
    try:
        have = set(subprocess.run([exe, "--list-langs"], capture_output=True, text=True, timeout=30).stdout.split())
    except Exception:
        have = {"eng"}
    langs = [x for x in wanted if x in have] or ["eng"]
    return "+".join(langs)


def ocr_image(data: bytes, suffix: str = ".png") -> str:
    """OCR via the free Tesseract engine when installed (brew install tesseract / apt install tesseract-ocr)."""
    exe = shutil.which("tesseract")
    if not exe:
        return ""
    with tempfile.NamedTemporaryFile(suffix=suffix) as f:
        f.write(data)
        f.flush()
        try:
            return subprocess.run([exe, f.name, "-", "--psm", "4", "-l", _ocr_languages(exe)],
                                  capture_output=True, text=True, timeout=180).stdout
        except Exception as e:
            logger.warning(f"Tesseract OCR failed: {e}")
            return ""


def ocr_pdf(data: bytes) -> str:
    """Scanned PDF (pages are images): each page rendered at 300 dpi with Poppler, then read by Tesseract."""
    exe = shutil.which("pdftoppm")
    if not exe or not shutil.which("tesseract"):
        return ""
    with tempfile.TemporaryDirectory() as d:
        src = os.path.join(d, "doc.pdf")
        with open(src, "wb") as f:
            f.write(data)
        try:
            subprocess.run([exe, "-r", "300", "-png", src, os.path.join(d, "page")], capture_output=True, timeout=180, check=True)
        except Exception as e:
            logger.warning(f"PDF rendering for OCR failed: {e}")
            return ""
        pages = sorted(p for p in os.listdir(d) if p.startswith("page") and p.endswith(".png"))
        return "\n".join(ocr_image(open(os.path.join(d, p), "rb").read()) for p in pages)


def mime_of(filename: str, data: bytes) -> str:
    if data[:4] == b"%PDF":
        return "application/pdf"
    if data[:3] == b"\xff\xd8\xff":
        return "image/jpeg"
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        return "image/png"
    if data[:4] in (b"II*\x00", b"MM\x00*"):
        return "image/tiff"
    return "text/plain" if (filename or "").lower().endswith((".txt", ".text", "")) else "application/octet-stream"


