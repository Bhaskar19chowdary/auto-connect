    async def run_daily_batch(self, as_of: Optional[date] = None) -> Dict[str, Any]:
        ref_summary = None
        if self.reference.enabled:  # downloads happen before taking the lock: business is never blocked by them
            ref_summary = await asyncio.to_thread(self.reference.refresh)
        async with self._unit_of_work(all_deals=True):
            as_of = as_of or date.today()
            if as_of < self.today:
                raise WorkflowError(f"Business date cannot go back ({self.today} -> {as_of})")
            self.state.business_date = as_of
            actions: List[str] = []
            if ref_summary:  # daily refresh of ECB rates and EU / OFAC lists (cached, ~once a day)
                actions.append("Reference data: " + ", ".join(f"{k} {v.get('state')}" for k, v in ref_summary["sources"].items()))
            for deal in list(self.state.deals.values()):
                try:
                    actions.extend(await self._eod_deal(deal))
                except BusError as e:
                    self._event(deal, "EOD", e.system, "FAILED", e.detail)
                    actions.append(f"{deal.ref}: EOD step failed ({e.code})")
            actions.extend(await self.integration.health_check())
            # KYC reviews due within 30 days -> alert RM once
            due = await self.bus.call(self.agent_id, "tf_customer_master", "periodic_reviews_due", {"within_days": 30},
                                      "KYC_REVIEW_MONITORING")
            for c in due["due"]:
                key = f"KYC_DUE_{c['customer_id']}_{c['kyc_next_review']}"
                if not any(n.get("key") == key for n in self.state.notifications):
                    await self.bus.call(self.agent_id, "tf_email_gateway", "dispatch_message",
                                        {"to": [c["relationship_manager_email"]], "subject": f"KYC review due {c['name']}",
                                         "body": f"Periodic KYC review for {c['name']} is due on {c['kyc_next_review']}.",
                                         "file_stem": key}, "KYC_REVIEW_REMINDER")
                    self.state.notifications.append({"key": key, "customer_id": c["customer_id"], "date": as_of.isoformat()})
                    actions.append(f"KYC review reminder sent for {c['customer_id']}")
            self._save()
            return {"business_date": as_of.isoformat(), "actions": actions}

    async def _reminders(self, deal) -> List[str]:
        """Follow-ups a trade finance officer would make before deadlines and expiries."""
        out: List[str] = []
        t = self.today
        if isinstance(deal, LetterOfCredit):
            for p in deal.presentations:
                if p.status == "DISCREPANT_AWAITING_APPLICANT" and p.applicant_decision_deadline and \
                        0 <= (p.applicant_decision_deadline - t).days <= 1:
                    if await self._notify_client_once(
                            deal, f"WAIVER_REMINDER_{p.presentation_id}", "Reminder: decision on discrepant documents due",
                            f"We still need your decision on the discrepant documents under {deal.ref}. Without your "
                            f"waiver by {p.applicant_decision_deadline} the documents will be refused.",
                            {"Accept discrepancies and pay": self.decision_link(deal.ref, p.presentation_id, "waive"),
                             "Refuse documents": self.decision_link(deal.ref, p.presentation_id, "refuse")}):
                        out.append(f"{deal.ref}: waiver reminder sent")
            if deal.status in ("ISSUED", "PARTIALLY_DRAWN") and 0 <= (deal.terms.expiry_date - t).days <= 30:
                if await self._notify_client_once(
                        deal, "EXPIRY_30D", "Your documentary credit expires soon",
                        f"Credit {deal.ref} expires on {deal.terms.expiry_date} with {deal.currency} {deal.outstanding:,} "
                        f"unused. If the shipment is delayed, request an amendment (extension) before that date."):
                    out.append(f"{deal.ref}: expiry reminder sent")
        else:
            exp = deal.terms.expiry_date
            if deal.status == "ISSUED" and exp and 0 <= (exp - t).days <= 30:
                if await self._notify_client_once(
                        deal, "EXPIRY_30D", "Your guarantee / bond expires soon",
                        f"{deal.ref} expires on {exp}. If the underlying contract runs longer, ask us to extend it in "
                        f"time - beneficiaries often present extend-or-pay demands shortly before expiry."):
                    out.append(f"{deal.ref}: expiry reminder sent")
            for c in getattr(deal, "claims", []):
                if c.status == "AWAITING_PRINCIPAL" and c.principal_deadline and 0 <= (c.principal_deadline - t).days <= 2:
                    if await self._notify_client_once(
                            deal, f"CLAIM_REMINDER_{c.claim_id}", "Reminder: claim under your surety bond",
                            f"Please tell us by {c.principal_deadline} whether you dispute the claim of {c.currency} "
                            f"{c.amount:,}. Without a reply we will pay and debit your account.",
                            {"Acknowledge claim (pay)": self.decision_link(deal.ref, c.claim_id, "acknowledge"),
                             "Dispute claim": self.decision_link(deal.ref, c.claim_id, "dispute")}):
                        out.append(f"{deal.ref}: claim reminder sent")
            for d in getattr(deal, "demands", []):
                if d.status == "SUSPENDED_EXTEND_OR_PAY" and d.suspension_end and 0 <= (d.suspension_end - t).days <= 3:
                    if await self._notify_client_once(
                            deal, f"EOP_REMINDER_{d.demand_id}", "Reminder: extend-or-pay demand",
                            f"Payment of {d.currency} {d.amount:,} under {deal.ref} will be made on {d.suspension_end} "
                            f"unless you agree to extend to {d.requested_new_expiry}.",
                            {"Agree to extension": self.decision_link(deal.ref, d.demand_id, "extend"),
                             "Do not extend (pay if complying)": self.decision_link(deal.ref, d.demand_id, "pay")}):
                        out.append(f"{deal.ref}: extend-or-pay reminder sent")
        return out

    async def _eod_deal(self, deal) -> List[str]:
        if deal.product in ("EXPORT_LC", "COLLECTION"):
            return await self._eod_product(deal)
        out: List[str] = await self._reminders(deal)
        if isinstance(deal, LetterOfCredit):
            for p in deal.presentations:
                if p.status == "ACCEPTED" and p.maturity_date and p.maturity_date <= self.today:
                    await self._pay_drawing(deal, p)
                    out.append(f"{deal.ref}: deferred payment {p.presentation_id} paid at maturity")
                elif p.status == "DISCREPANT_AWAITING_APPLICANT" and p.applicant_decision_deadline and \
                        self.today > p.applicant_decision_deadline:
                    await self._refuse(deal, p, "No waiver received from the applicant within the deadline")
                    out.append(f"{deal.ref}: presentation {p.presentation_id} refused (no waiver)")
            grace = deal.terms.expiry_date + timedelta(days=30)
            if deal.status in ("ISSUED", "PARTIALLY_DRAWN") and self.today > grace and \
                    not any(p.status in ("ACCEPTED", "DISCREPANT_AWAITING_APPLICANT") for p in deal.presentations):
                await self._release_all(deal, "LC", f"Credit expired on {deal.terms.expiry_date}; unutilised balance cancelled")
                deal.status = "EXPIRED"
                await self._notify_client(deal, "Documentary credit expired",
                                          f"{deal.ref} expired on {deal.terms.expiry_date}. The unused balance "
                                          f"{deal.currency} {deal.outstanding:,} was cancelled and your limit released.")
                out.append(f"{deal.ref}: expired and released")
        else:
            claims = deal.demands if isinstance(deal, Guarantee) else deal.claims
            for c in claims:
                if isinstance(c, Demand) and c.status == "SUSPENDED_EXTEND_OR_PAY" and c.suspension_end and c.suspension_end <= self.today:
                    await self._decide_demand(deal, c)
                    out.append(f"{deal.ref}: extend-or-pay suspension ended, demand decided ({c.status})")
                if isinstance(c, SuretyClaim) and c.status == "AWAITING_PRINCIPAL" and c.principal_deadline and \
                        self.today > c.principal_deadline:
                    c.principal_response = "NO RESPONSE - no defences raised"
                    await self._pay_undertaking(deal, c.amount, c.claim_id, "SURETY", deal.terms.obligee, None)
                    c.status = "PAID"
                    out.append(f"{deal.ref}: claim {c.claim_id} paid after principal's deadline")
            if deal.status == "ISSUED" and deal.terms.expiry_date and self.today > deal.terms.expiry_date and \
                    not any(getattr(c, "status", "") in ("SUSPENDED_EXTEND_OR_PAY", "AWAITING_PRINCIPAL", "DISPUTED") for c in claims):
                await self._release_undertaking(deal, f"Expired on {deal.terms.expiry_date} (URDG 758 Art. 25)"
                                                if isinstance(deal, Guarantee) else f"Expired on {deal.terms.expiry_date}")
                out.append(f"{deal.ref}: expired and released")
            elif deal.status == "ISSUED" and deal.commission_paid_until and deal.commission_paid_until <= self.today:
                cust = await self._customer(deal.customer_id)
                amount_eur = await self._eur(deal, deal.outstanding, deal.currency)
                while deal.commission_paid_until <= self.today:
                    q_end = rules.add_quarter(deal.commission_paid_until)
                    fee = rules.aval_commission_for_quarter(amount_eur, cust.risk_rating, self.state.reference.tariff)
                    await self._charge_fee(deal, "AVAL_COMMISSION", fee, q_end)
                    deal.commission_paid_until = q_end
                    out.append(f"{deal.ref}: aval commission EUR {fee} charged until {q_end}")
        return out
