    async def _step_kyc(self, deal) -> bool:
        if self._done(deal, "KYC"):
            return True
        r = await self._call(deal, "KYC", "tf_customer_master", "get_customer", {"customer_id": deal.customer_id},
                             "VERIFY_KYC", record=False)
        if not r["kyc_ok"] and not self._use_approval(deal, "KYC"):
            issue = r.get("kyc_issue") or "KYC not valid according to the customer master"
            self._raise_exception(deal, "KYC", issue, "ISSUE")
            await self._notify_internal(deal, "KYC refresh required", f"Deal on hold: {issue}.")
            await self._notify_client_once(
                deal, "KYC_REQUEST", "Please update your customer information (KYC)",
                f"Before we can process {deal.ref} we need to complete the periodic review of your customer file "
                f"required by the German Money Laundering Act (GwG). Please send us: current commercial register "
                f"extract, list of beneficial owners (Transparenzregister), and ID copies of authorised signatories. "
                f"Your relationship manager is in copy.")
            return False
        self._event(deal, "KYC", "tf_customer_master", "DONE", "KYC valid" if r["kyc_ok"] else "KYC override approved")
        return True

    async def _step_sanctions(self, deal, parties, places, goods="", vessel=None, licence=None, step="SANCTIONS",
                              resume="ISSUE") -> bool:
        if self._done(deal, step):
            return True
        r = await self._call(deal, step, "tf_sanctions_screening", "screen_parties",
                             {"deal_ref": deal.ref, "parties": parties, "places": places, "goods": goods,
                              "vessel_imo": vessel, "export_license_ref": licence}, "SCREEN_TRANSACTION", record=False)
        r.setdefault("alerts", [])
        r.setdefault("case_id", "-")
        if r["result"] in ("BLOCKED", "REVIEW_REQUIRED") and not self._use_approval(deal, "SANCTIONS"):
            reasons = "; ".join(f"{a.get('subject', '')}: {a.get('reason', '')}" for a in r["alerts"]
                                if a.get("decision") in ("HIT", "REVIEW")) or "screening system reports a match"
            self._raise_exception(deal, "SANCTIONS", f"{r['result']} ({r['case_id']}): {reasons}", resume)
            await self._notify_internal(deal, f"Sanctions {r['result']}",
                                        f"Screening case {r['case_id']} requires compliance decision.\n{reasons}")
            return False
        self._event(deal, step, "tf_sanctions_screening", "DONE", f"{r['result']} (case {r['case_id']})",
                    {"case_id": r["case_id"], "alerts": r["alerts"]})
        return True

    async def _step_limit(self, deal, product: str, amount_eur: Decimal, step="CREDIT", resume="ISSUE") -> bool:
        if self._done(deal, step):
            return True
        try:
            r = await self._call(deal, step, "tf_credit_limits", "earmark_limit",
                                 {"customer_id": deal.customer_id, "product": product, "amount_eur": amount_eur,
                                  "deal_ref": deal.ref, "credit_approved": "CREDIT" in deal.approvals},
                                 "RESERVE_CREDIT_LIMIT", record=False)
        except BusError as e:
            if e.code in ("CREDIT_LIMIT_INSUFFICIENT", "NO_FACILITY"):
                self._raise_exception(deal, "CREDIT", e.detail, resume)
                await self._notify_internal(deal, "Credit decision required", e.detail)
                return False
            raise
        self._use_approval(deal, "CREDIT")
        deal.facility_id = r.get("facility_id") or deal.facility_id
        cash = Decimal(str(r.get("cash_collateral_eur") or 0))
        deal.limit_utilisation_eur += Decimal(str(r.get("utilised_eur") if r.get("utilised_eur") is not None else amount_eur - cash))
        deal.cash_collateral_eur += cash
        methods = ", ".join(m.get("method", "?") for m in (r.get("methods") or [])) or "limit system approval"
        self._event(deal, step, "tf_credit_limits", "DONE", f"Limit reserved via {methods}", r)
        return True

    async def _book_contingent(self, deal, prefix: str, amount_eur: Decimal, reverse: bool = False, step="BOOKING"):
        if amount_eur <= 0:
            return
        cust_acc, bank_acc = f"OB_{prefix}_CUSTOMER_LIABILITY", f"OB_{prefix}_BANK_COMMITMENT"
        entry = ({"debit": bank_acc, "credit": cust_acc} if reverse else {"debit": cust_acc, "credit": bank_acc})
        entry.update({"amount": amount_eur, "narrative": f"{'Release' if reverse else 'Book'} contingent {deal.ref}"})
        before = self._contingent_open(deal, prefix)
        await self._post(deal, step, [entry])
        deal.contingent_booked_eur = before - amount_eur if reverse else before + amount_eur

    async def _release_all(self, deal, prefix: str, reason: str):
        """Releases the remaining limit, cash collateral and contingent booking of a deal."""
        r = await self._call(deal, "RELEASE", "tf_credit_limits", "release_limit", {"deal_ref": deal.ref},
                             "RELEASE_CREDIT_LIMIT")
        remaining = self._contingent_open(deal, prefix)
        await self._book_contingent(deal, prefix, remaining, reverse=True, step="RELEASE")
        deal.limit_utilisation_eur = D0
        deal.cash_collateral_eur = D0
        self._event(deal, "RELEASE", self.agent_id, "DONE", reason, r)

    def _contingent_open(self, deal, prefix: str) -> Decimal:
        if deal.contingent_booked_eur is not None:
            return deal.contingent_booked_eur
        bank_acc = f"OB_{prefix}_BANK_COMMITMENT"  # deals booked before tracking existed: derive once from the ledger
        total = D0
        for e in self.state.ledger:
            if e.deal_ref != deal.ref:
                continue
            if e.credit_account == bank_acc:
                total += e.amount
            elif e.debit_account == bank_acc:
                total -= e.amount
        return total

    async def _debit_customer_for_payment(self, deal, amount: Decimal, currency: str, narrative: str,
                                          payee_entries_ccy: List[Dict[str, Any]], step: str,
                                          fees_eur: Decimal = D0) -> Dict[str, Any]:
        """
        Debits the customer (applicant/principal) for a payment made by the bank in `currency`.
        Converts via FX position accounts when needed. If the customer cannot fund it (incl. the fees that
        follow), books an automatic post-financing loan when agreed; otherwise the account runs into
        unauthorised excess and operations gets a follow-up item (the bank's payment never waits for funding).
        """
        cust = await self._customer(deal.customer_id)
        amount_eur = await self._eur(deal, amount, currency)
        info: Dict[str, Any] = {"amount_eur": amount_eur, "post_financing_eur": D0}
        bal = await self.bus.call(self.agent_id, "tf_core_ledger", "account_balance",
                                  {"account_id": cust.current_account_iban}, "CHECK_FUNDS")  # ledger is the record
        shortfall = amount_eur + fees_eur - Decimal(str(bal["free_balance"]))
        if shortfall > 0 and not cust.auto_post_financing:
            exc = ExceptionItem(deal_ref=deal.ref, category="OPERATIONS", resume_step="FOLLOW_UP",
                                reason=f"Customer cannot fund {amount_eur} EUR (shortfall {rules.money(shortfall)}); no standing "
                                       f"post-financing agreement - account in unauthorised excess, arrange financing or recovery")
            self.state.exceptions[exc.exception_id] = exc
            deal.open_exceptions.append(exc.exception_id)
            self._event(deal, step, self.agent_id, "ESCALATED", exc.reason, {"exception_id": exc.exception_id})
            await self._notify_internal(deal, "Unfunded payment - action required", exc.reason)
        elif shortfall > 0:
            await self._post(deal, step, [{"debit": "GL_IMPORT_LOANS", "credit": cust.current_account_iban,
                                           "amount": rules.money(shortfall),
                                           "narrative": f"Post-financing loan {deal.ref}"}], allow_overdraft_excess=True)
            info["post_financing_eur"] = rules.money(shortfall)
            if isinstance(deal, LetterOfCredit):
                deal.import_loan_outstanding += rules.money(shortfall)
            await self._notify_internal(deal, "Post-financing loan booked",
                                        f"Payment of {amount_eur} EUR exceeded available funds; loan of "
                                        f"{rules.money(shortfall)} EUR booked automatically under the customer's standing agreement.")
        entries = []
        if currency == "EUR":
            entries.append({"debit": cust.current_account_iban, "credit": "GL_FX_POSITION_EUR", "amount": amount_eur,
                            "narrative": narrative})
            for pe in payee_entries_ccy:
                entries.append({"debit": "GL_FX_POSITION_EUR", **pe})
        else:
            entries.append({"debit": cust.current_account_iban, "credit": "GL_FX_POSITION_EUR", "amount": amount_eur,
                            "narrative": f"{narrative} (EUR equivalent)"})
            for pe in payee_entries_ccy:
                entries.append({"debit": f"GL_FX_POSITION_{currency}", **pe})
        await self._post(deal, step, entries, allow_overdraft_excess=True)
        return info

