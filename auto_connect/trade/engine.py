    def _event(self, deal, step: str, system: str, outcome: str, detail: str = "", data: Optional[dict] = None):
        deal.history.append(WorkflowEvent(business_date=self.today, step=step, system=system, outcome=outcome,
                                          detail=detail, data=to_jsonable(data or {})))

    @staticmethod
    def _use_approval(deal, category: str) -> bool:
        """An approval from the exception queue is used once (it does not pre-approve later events)."""
        if category in deal.approvals:
            deal.approvals.remove(category)
            return True
        return False

    def _done(self, deal, step: str) -> bool:
        return any(e.step == step and e.outcome == "DONE" for e in deal.history)

    def _did(self, deal, step: str, system: str) -> bool:
        """A system call of `step` already succeeded in an earlier attempt (issuance resumed after a failure)."""
        return any(e.step == step and e.system == system and e.outcome == "OK" for e in deal.history)

    async def _call(self, deal, step: str, target: str, op: str, params: Dict[str, Any], intent: str,
                    record: bool = True) -> Dict[str, Any]:
        correlation_id.set(deal.ref)  # every system call of this deal carries its reference (gateway tracing)
        try:
            data = await self.bus.call(self.agent_id, target, op, params, intent)
        except BusError as e:
            self._event(deal, step, target, "FAILED", f"{e.code}: {e.detail}", {**(e.data or {}), "status_code": e.status_code})
            raise
        if record:
            self._event(deal, step, target, "OK", intent, {"response": data} if len(json.dumps(to_jsonable(data))) < 4000 else {})
        return data

    def _raise_exception(self, deal, category: str, reason: str, resume_step: str) -> ExceptionItem:
        exc = ExceptionItem(deal_ref=deal.ref, category=category, reason=reason, resume_step=resume_step)
        self.state.exceptions[exc.exception_id] = exc
        deal.open_exceptions.append(exc.exception_id)
        deal.status = f"ON_HOLD_{category}"
        self._event(deal, resume_step, self.agent_id, "ESCALATED", f"{category}: {reason}", {"exception_id": exc.exception_id})
        return exc

    async def _notify_internal(self, deal, subject: str, body: str):
        try:
            cust = await self._customer(deal.customer_id)
        except (WorkflowError, BusError):
            cust = None
        to = [cust.relationship_manager_email] if cust else ["trade-ops@bank.local"]
        try:
            await self._call(deal, "INTERNAL_ALERT", "tf_email_gateway", "dispatch_message",
                             {"to": to, "subject": f"[{deal.ref}] {subject}", "body": body,
                              "file_stem": f"{deal.ref}_INTERNAL_{len(deal.history):03d}"}, "ALERT_OPERATIONS")
        except BusError:
            pass

    async def _notify_client(self, deal, subject: str, body: str, actions: Optional[Dict[str, str]] = None):
        try:
            await self._call(deal, "NOTIFY_CLIENT", "tf_client_portal", "notify_client",
                             {"customer_id": deal.customer_id, "deal_ref": deal.ref, "subject": subject,
                              "body": body, "actions": actions or {}}, "NOTIFY_CLIENT")
        except BusError:
            pass  # notification failure is logged in history; never blocks the deal

    async def _notify_client_once(self, deal, key: str, subject: str, body: str, actions: Optional[Dict[str, str]] = None):
        """Sends a client message only once per key (reminders run in every end-of-day batch)."""
        key = f"{deal.ref}:{key}"
        if any(n.get("key") == key for n in self.state.notifications):
            return False
        await self._notify_client(deal, subject, body, actions)
        self.state.notifications.append({"key": key, "deal_ref": deal.ref, "date": self.today.isoformat()})
        return True

    async def _email_counterparty(self, deal, party: Party, subject: str, body: str) -> bool:
        """Emails a beneficiary / obligee directly when their address is known (else: letter by post, archived)."""
        if not party.email:
            self._event(deal, "COUNTERPARTY_NOTICE", self.agent_id, "OK",
                        f"No email for {party.name}: notice dispatched by letter (copy archived)")
            return False
        try:
            await self._call(deal, "COUNTERPARTY_NOTICE", "tf_email_gateway", "dispatch_message",
                             {"to": [party.email], "subject": f"[{deal.ref}] {subject}",
                              "body": body + f"\n\nKind regards\nTrade Finance Operations\n{settings.bank_name()}",
                              "file_stem": f"{deal.ref}_TO_{''.join(c for c in party.name if c.isalnum())[:20]}_{len(deal.history):03d}"},
                             "NOTIFY_COUNTERPARTY")
            return True
        except BusError:
            return False

    async def _acknowledge(self, deal, product_name: str):
        """Human-like acknowledgment when an application cannot be completed straight away."""
        if deal.status in ("ON_HOLD_SANCTIONS", "ON_HOLD_CREDIT", "ON_HOLD_LEGAL", "ON_HOLD_OPERATIONS"):
            # never disclose a sanctions reason to the client (tipping-off); credit decisions are pending internally
            await self._notify_client_once(
                deal, "ACK", f"Your {product_name} application {deal.ref} is being processed",
                f"Thank you for your {product_name} application. It has been received under reference {deal.ref} "
                f"and is undergoing our internal review. We will inform you as soon as it is completed.")

    async def _eur(self, deal, amount: Decimal, currency: str) -> Decimal:
        if currency == "EUR":
            return rules.money(amount)
        r = await self._call(deal, "FX", "tf_market_data", "convert",
                             {"amount": amount, "from_currency": currency, "to_currency": "EUR"}, "FX_CONVERSION", record=False)
        return Decimal(r["amount"])

    async def _post(self, deal, step: str, entries: List[Dict[str, Any]], allow_overdraft_excess: bool = False,
                    value_date: Optional[date] = None):
        return await self._call(deal, step, "tf_core_ledger", "post_entries",
                                {"deal_ref": deal.ref, "entries": entries, "allow_overdraft_excess": allow_overdraft_excess,
                                 "value_date": value_date or self.today}, "POST_ACCOUNTING")

    async def _charge_fee(self, deal, fee_type: str, amount_eur: Decimal, period_end: Optional[date] = None,
                          allow_overdraft_excess: bool = True, once: bool = False):
        """once=True: one-off fees of a step that may be resumed after a failure are never charged twice."""
        if amount_eur <= 0 or (once and any(f.fee_type == fee_type for f in deal.fees)):
            return
        cust = await self._customer(deal.customer_id)
        await self._post(deal, f"FEE_{fee_type}", [{"debit": cust.current_account_iban, "credit": "GL_FEE_INCOME_EUR",
                                                     "amount": amount_eur, "narrative": f"{fee_type} {deal.ref}"}],
                         allow_overdraft_excess=allow_overdraft_excess)
        deal.fees.append(FeeCharge(date=self.today, fee_type=fee_type, amount=amount_eur, period_end=period_end))

    async def _swift(self, deal, step: str, mt_type: str, receiver_bic: str, fin_text: str) -> str:
        r = await self._call(deal, step, "tf_swift_gateway", "release_message",
                             {"deal_ref": deal.ref, "mt_type": mt_type, "receiver_bic": receiver_bic, "fin_text": fin_text},
                             f"SEND_MT{mt_type}")
        deal.swift_message_ids.append(r["message_id"])
        return r["message_id"]

    async def _pay_bank(self, deal, step: str, ref: str, related_ref: str, value_date: date, currency: str,
                        amount: Decimal, creditor_bic: str, correspondent_bic: str):
        """Bank-to-bank cover payment: ISO 20022 pacs.009 (CBPR+), or MT202 when PAYMENT_MESSAGE_FORMAT=MT."""
        if settings.payment_message_format() == "MT":
            fin = swift.mt202(ref, related_ref, value_date, currency, amount, creditor_bic, correspondent_bic, settings.bank_bic())
            await self._swift(deal, step, "202", correspondent_bic, fin)
        else:
            xml = iso20022.pacs009(ref, related_ref, value_date, currency, amount, creditor_bic, correspondent_bic,
                                   settings.bank_bic())
            await self._swift(deal, step, "pacs.009", correspondent_bic, xml)

    async def _archive(self, deal, doc_type: str, title: str, content: str):
        try:
            await self._call(deal, "ARCHIVE", "tf_document_archive", "store_document",
                             {"deal_ref": deal.ref, "doc_type": doc_type, "title": title, "content": content},
                             "ARCHIVE_DOCUMENT", record=False)
        except BusError:
            pass

    def decision_link(self, ref: str, item: str, decision: str) -> str:
        base = os.environ.get("PUBLIC_BASE_URL", "http://127.0.0.1:8088").rstrip("/")
        return f"{base}/portal/decision?ref={ref}&item={item}&decision={decision}&sig={self.sign(ref, item, decision)}"

    def sign(self, ref: str, item: str, decision: str) -> str:
        msg = f"{ref}|{item}|{decision}".encode()
        return hmac.new(self.state.portal_secret.encode(), msg, hashlib.sha256).hexdigest()[:24]

    def verify(self, ref: str, item: str, decision: str, sig: str) -> bool:
        return hmac.compare_digest(self.sign(ref, item, decision), sig or "")

    def get_deal(self, ref: str):
        deal = self.state.deals.get(ref)
        if not deal:
            raise WorkflowError(f"Unknown deal reference {ref}")
        if getattr(self, "_touched", None) is not None:
            self._touched.add(ref)
        return deal

    def _save(self):
        if not getattr(self.store, "in_transaction", False):  # inside an action the unit of work commits
            self.store.save()

    @contextlib.asynccontextmanager
    async def _unit_of_work(self, all_deals: bool = False):
        """One business action = one transaction: everything it booked is stored, or nothing (rollback).
        An action started inside another one (e.g. issuing the LC of an application) joins the outer transaction."""
        if _IN_UNIT_OF_WORK.get():
            yield
            return
        token = _IN_UNIT_OF_WORK.set(True)
        try:
            async with self._transaction(all_deals):
                yield
        finally:
            _IN_UNIT_OF_WORK.reset(token)
        await self.dispatch_outbox()

    @contextlib.asynccontextmanager
    async def _transaction(self, all_deals: bool = False):
        async with self.lock:
            self.store.begin()
            self._touched = None if all_deals else set()
            self._cust_cache = {}
            self.bus.compensations = []
            try:
                yield
            except BaseException:
                done, self.bus.compensations = self.bus.compensations or [], None
                self.store.rollback()  # queued emails / SWIFT messages disappear with it: nothing was sent
                if done:
                    await self._compensate(done)  # undo what external systems already booked
                raise
            else:
                self.bus.compensations = None
                self.store.commit(self._touched)
            finally:
                self._touched = None
                self._cust_cache = None
                self.bus.compensations = None

    def _pending_outbox(self) -> set:
        """Ids waiting to be sent, maintained incrementally (no scan of the whole outbox per action)."""
        st = self.state
        if getattr(self, "_ob_state", None) is not st:  # first use, or the books were reloaded / rolled back
            self._ob_state, self._ob_seen = st, 0
            self._ob_pending = set()
        n_new = len(st.outbox) - self._ob_seen
        if n_new > 0:
            for k in reversed(st.outbox):  # only the newly queued items, read from the end
                if n_new == 0:
                    break
                n_new -= 1
                if st.outbox[k]["status"] in ("PENDING", "FAILED"):
                    self._ob_pending.add(k)
            self._ob_seen = len(st.outbox)
        return self._ob_pending

    async def _compensate(self, done: List[Dict[str, Any]]):
        """The action failed after external systems had booked: reverse those bookings (newest first). What cannot
        be reversed automatically becomes a reconciliation task for operations - nothing is silently left behind."""
        problems = []
        for c in reversed(done):
            if c["operation"] is None:
                problems.append(f"{c['target']}.{c['undoes']} cannot be reversed automatically ({c['params']})")
                continue
            try:
                await self.bus.call(c["sender"], c["target"], c["operation"], c["params"], "COMPENSATION", _from_outbox=True)
            except Exception as e:
                problems.append(f"{c['target']}.{c['operation']} (undo {c['undoes']}) failed: {e}")
        if problems:
            ref = next((c["params"].get("deal_ref") for c in done if c["params"].get("deal_ref")), "UNKNOWN")
            exc = ExceptionItem(deal_ref=ref, category="OPERATIONS", resume_step="FOLLOW_UP",
                                reason=("Action failed after external systems had booked - manual reconciliation needed: "
                                        + " | ".join(problems))[:900])
            self.state.exceptions[exc.exception_id] = exc
            self.store.save(dirty_deals=set())

    async def dispatch_outbox(self, max_attempts: int = 5) -> Dict[str, int]:
        """Sends what committed actions queued (emails, SWIFT releases). At-least-once: a crash after the commit
        leaves the items PENDING and they go out on the next dispatch; failures are retried."""
        from ..notifications import send_email

        pending = self._pending_outbox()
        due = sorted((self.state.outbox[k] for k in pending), key=lambda i: i["created_at"])
        stats = {"sent": 0, "failed": 0}
        for item in due:
            item["attempts"] += 1
            try:
                if item["kind"] == "SWIFT":
                    item["result"] = self.systems["tf_swift_gateway"].release(item["payload"]["message_id"])
                elif item["kind"] == "BUS":  # real SWIFT / email system, called now that the action is committed
                    pl = item["payload"]
                    item["result"] = await self.bus.call(pl["sender"], pl["target"], pl["operation"], pl["params"],
                                                         pl.get("intent"), _from_outbox=True)
                else:
                    r = await asyncio.to_thread(send_email, **item["payload"])
                    if r.get("relay_error"):
                        raise RuntimeError(f"SMTP relay failed: {r['relay_error']}")
                    item["result"] = r.get("eml_file")
                item["status"], item["sent_at"], item["error"] = "SENT", rules_now(), None
                pending.discard(item["id"])
                stats["sent"] += 1
            except Exception as e:  # stays in the outbox, retried by the next dispatch / end-of-day batch
                item["status"], item["error"] = "FAILED", f"{type(e).__name__}: {e}"[:300]
                if item["attempts"] >= max_attempts:
                    pending.discard(item["id"])  # stays FAILED in the outbox for operations to see
                stats["failed"] += 1
            finally:
                self.store.mark("outbox", item["id"])
        if due and not getattr(self.store, "in_transaction", False):
            self.store.save(dirty_deals=set())
        return stats

    def sync(self) -> bool:
        """Picks up changes another application server committed (shared database)."""
        if self.lock.locked():
            return False
        return self.store.refresh_if_changed()

    async def refresh_reference_data(self, force: bool = False) -> Dict[str, Any]:
        return await asyncio.to_thread(self.reference.refresh, force)

    async def _customer(self, customer_id: str) -> Customer:
        """Customer master data comes from the customer master system (the official record), cached for one action.
        Trade-finance standing instructions (pre-agreed waivers, post-financing, collateral consent) stay with the
        engine's own client profile."""
        cache = getattr(self, "_cust_cache", None)
        if cache is not None and customer_id in cache:
            return cache[customer_id]
        try:
            r = await self.bus.call(self.agent_id, "tf_customer_master", "get_customer", {"customer_id": customer_id},
                                    "LOOKUP_CUSTOMER")
        except BusError as e:
            if e.status_code == 404:
                raise WorkflowError(f"Unknown customer {customer_id}")
            raise
        master = r.get("customer") or {}
        local = self.state.customers.get(customer_id)
        data = local.model_dump(mode="json") if local else {
            "customer_id": customer_id, "email": settings.default_client_email(),
            "kyc_next_review": (self.today + timedelta(days=365)).isoformat()}
        data.update({k: v for k, v in master.items() if k in Customer.model_fields and v not in (None, "")})
        if not data.get("current_account_iban"):
            raise WorkflowError(f"Customer master has no settlement account for {customer_id}")
        cust = Customer.model_validate(data)
        if cache is not None:
            cache[customer_id] = cust
        return cust

    def _attach_files(self, deal, item_id: str, files, uploaded_by: Optional[str]):
        """Keeps the original uploaded documents in the database (record-keeping, disputes, audits). Saved in the same
        transaction as the action, with a SHA-256 fingerprint that proves later that a file was not changed."""
        from ..document_reader import mime_of

        for name, data in files or []:
            meta = {"file_id": new_id_file(), "deal_ref": deal.ref, "item_id": item_id, "filename": name,
                    "mime": mime_of(name, data), "size": len(data), "sha256": hashlib.sha256(data).hexdigest(),
                    "uploaded_at": rules_now(), "uploaded_by": uploaded_by}
            self.store.save_file(meta, data)
            deal.attachments.append(meta)
            self._event(deal, "DOCUMENT_ARCHIVED", self.agent_id, "DONE",
                        f"Original '{name}' stored ({len(data):,} bytes, SHA-256 {meta['sha256'][:12]}...)",
                        {"file_id": meta["file_id"], "item_id": item_id})

