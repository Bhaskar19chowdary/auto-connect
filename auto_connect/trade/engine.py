    async def resolve_exception(self, exception_id: str, approve: bool, resolved_by: str, note: str = "",
                                approvals_required: int = 1) -> Dict[str, Any]:
        """approvals_required > 1: four-eyes - the approval takes effect only when that many different users
        (none of them the deal's maker) have approved; a single rejection decides."""
        async with self._unit_of_work():
            exc = self.state.exceptions.get(exception_id)
            if not exc or exc.status != "OPEN":
                raise WorkflowError("Unknown or already resolved exception")
            deal = self.get_deal(exc.deal_ref)
            if approvals_required > 1 and deal.created_by and resolved_by == deal.created_by:
                raise WorkflowError(f"Maker-checker: {resolved_by} entered {deal.ref} and cannot decide its exception")
            if approve and approvals_required > 1:
                if resolved_by in exc.approvers:
                    raise WorkflowError(f"Four-eyes: {resolved_by} already approved - a second person must approve")
                exc.approvers.append(resolved_by)
                self.store.mark("exceptions", exception_id)
                if len(exc.approvers) < approvals_required:
                    self._event(deal, "EXCEPTION", resolved_by, "FIRST_APPROVAL",
                                f"{exc.category}: approval {len(exc.approvers)}/{approvals_required} - {note}")
                    self._save()
                    return {"exception": exc, "deal": deal, "pending_approvals": approvals_required - len(exc.approvers)}
            exc.status = "APPROVED" if approve else "REJECTED"
            self.store.mark("exceptions", exception_id)
            exc.resolved_by = resolved_by
            exc.resolution_note = note
            if exception_id in deal.open_exceptions:
                deal.open_exceptions.remove(exception_id)
            self._event(deal, "EXCEPTION", resolved_by, exc.status, f"{exc.category}: {note}")
            step = exc.resume_step or "ISSUE"
            if approve:
                deal.approvals.append(exc.category)
                await self._resume(deal, step)
            else:
                await self._reject(deal, step, exc)
            self._save()
            return {"exception": exc, "deal": deal}

    async def _resume(self, deal, step: str):
        if await self._resume_product(deal, step):
            return
        if step == "ISSUE":
            deal.status = "RECEIVED"
            if isinstance(deal, LetterOfCredit):
                await self._run_issuance(deal, self._lc_issuance)
            elif isinstance(deal, Guarantee):
                await self._run_issuance(deal, self._guarantee_issuance)
            else:
                await self._run_issuance(deal, self._surety_issuance)
        elif step == "FOLLOW_UP":
            pass  # information item for operations; the deal itself was already completed
        elif step.startswith("AMEND:"):
            amd = next(a for a in deal.amendments if a.number == int(step.split(":")[1]))
            deal.status = "ISSUED"
            await self._process_lc_amendment(deal, amd)
        elif step.startswith("AMEND_UNDERTAKING:"):
            n = int(step.split(":")[1])
            amd = next(a for a in deal.amendments if a.number == n)
            deal.amendments.remove(amd)
            deal.status = "ISSUED"
            await self._amend_undertaking(deal, amd.changes, "GUARANTEE" if isinstance(deal, Guarantee) else "SURETY",
                                          "GTEE" if isinstance(deal, Guarantee) else "SURETY")
        elif step.startswith("PRESENTATION:"):
            pid = step.split(":")[1]
            p = next(x for x in deal.presentations if x.presentation_id == pid)
            deal.status = self._lc_open_status(deal)
            await self._examine_presentation(deal, p)
        elif step.startswith("CLAIM:"):
            cid = step.split(":")[1]
            c = next(x for x in deal.claims if x.claim_id == cid)
            deal.status = "ISSUED"
            await self._pay_undertaking(deal, c.amount, c.claim_id, "SURETY", deal.terms.obligee, None)
            c.status = "PAID"
        else:
            deal.status = "ISSUED"

    async def _reject(self, deal, step: str, exc: ExceptionItem):
        if await self._reject_product(deal, step, exc):
            return
        if step == "ISSUE":
            try:
                await self._call(deal, "RELEASE", "tf_credit_limits", "release_limit", {"deal_ref": deal.ref}, "RELEASE_CREDIT_LIMIT")
            except BusError:
                pass
            deal.status = "REJECTED"
            await self._notify_client(deal, "Application declined",
                                      f"We are unable to proceed with {deal.ref}. Your relationship manager will contact you.")
        elif step.startswith("AMEND"):
            n = int(step.split(":")[1])
            for a in deal.amendments:
                if a.number == n:
                    a.status = "REJECTED"
            deal.status = "ISSUED"
            await self._notify_client(deal, "Amendment declined", f"The requested amendment to {deal.ref} could not be approved.")
        elif step.startswith("PRESENTATION:") and exc.category != "SANCTIONS":
            pid = step.split(":")[1]
            deal.presentations = [x for x in deal.presentations if x.presentation_id != pid]
            deal.status = self._lc_open_status(deal)
            self._event(deal, step, exc.resolved_by or self.agent_id, "DONE",
                        "Automatically read presentation discarded by the document checker - documents to be re-presented")
        elif step.startswith("PRESENTATION:"):
            pid = step.split(":")[1]
            p = next(x for x in deal.presentations if x.presentation_id == pid)
            p.discrepancies.append(Discrepancy(code="SANCTIONS", rule="EU/UN/US sanctions law",
                                               description="Payment prohibited by applicable sanctions regulations"))
            deal.status = "BLOCKED_SANCTIONS"
            p.status = "REFUSED"
            self._event(deal, step, self.agent_id, "DONE", "Payment blocked for sanctions reasons; funds frozen")
        elif step.startswith("CLAIM:"):
            cid = step.split(":")[1]
            c = next(x for x in deal.claims if x.claim_id == cid)
            c.status = "REJECTED"
            deal.status = "ISSUED"
            await self._notify_client(deal, "Claim rejected", f"Following legal review the claim {cid} under {deal.ref} was rejected.")

