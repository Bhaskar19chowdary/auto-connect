    BusError = BusError

    def __init__(self, store: StateStore, vault, mesh, executor):
        self.store = store
        self.mesh = mesh
        self.systems = register_systems(store, vault, mesh, executor)
        self.bus = next(iter(self.systems.values())).bus
        from .reference_feeds import ReferenceDataService

        self.reference = ReferenceDataService(settings.reference_data_dir(), settings.live_reference_data())
        for system in self.systems.values():
            system.reference = self.reference
        mesh.register_agent(self._agent_card())
        self.lock = asyncio.Lock()
        from .integration import IntegrationManager

        self.integration = IntegrationManager(self)

