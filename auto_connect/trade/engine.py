    async def apply_guarantee(self, terms: GuaranteeTerms, created_by: Optional[str] = None) -> Guarantee:
        async with self._unit_of_work():
            await self._customer(terms.applicant_customer_id)  # unknown customers are refused by the customer master
            self._check_currency(terms.currency)
            ref = self.state.next_ref("GTE")
            g = Guarantee(ref=ref, customer_id=terms.applicant_customer_id, status="RECEIVED", contingent_booked_eur=D0, currency=terms.currency,
                          amount=rules.money(terms.amount), outstanding=rules.money(terms.amount), terms=terms)
            g.created_by = created_by
            self.state.deals[ref] = g
            self._event(g, "RECEIVED", self.agent_id, "DONE", "Guarantee application received")
            await self._run_issuance(g, self._guarantee_issuance)
            await self._acknowledge(g, "guarantee")
            self._save()
            return g

    async def _guarantee_issuance(self, g: Guarantee):
        t = g.terms
        cust = await self._customer(g.customer_id)
        if not self._done(g, "VALIDATION"):
            errors, warnings = rules.validate_guarantee_application(t, self.today)
            if errors and not self._use_approval(g, "DATA_QUALITY"):
                cat = "CREDIT" if any(e.code == "OPEN_ENDED" for e in errors) and len(errors) == 1 else "DATA_QUALITY"
                if not (cat == "CREDIT" and "CREDIT" in g.approvals):
                    self._raise_exception(g, cat, " | ".join(f"{e.code}: {e.description}" for e in errors), "ISSUE")
                    if cat == "DATA_QUALITY":
                        await self._notify_client(g, "Your guarantee application needs correction",
                                                  "We could not issue your guarantee because:\n" +
                                                  "\n".join(f"- {e.description} ({e.rule})" for e in errors))
                    return
            self._event(g, "VALIDATION", self.agent_id, "DONE", "Application checks passed", {"warnings": warnings})
        if not await self._step_kyc(g):
            return
        parties = [{"name": cust.name, "country": cust.country, "address": cust.address, "role": "applicant"},
                   {"name": t.beneficiary.name, "country": t.beneficiary.country, "address": t.beneficiary.address,
                    "role": "beneficiary"}]
        if t.beneficiary_bank_bic:
            parties.append({"name": f"Bank {t.beneficiary_bank_bic}", "country": t.beneficiary_bank_bic[4:6], "role": "beneficiary bank"})
        if not await self._step_sanctions(g, parties, [t.beneficiary.address], t.underlying_transaction):
            return
        amount_eur = await self._eur(g, g.amount, t.currency)
        if not await self._step_limit(g, "GUARANTEE", amount_eur):
            return
        if not self._done(g, "ISSUANCE"):
            g.issue_date = self.today
            tariff = self.state.reference.tariff
            await self._charge_fee(g, "GUARANTEE_ISSUANCE", tariff["guarantee_issuance_flat"], once=True)
            q_end = g.commission_paid_until or rules.add_quarter(self.today)
            await self._charge_fee(g, "AVAL_COMMISSION", rules.aval_commission_for_quarter(amount_eur, cust.risk_rating, tariff),
                                   q_end, once=True)
            g.commission_paid_until = q_end
            if self._contingent_open(g, "GTEE") == 0:
                await self._book_contingent(g, "GTEE", amount_eur)
            wording = rules.guarantee_wording(g, cust.name, settings.bank_name())
            await self._archive(g, "GUARANTEE_TEXT", f"{g.ref}_guarantee.txt", wording)
            if t.beneficiary_bank_bic:
                form = "STBY" if t.guarantee_type == "STANDBY_LC" else "GUAR"
                rules_tag = "ISPR" if form == "STBY" else "URDG"
                fin = swift.mt760(g, cust, t.beneficiary, t.beneficiary_bank_bic, settings.bank_bic(), wording,
                                  form=form, rules=rules_tag, underlying=t.underlying_transaction)
                if not self._did(g, "ISSUANCE", "tf_swift_gateway"):
                    await self._swift(g, "ISSUANCE", "760", t.beneficiary_bank_bic, fin)
                channel = (f"counter-guarantee by SWIFT MT760 (ICCO) to {t.beneficiary_bank_bic}, local guarantee requested"
                           if t.counter_guarantee else f"SWIFT MT760 to {t.beneficiary_bank_bic}")
            else:
                channel = "original deed dispatched to the beneficiary by courier"
            g.status = "ISSUED"
            self._event(g, "ISSUANCE", self.agent_id, "DONE", f"Guarantee issued ({channel})")
            await self._notify_client(g, "Guarantee issued",
                                      f"{t.guarantee_type.replace('_', ' ').title()} guarantee {g.ref} for {t.currency} "
                                      f"{g.amount:,} in favour of {t.beneficiary.name} was issued ({channel}). "
                                      f"Expiry: {t.expiry_date}. Commission charged until {q_end}.")

    async def amend_guarantee(self, ref: str, changes: Dict[str, Any]) -> Guarantee:
        async with self._unit_of_work():
            g = self.get_deal(ref)
            if not isinstance(g, Guarantee) or g.status != "ISSUED":
                raise WorkflowError(f"{ref} cannot be amended in status {getattr(g, 'status', '?')}")
            await self._amend_undertaking(g, changes, "GUARANTEE", "GTEE")
            self._save()
            return g

    async def _amend_undertaking(self, deal, changes: Dict[str, Any], product: str, prefix: str):
        n = len(deal.amendments) + 1
        step = f"AMENDMENT_{n}"
        delta = Decimal(str(changes.get("amount_delta", "0")))
        new_expiry = date.fromisoformat(str(changes["expiry_date"])) if changes.get("expiry_date") else None
        if new_expiry and new_expiry <= self.today:
            raise WorkflowError("New expiry date must be in the future")
        if deal.outstanding + delta <= 0:
            raise WorkflowError("Amendment would reduce the amount to zero - use release instead")
        delta_eur = await self._eur(deal, abs(delta), deal.currency) if delta else D0
        if delta > 0:
            if not await self._step_limit(deal, product, delta_eur, step=f"{step}_CREDIT", resume=f"AMEND_UNDERTAKING:{n}"):
                deal.amendments.append(Amendment(number=n, date=self.today, changes=to_jsonable(changes), status="PENDING_APPROVAL"))
                return
            await self._book_contingent(deal, prefix, delta_eur, step=step)
        elif delta < 0:
            await self._call(deal, step, "tf_credit_limits", "release_limit", {"deal_ref": deal.ref, "amount_eur": delta_eur},
                             "RELEASE_CREDIT_LIMIT")
            deal.limit_utilisation_eur = max(D0, deal.limit_utilisation_eur - delta_eur)
            await self._book_contingent(deal, prefix, delta_eur, reverse=True, step=step)
        await self._charge_fee(deal, f"{product}_AMENDMENT", self.state.reference.tariff["lc_amendment_flat"])
        prev = {"amount": deal.amount, "expiry_date": deal.terms.expiry_date}
        deal.amount += delta
        deal.outstanding += delta
        if new_expiry:
            deal.terms.expiry_date = new_expiry
        receiver = getattr(deal.terms, "beneficiary_bank_bic", None)
        if receiver:
            fin = swift.mt767(deal, n, {"amount_delta": delta or None, "expiry_date": new_expiry,
                                        "narrative": changes.get("narrative")}, self.today, receiver, settings.bank_bic())
            await self._swift(deal, step, "767", receiver, fin)
        deal.amendments.append(Amendment(number=n, date=self.today, changes=to_jsonable(changes), status="EFFECTIVE",
                                         previous=to_jsonable(prev)))
        deal.status = "ISSUED"
        self._event(deal, step, self.agent_id, "DONE", f"Amendment {n} effective", to_jsonable(changes))
        await self._notify_client(deal, f"Amendment {n} effective",
                                  f"{deal.ref} amended: amount now {deal.currency} {deal.amount:,}, expiry {deal.terms.expiry_date}.")

    async def present_demand(self, ref: str, demand: Demand, files=None, uploaded_by: Optional[str] = None) -> Guarantee:
        async with self._unit_of_work():
            g = self.get_deal(ref)
            if not isinstance(g, Guarantee) or g.status not in ("ISSUED", "DEMAND_UNDER_EXAMINATION"):
                raise WorkflowError(f"{ref} cannot receive a demand in status {getattr(g, 'status', '?')}")
            demand.examination_deadline = add_banking_days(demand.presentation_date, 5)
            g.demands.append(demand)
            self._attach_files(g, demand.demand_id, files, uploaded_by)
            g.status = "DEMAND_UNDER_EXAMINATION"
            self._event(g, f"DEMAND_{demand.demand_id}", "beneficiary", "DONE",
                        f"Demand for {demand.currency} {demand.amount} received; examination deadline "
                        f"{demand.examination_deadline} (URDG 758 Art. 20)")
            # URDG 758 Art. 16: inform the applicant without delay
            if demand.extend_or_pay and demand.requested_new_expiry:
                demand.status = "SUSPENDED_EXTEND_OR_PAY"
                demand.suspension_end = demand.presentation_date + timedelta(days=30)
                await self._notify_client(
                    g, "Extend-or-pay demand received",
                    f"The beneficiary demands {demand.currency} {demand.amount:,} under {g.ref} OR an extension to "
                    f"{demand.requested_new_expiry}. Payment is suspended until {demand.suspension_end} (URDG 758 Art. 23). "
                    f"If you agree to extend, the demand is deemed withdrawn.",
                    {"Agree to extension": self.decision_link(g.ref, demand.demand_id, "extend"),
                     "Do not extend (pay if complying)": self.decision_link(g.ref, demand.demand_id, "pay")})
            else:
                await self._notify_client(g, "Demand received under your guarantee",
                                          f"A demand for {demand.currency} {demand.amount:,} under {g.ref} was received and "
                                          f"is being examined (URDG 758 Art. 16). You will be debited if it complies.")
                await self._decide_demand(g, demand)
            self._save()
            return g

    async def extend_or_pay_decision(self, ref: str, demand_id: str, extend: bool) -> Guarantee:
        async with self._unit_of_work():
            g = self.get_deal(ref)
            d = next((x for x in g.demands if x.demand_id == demand_id), None)
            if not d or d.status != "SUSPENDED_EXTEND_OR_PAY":
                raise WorkflowError("No suspended extend-or-pay demand with that id")
            if extend:
                g.status = "ISSUED"
                await self._amend_undertaking(g, {"expiry_date": d.requested_new_expiry,
                                                  "narrative": "Extension agreed following extend-or-pay demand"},
                                              "GUARANTEE", "GTEE")
                d.status = "WITHDRAWN"
                self._event(g, f"DEMAND_{demand_id}", self.agent_id, "DONE",
                            "Extension granted - demand deemed withdrawn (URDG 758 Art. 23(d))")
            else:
                await self._decide_demand(g, d)
            self._save()
            return g

    async def _decide_demand(self, g: Guarantee, d: Demand):
        disc = rules.examine_urdg_demand(g, d)
        d.discrepancies = disc
        step = f"DEMAND_{d.demand_id}"
        if disc:
            d.status = "REJECTED"
            text = "\n".join(f"{i}. {x.description} ({x.rule})" for i, x in enumerate(disc, 1))
            notice = (f"Rejection of demand {d.demand_id} under guarantee {g.ref} (URDG 758 Art. 24). "
                      f"The demand is not complying for the following reasons:\n{text}\n"
                      f"Documents are held at your disposal.")
            await self._archive(g, "REJECTION_NOTICE", f"{g.ref}_{d.demand_id}_rejection.txt", notice)
            if g.terms.beneficiary_bank_bic:
                fin = swift.build_fin("799", settings.bank_bic(), g.terms.beneficiary_bank_bic,
                                      [("20", swift.ref16(g.ref)), ("21", swift.ref16(d.demand_id)),
                                       ("79", swift.lines(notice, 50, 35))])
                await self._swift(g, step, "799", g.terms.beneficiary_bank_bic, fin)
            else:
                await self._email_counterparty(g, g.terms.beneficiary, "Rejection of your demand", notice)
            g.status = "ISSUED"
            self._event(g, step, self.agent_id, "DONE", f"Demand rejected: {[x.code for x in disc]}")
            await self._notify_client(g, "Demand rejected", f"The demand under {g.ref} was rejected as non-complying:\n{text}")
            return
        d.status = "COMPLYING"
        payee = g.terms.beneficiary
        if g.terms.counter_guarantee:  # we pay the local bank that paid under its own guarantee (bank-to-bank)
            bic = g.terms.beneficiary_bank_bic
            payee = Party(name=f"Guarantor bank {bic}", country=bic[4:6], bic=bic)
        await self._pay_undertaking(g, d.amount, d.demand_id, "GTEE", payee, g.terms.beneficiary_bank_bic)
        d.status = "PAID"

    async def _pay_undertaking(self, deal, amount: Decimal, item_id: str, prefix: str, payee: Party, payee_bank_bic: Optional[str]):
        step = f"PAYMENT_{item_id}"
        value_date = next_banking_day(self.today)
        amount_eur = await self._eur(deal, amount, deal.currency)
        release_eur = min(amount_eur, deal.limit_utilisation_eur + deal.cash_collateral_eur)
        await self._call(deal, step, "tf_credit_limits", "release_limit", {"deal_ref": deal.ref, "amount_eur": release_eur},
                         "RELEASE_CREDIT_LIMIT")
        deal.limit_utilisation_eur = max(D0, deal.limit_utilisation_eur - release_eur)
        nostro = self.state.reference.nostro_by_currency[deal.currency]
        info = await self._debit_customer_for_payment(
            deal, amount, deal.currency, f"Payment under {deal.ref} (recourse)",
            [{"credit": nostro, "amount": amount, "narrative": f"Payment to {payee.name} under {deal.ref}"}], step,
            fees_eur=self.state.reference.tariff["claim_handling_flat"])
        if deal.currency != "EUR":
            await self._post(deal, step, [{"debit": "GL_FX_POSITION_EUR", "credit": "GL_EQUITY_EUR", "amount": info["amount_eur"],
                                           "narrative": "FX deal EUR leg"},
                                          {"debit": f"GL_EQUITY_{deal.currency}", "credit": f"GL_FX_POSITION_{deal.currency}",
                                           "amount": amount, "narrative": f"FX deal {deal.currency} leg"}])
        await self._charge_fee(deal, "CLAIM_HANDLING", self.state.reference.tariff["claim_handling_flat"])
        await self._book_contingent(deal, prefix, min(amount_eur, self._contingent_open(deal, prefix)), reverse=True, step=step)
        corr = self.state.reference.correspondent_bic_by_currency.get(deal.currency)
        if payee.iban and corr:
            cust = await self._customer(deal.customer_id)
            ref = f"{deal.ref}C{len(deal.swift_message_ids)}"
            remittance = f"PAYMENT UNDER {deal.ref} CLAIM {item_id}"
            if settings.payment_message_format() == "MT":
                fin = swift.mt103(ref, value_date, deal.currency, amount, settings.bank_name(), cust.current_account_iban,
                                  payee.name, payee.iban, payee.country, remittance, corr, settings.bank_bic())
                await self._swift(deal, step, "103", corr, fin)
            else:
                xml = iso20022.pacs008(ref, item_id, value_date, deal.currency, amount, settings.bank_name(),
                                       cust.current_account_iban, payee.name, payee.iban, payee.country, remittance, corr,
                                       settings.bank_bic(), payee_bank_bic)
                await self._swift(deal, step, "pacs.008", corr, xml)
        elif payee_bank_bic and corr:
            await self._pay_bank(deal, step, f"{deal.ref}C{len(deal.swift_message_ids)}", item_id, value_date, deal.currency,
                                 amount, payee_bank_bic, corr)
        else:
            self._event(deal, step, "tf_core_ledger", "OK", "Domestic payment released via SEPA clearing (no SWIFT leg)")
        deal.outstanding = max(D0, deal.outstanding - amount)
        self._event(deal, step, self.agent_id, "DONE",
                    f"Paid {deal.currency} {amount} to {payee.name} value {value_date}; customer debited EUR {info['amount_eur']} (recourse)")
        await self._email_counterparty(deal, payee, "Payment advice",
                                       f"We have paid {deal.currency} {amount:,} under {deal.ref} (claim {item_id}), "
                                       f"value date {value_date}.")
        await self._notify_client(deal, "Payment made under your undertaking",
                                  f"We paid {deal.currency} {amount:,} to {payee.name} under {deal.ref}. Your account was "
                                  f"debited EUR {info['amount_eur']:,} (value {value_date}). Remaining amount: "
                                  f"{deal.currency} {deal.outstanding:,}.")
        if deal.outstanding <= 0:
            await self._release_all(deal, prefix, "Fully paid - closed")
            deal.status = "CLOSED"
        else:
            deal.status = "ISSUED"

    async def release_undertaking(self, ref: str, reason: str = "Released by beneficiary / original returned") -> Any:
        async with self._unit_of_work():
            deal = self.get_deal(ref)
            if deal.status not in ("ISSUED",):
                raise WorkflowError(f"{ref} cannot be released in status {deal.status}")
            await self._release_undertaking(deal, reason)
            self._save()
            return deal

    async def _release_undertaking(self, deal, reason: str):
        prefix = "GTEE" if isinstance(deal, Guarantee) else "SURETY"
        outstanding = deal.outstanding
        await self._release_all(deal, prefix, reason)
        receiver = getattr(deal.terms, "beneficiary_bank_bic", None)
        if receiver:
            fin = swift.mt769(deal, outstanding, D0, self.today, receiver, settings.bank_bic(), reason)
            await self._swift(deal, "RELEASE", "769", receiver, fin)
        deal.outstanding = D0
        deal.status = "EXPIRED" if "expir" in reason.lower() else "RELEASED"
        await self._notify_client(deal, f"{'Guarantee' if prefix == 'GTEE' else 'Surety bond'} {deal.status.lower()}",
                                  f"{deal.ref} is no longer outstanding ({reason}). Your limit has been released and no "
                                  f"further commission will be charged.")

