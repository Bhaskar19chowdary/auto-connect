    async def apply_surety(self, terms: SuretyTerms, created_by: Optional[str] = None) -> SuretyBond:
        async with self._unit_of_work():
            await self._customer(terms.principal_customer_id)  # unknown customers are refused by the customer master
            self._check_currency(terms.currency)
            ref = self.state.next_ref("SUR")
            b = SuretyBond(ref=ref, customer_id=terms.principal_customer_id, status="RECEIVED", contingent_booked_eur=D0, currency=terms.currency,
                           amount=rules.money(terms.amount), outstanding=rules.money(terms.amount), terms=terms)
            b.created_by = created_by
            self.state.deals[ref] = b
            self._event(b, "RECEIVED", self.agent_id, "DONE", "Surety bond application received")
            await self._run_issuance(b, self._surety_issuance)
            await self._acknowledge(b, "surety bond")
            self._save()
            return b

    async def _surety_issuance(self, b: SuretyBond):
        t = b.terms
        cust = await self._customer(b.customer_id)
        if not self._done(b, "VALIDATION"):
            errors, warnings = rules.validate_surety_application(t, self.today)
            if errors and not self._use_approval(b, "DATA_QUALITY"):
                self._raise_exception(b, "DATA_QUALITY", " | ".join(f"{e.code}: {e.description} [{e.rule}]" for e in errors), "ISSUE")
                await self._notify_client(b, "Your surety bond application needs correction",
                                          "\n".join(f"- {e.description} ({e.rule})" for e in errors))
                return
            self._event(b, "VALIDATION", self.agent_id, "DONE", "Underwriting checks passed", {"warnings": warnings})
        if not await self._step_kyc(b):
            return
        parties = [{"name": cust.name, "country": cust.country, "address": cust.address, "role": "principal"},
                   {"name": t.obligee.name, "country": t.obligee.country, "address": t.obligee.address, "role": "obligee"}]
        if not await self._step_sanctions(b, parties, [t.obligee.address], t.underlying_contract):
            return
        amount_eur = await self._eur(b, b.amount, t.currency)
        if not await self._step_limit(b, "SURETY", amount_eur):
            return
        if not self._done(b, "ISSUANCE"):
            b.issue_date = self.today
            tariff = self.state.reference.tariff
            q_end = b.commission_paid_until or rules.add_quarter(self.today)
            await self._charge_fee(b, "SURETY_ISSUANCE", tariff["guarantee_issuance_flat"], once=True)
            await self._charge_fee(b, "AVAL_COMMISSION", rules.aval_commission_for_quarter(amount_eur, cust.risk_rating, tariff),
                                   q_end, once=True)
            b.commission_paid_until = q_end
            if self._contingent_open(b, "SURETY") == 0:
                await self._book_contingent(b, "SURETY", amount_eur)
            deed = rules.surety_deed_text(b, cust.name, settings.bank_name())
            await self._archive(b, "SURETY_DEED", f"{b.ref}_Buergschaftsurkunde.txt", deed)
            b.status = "ISSUED"
            self._event(b, "ISSUANCE", self.agent_id, "DONE", "Surety deed issued and dispatched to the obligee")
            await self._notify_client(b, "Surety bond issued",
                                      f"Surety bond {b.ref} ({t.bond_type.replace('_', ' ').lower()}) for {t.currency} "
                                      f"{b.amount:,} in favour of {t.obligee.name} has been issued.\n\nDeed text:\n{deed}")

    async def amend_surety(self, ref: str, changes: Dict[str, Any]) -> SuretyBond:
        async with self._unit_of_work():
            b = self.get_deal(ref)
            if not isinstance(b, SuretyBond) or b.status != "ISSUED":
                raise WorkflowError(f"{ref} cannot be amended in status {getattr(b, 'status', '?')}")
            await self._amend_undertaking(b, changes, "SURETY", "SURETY")
            self._save()
            return b

    async def present_surety_claim(self, ref: str, claim: SuretyClaim, files=None,
                                   uploaded_by: Optional[str] = None) -> SuretyBond:
        async with self._unit_of_work():
            b = self.get_deal(ref)
            if not isinstance(b, SuretyBond) or b.status not in ("ISSUED",):
                raise WorkflowError(f"{ref} cannot receive a claim in status {getattr(b, 'status', '?')}")
            b.claims.append(claim)
            self._attach_files(b, claim.claim_id, files, uploaded_by)
            step = f"CLAIM_{claim.claim_id}"
            disc = rules.examine_surety_claim(b, claim)
            claim.discrepancies = disc
            self._event(b, step, "obligee", "DONE", f"Claim for {claim.currency} {claim.amount} received")
            if disc:
                claim.status = "REJECTED"
                text = "\n".join(f"- {x.description} ({x.rule})" for x in disc)
                letter = f"Claim {claim.claim_id} under surety bond {b.ref} rejected for the following reasons:\n{text}"
                await self._archive(b, "CLAIM_REJECTION", f"{b.ref}_{claim.claim_id}_rejection.txt", letter)
                await self._email_counterparty(b, b.terms.obligee, "Your claim under our surety bond", letter)
                self._event(b, step, self.agent_id, "DONE", f"Claim rejected: {[x.code for x in disc]}")
                await self._notify_client(b, "Claim under your surety bond rejected",
                                          f"A claim by {b.terms.obligee.name} for {claim.currency} {claim.amount:,} was "
                                          f"rejected:\n{text}")
            elif b.terms.on_first_demand:
                await self._notify_client(b, "Claim under your surety bond (first demand)",
                                          f"{b.terms.obligee.name} demanded {claim.currency} {claim.amount:,} under the "
                                          f"first-demand bond {b.ref}. We are obliged to pay; you will be debited (recourse).")
                await self._pay_undertaking(b, claim.amount, claim.claim_id, "SURETY", b.terms.obligee, None)
                claim.status = "PAID"
            else:
                claim.status = "AWAITING_PRINCIPAL"
                claim.principal_deadline = self.today + timedelta(days=b.terms.principal_response_days)
                await self._email_counterparty(
                    b, b.terms.obligee, "Your claim has been received",
                    f"We received your claim for {claim.currency} {claim.amount:,} under surety bond {b.ref}. We are "
                    f"examining it together with the principal and will revert by {claim.principal_deadline}.")
                await self._notify_client(
                    b, "Claim under your surety bond - defences?",
                    f"{b.terms.obligee.name} claims {claim.currency} {claim.amount:,} under surety bond {b.ref}. "
                    f"As accessory surety we may raise your defences (§ 768 BGB). If you do not respond by "
                    f"{claim.principal_deadline}, we will pay and debit your account (§ 774 BGB).",
                    {"Acknowledge claim (pay)": self.decision_link(b.ref, claim.claim_id, "acknowledge"),
                     "Dispute claim": self.decision_link(b.ref, claim.claim_id, "dispute")})
            self._save()
            return b

    async def principal_claim_response(self, ref: str, claim_id: str, dispute: bool, reason: str = "") -> SuretyBond:
        async with self._unit_of_work():
            b = self.get_deal(ref)
            c = next((x for x in b.claims if x.claim_id == claim_id), None)
            if not c or c.status != "AWAITING_PRINCIPAL":
                raise WorkflowError("No claim awaiting the principal's response")
            c.principal_response = reason or ("DISPUTED" if dispute else "ACKNOWLEDGED")
            if dispute:
                c.status = "DISPUTED"
                self._raise_exception(b, "LEGAL", f"Principal disputes claim {claim_id}: {reason or 'no reason given'}",
                                      f"CLAIM:{claim_id}")
                await self._notify_internal(b, "Disputed surety claim", f"Legal assessment needed for claim {claim_id}: {reason}")
                b.status = "ON_HOLD_LEGAL"
            else:
                await self._pay_undertaking(b, c.amount, c.claim_id, "SURETY", b.terms.obligee, None)
                c.status = "PAID"
            self._save()
            return b

