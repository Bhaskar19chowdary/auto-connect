    # client applications (client portal / entered by staff)
    @staticmethod
    def application_terms(product: str, customer_id: str, details: Dict[str, Any]):
        """Turns the submitted form into the product's terms; the applicant is always the signed-in customer."""
        from .models import CollectionTerms

        d = {k: v for k, v in (details or {}).items() if k not in ("applicant_customer_id", "principal_customer_id",
                                                                     "customer_id", "direction")}
        if product == "LC":
            return LCTerms(**d, applicant_customer_id=customer_id)
        if product == "GUARANTEE":
            return GuaranteeTerms(**d, applicant_customer_id=customer_id)
        if product == "SURETY":
            return SuretyTerms(**d, principal_customer_id=customer_id)
        if product == "COLLECTION":
            return CollectionTerms(**d, direction="EXPORT", customer_id=customer_id)
        raise WorkflowError(f"Unknown product {product}")

    async def submit_application(self, customer_id: str, product: str, details: Dict[str, Any], files=None,
                                 submitted_by: Optional[str] = None, channel: str = "CLIENT_PORTAL"):
        """Step 1: the application and its supporting files are saved (own transaction - never lost).
        Step 2: it is processed straight away like any other application (checks, limits, issuance)."""
        from .models import Application

        terms = self.application_terms(product, customer_id, details)  # invalid forms are refused before saving
        async with self._unit_of_work():
            if customer_id not in self.state.customers:
                await self._customer(customer_id)  # unknown customers are refused by the customer master
            app = Application(customer_id=customer_id, product=product, details=to_jsonable(terms.model_dump(mode="json")),
                              channel=channel, submitted_by=submitted_by)
            app.history.append({"at": rules_now(), "text": "Application received and saved"
                                + (f" with {len(files)} supporting document(s)" if files else "")})
            for name, data in files or []:
                from ..document_reader import mime_of

                meta = {"file_id": new_id_file(), "deal_ref": app.application_id, "item_id": app.application_id,
                        "filename": name, "mime": mime_of(name, data), "size": len(data),
                        "sha256": hashlib.sha256(data).hexdigest(), "uploaded_at": rules_now(), "uploaded_by": submitted_by}
                self.store.save_file(meta, data)
                app.attachments.append(meta)
            self.state.applications[app.application_id] = app
        return await self.process_application(app.application_id)

    async def process_application(self, application_id: str, by: Optional[str] = None):
        """Creates the deal of a saved application. The deal and the application's new status are stored in one
        transaction; if a bank system is down the application waits (retry later), invalid ones are rejected."""
        app = self.state.applications.get(application_id)
        if not app:
            raise WorkflowError(f"Unknown application {application_id}")
        if app.status not in ("SUBMITTED", "WAITING_FOR_SYSTEM"):
            raise WorkflowError(f"Application {application_id} is already {app.status.lower()}")
        try:
            async with self._unit_of_work():
                app = self.state.applications[application_id]  # the books may have been reloaded at begin()
                terms = self.application_terms(app.product, app.customer_id, app.details)
                maker = app.submitted_by or f"client:{app.customer_id}"
                mistakes = self._client_mistakes(app.product, terms) if app.channel == "CLIENT_PORTAL" else []
                if mistakes:  # typing errors go straight back to the client - no transaction, no employee needed
                    app.attempts += 1
                    app.status, app.problems = "NEEDS_CORRECTION", mistakes
                    app.message = "Please correct: " + " ".join(m["message"] for m in mistakes)
                    app.history.append({"at": rules_now(), "text": app.message})
                    self.store.mark("applications", application_id)
                    return app
                if app.product == "LC":
                    deal = await self.apply_lc(terms, created_by=maker)
                elif app.product == "GUARANTEE":
                    deal = await self.apply_guarantee(terms, created_by=maker)
                elif app.product == "SURETY":
                    deal = await self.apply_surety(terms, created_by=maker)
                else:
                    deal = await self.new_collection(terms, created_by=maker)
                deal = self.state.deals[deal.ref]
                deal.application_id = application_id
                for meta in app.attachments:
                    deal.attachments.append({**meta, "deal_ref": deal.ref})
                app.attempts += 1
                app.status, app.deal_ref, app.problems = "PROCESSED", deal.ref, []
                app.message = f"Processed - transaction {deal.ref} created"
                app.history.append({"at": rules_now(), "text": app.message + (f" (retried by {by})" if by else "")})
                self.store.mark("applications", application_id)
        except WorkflowError as e:
            await self._application_outcome(application_id, "REJECTED", f"Cannot be processed: {e}")
        except (BusError, ConnectionError, TimeoutError, OSError) as e:
            await self._application_outcome(application_id, "WAITING_FOR_SYSTEM",
                                            f"A bank system was not available ({getattr(e, 'system', '') or type(e).__name__}); "
                                            f"the application is saved and will be processed again")
        return self.state.applications[application_id]

    EDITABLE_APPLICATION = ("WAITING_FOR_SYSTEM", "REJECTED", "NEEDS_CORRECTION")

    def _client_mistakes(self, product: str, terms) -> List[Dict[str, str]]:
        from . import plain

        check = {"LC": rules.validate_lc_application, "GUARANTEE": rules.validate_guarantee_application,
                 "SURETY": rules.validate_surety_application}.get(product)
        found = plain.client_problems(check(terms, self.today)[0]) if check else []
        if product == "LC":  # obvious date typos (e.g. year 0026) the bank's rule book does not cover on its own
            codes = {p["code"] for p in found}
            if terms.latest_shipment_date < self.today and "SHIPMENT_AFTER_EXPIRY" not in codes:
                found += plain.client_problems(["SHIPMENT_DATE_IN_PAST"])
            elif (terms.latest_shipment_date >= self.today and terms.expiry_date > self.today
                  and terms.expiry_date < terms.latest_shipment_date + timedelta(days=min(terms.presentation_period_days, 7))):
                found += plain.client_problems(["EXPIRY_TOO_SOON"])
        return found

    def can_return_to_client(self, exc) -> bool:
        """A data-quality stop can go back to the client only before anything was booked or sent for the deal."""
        deal = self.state.deals.get(exc.deal_ref)
        return bool(exc.status == "OPEN" and exc.category == "DATA_QUALITY" and deal and deal.application_id
                    and deal.application_id in self.state.applications and deal.issue_date is None
                    and not deal.swift_message_ids and not deal.fees and deal.limit_utilisation_eur == 0
                    and not any(e.deal_ref == deal.ref for e in self.state.ledger[-500:]))

    async def return_to_client(self, exception_id: str, by: str, note: str = ""):
        """Employee sends an application with client mistakes back for correction: the stopped transaction is
        cancelled (nothing was booked) and the application opens again for the client to edit."""
        from . import plain

        async with self._unit_of_work():
            exc = self.state.exceptions.get(exception_id)
            if not exc or not self.can_return_to_client(exc):
                raise WorkflowError("This case cannot be sent back to the client (already decided, or something was "
                                    "already booked - use Reject instead)")
            deal = self.get_deal(exc.deal_ref)
            app = self.state.applications[deal.application_id]
            problems = plain.client_problems(exc.reason.split(" | ")) or [
                {"code": "OTHER", "field": "", "message": exc.reason}]
            exc.status, exc.resolved_by = "REJECTED", by
            exc.resolution_note = f"Returned to client for correction. {note}".strip()
            self.store.mark("exceptions", exception_id)
            if exception_id in deal.open_exceptions:
                deal.open_exceptions.remove(exception_id)
            deal.status = "RETURNED_FOR_CORRECTION"
            self._event(deal, "EXCEPTION", by, "DONE", f"Returned to the client for correction. {note}".strip())
            app.status, app.problems = "NEEDS_CORRECTION", problems
            app.message = "Please correct: " + " ".join(p["message"] for p in problems) + (f" Note from the bank: {note}" if note else "")
            app.history.append({"at": rules_now(), "text": f"Sent back for correction by {by}; transaction {deal.ref} cancelled"})
            app.deal_ref = None
            self.store.mark("applications", app.application_id)
            await self._notify_client(deal, "Please correct your application",
                                      f"We could not process your application {app.application_id} yet: "
                                      + " ".join(p["message"] for p in problems)
                                      + (f"\n\nNote from the bank: {note}" if note else "")
                                      + "\n\nPlease open 'My applications' in the client portal, correct it and send it again.")
            return app

    async def edit_application(self, application_id: str, customer_id: str, details: Dict[str, Any], files=None,
                               by: Optional[str] = None):
        """The client corrects an application that has not become a transaction yet, and sends it again.
        The previous version is kept in the history (nothing is overwritten without a trace)."""
        app = self.state.applications.get(application_id)
        if not app or app.customer_id != customer_id:
            raise WorkflowError(f"Unknown application {application_id}")
        if app.status not in self.EDITABLE_APPLICATION:
            raise WorkflowError(f"Application {application_id} can no longer be changed (it is {app.status.lower()})")
        terms = self.application_terms(app.product, customer_id, details)
        async with self._unit_of_work():
            app = self.state.applications[application_id]
            if app.status not in self.EDITABLE_APPLICATION:
                raise WorkflowError(f"Application {application_id} can no longer be changed")
            app.history.append({"at": rules_now(), "text": f"Changed and sent again by {by or 'the client'}",
                                "previous": app.details})
            app.details = to_jsonable(terms.model_dump(mode="json"))
            for name, data in files or []:
                from ..document_reader import mime_of

                meta = {"file_id": new_id_file(), "deal_ref": app.application_id, "item_id": app.application_id,
                        "filename": name, "mime": mime_of(name, data), "size": len(data),
                        "sha256": hashlib.sha256(data).hexdigest(), "uploaded_at": rules_now(), "uploaded_by": by}
                self.store.save_file(meta, data)
                app.attachments.append(meta)
            app.status, app.message = "SUBMITTED", "Changed and sent again"
            self.store.mark("applications", application_id)
        return await self.process_application(application_id)

    async def withdraw_application(self, application_id: str, customer_id: str, by: Optional[str] = None):
        app = self.state.applications.get(application_id)
        if not app or app.customer_id != customer_id:
            raise WorkflowError(f"Unknown application {application_id}")
        if app.status not in self.EDITABLE_APPLICATION:
            raise WorkflowError(f"Application {application_id} can no longer be withdrawn (it is {app.status.lower()})")
        await self._application_outcome(application_id, "WITHDRAWN", f"Withdrawn by {by or 'the client'}")
        return self.state.applications[application_id]

    async def _application_outcome(self, application_id: str, status: str, message: str):
        async with self._unit_of_work():
            app = self.state.applications[application_id]
            app.attempts += 0 if status == "WITHDRAWN" else 1
            app.status, app.message = status, message[:500]
            app.history.append({"at": rules_now(), "text": app.message})
            self.store.mark("applications", application_id)

    async def retry_waiting_applications(self) -> int:
        n = 0
        for app_id in [a.application_id for a in self.state.applications.values() if a.status == "WAITING_FOR_SYSTEM"]:
            if (await self.process_application(app_id, by="automatic retry")).status == "PROCESSED":
                n += 1
        return n

    def _check_currency(self, currency: str):
        if currency not in self.state.reference.fx_eur_per_unit or currency not in self.state.reference.nostro_by_currency:
            raise WorkflowError(f"Currency {currency} is not supported (no FX rate or nostro account)")

    async def _run_issuance(self, deal, pipeline):
        """Runs an issuance pipeline; a bank system outage parks the deal in the operations queue instead of losing it."""
        try:
            await pipeline(deal)
        except BusError as e:
            reason = f"{e.system or 'bank system'} unavailable ({e.code}): {e.detail}"[:300]
            self._raise_exception(deal, "OPERATIONS", reason, "ISSUE")
            await self._notify_internal(deal, "System outage - application parked",
                                        f"{reason}\nApprove the exception to retry once the system is back.")

