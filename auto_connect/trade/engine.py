"""
Trade Finance Operations Engine - straight-through processing of the full lifecycle of

* Import Letters of Credit (UCP 600): application -> KYC -> sanctions -> limit -> fees -> booking
  -> MT700 -> amendments (MT707) -> document examination -> waiver / refusal (MT734) ->
  payment (MT756 + MT202) or acceptance (MT732) and payment at maturity -> expiry/closure.
* Demand Guarantees / Standby LCs (URDG 758): issuance (MT760) -> amendments (MT767) ->
  demand handling incl. extend-or-pay -> payment -> reduction/release (MT769).
* Surety bonds (Bürgschaften): underwriting -> deed -> claim handling (accessory: principal's
  defences; on first demand) -> payment and recourse -> release.

The engine is the orchestrating agent ("tf_operations_engine"); every step is a call to one of
the bank systems over the A2A bus. Every decision is taken by rules and recorded with the rule
reference. Work only stops in the exception queue when the rules legally cannot decide
(e.g. a confirmed sanctions match, a credit request above delegated authority, or a principal
disputing a surety claim) - and resumes automatically once the item is resolved.
"""

