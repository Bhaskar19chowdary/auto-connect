    async def apply_lc(self, terms: LCTerms, created_by: Optional[str] = None) -> LetterOfCredit:
        async with self._unit_of_work():
            await self._customer(terms.applicant_customer_id)  # unknown customers are refused by the customer master
            self._check_currency(terms.currency)
            ref = self.state.next_ref("ILC")
            lc = LetterOfCredit(ref=ref, customer_id=terms.applicant_customer_id, status="RECEIVED", contingent_booked_eur=D0,
                                currency=terms.currency, amount=rules.money(terms.amount),
                                outstanding=rules.money(terms.amount), terms=terms)
            lc.created_by = created_by
            self.state.deals[ref] = lc
            self._event(lc, "RECEIVED", self.agent_id, "DONE", "LC application received")
            await self._run_issuance(lc, self._lc_issuance)
            await self._acknowledge(lc, "documentary credit")
            self._save()
            return lc

    async def _lc_issuance(self, lc: LetterOfCredit):
        t = lc.terms
        cust = await self._customer(lc.customer_id)
        if not self._done(lc, "VALIDATION"):
            errors, warnings = rules.validate_lc_application(t, self.today)
            if errors and not self._use_approval(lc, "DATA_QUALITY"):
                self._raise_exception(lc, "DATA_QUALITY", " | ".join(f"{e.code}: {e.description} [{e.rule}]" for e in errors), "ISSUE")
                await self._notify_client(lc, "Your LC application needs correction",
                                          "We could not issue your documentary credit because:\n" +
                                          "\n".join(f"- {e.description} ({e.rule})" for e in errors))
                return
            self._event(lc, "VALIDATION", self.agent_id, "DONE", "Application checks passed", {"warnings": warnings})
        if not await self._step_kyc(lc):
            return
        adv_country = t.advising_bank_bic[4:6]
        parties = [
            {"name": cust.name, "country": cust.country, "address": cust.address, "role": "applicant"},
            {"name": t.beneficiary.name, "country": t.beneficiary.country, "address": t.beneficiary.address, "role": "beneficiary"},
            {"name": f"Advising bank {t.advising_bank_bic}", "country": adv_country, "role": "advising bank"},
        ]
        if not await self._step_sanctions(lc, parties, [t.port_of_loading, t.port_of_discharge], t.goods_description,
                                          t.vessel_imo, t.export_license_ref):
            return
        exposure_eur = await self._eur(lc, rules.credit_ceiling(t), t.currency)
        if not await self._step_limit(lc, "LC", exposure_eur):
            return
        if not self._done(lc, "ISSUANCE"):
            fee = rules.lc_issuance_commission(exposure_eur, self.today, t.expiry_date, self.state.reference.tariff)
            await self._charge_fee(lc, "LC_ISSUANCE_COMMISSION", fee, period_end=t.expiry_date, once=True)
            await self._charge_fee(lc, "SWIFT", self.state.reference.tariff["swift_fee"], once=True)
            if self._contingent_open(lc, "LC") == 0:
                await self._book_contingent(lc, "LC", exposure_eur)
            lc.issue_date = lc.issue_date or self.today
            fin = swift.mt700(lc, cust, lc.issue_date, settings.bank_bic())
            if not self._did(lc, "ISSUANCE", "tf_swift_gateway"):
                await self._swift(lc, "ISSUANCE", "700", t.advising_bank_bic, fin)
            await self._archive(lc, "MT700", f"{lc.ref}_MT700.fin", fin)
            await self._archive(lc, "TERMS", f"{lc.ref}_terms.json", json.dumps(to_jsonable(t), indent=2))
            lc.status = "ISSUED"
            self._event(lc, "ISSUANCE", self.agent_id, "DONE", f"LC issued, MT700 sent to {t.advising_bank_bic}")
            await self._notify_client(
                lc, "Documentary credit issued",
                f"Your documentary credit {lc.ref} for {t.currency} {lc.amount:,} in favour of {t.beneficiary.name} "
                f"has been issued today and advised via {t.advising_bank_bic} (SWIFT MT700).\n"
                f"Expiry: {t.expiry_date} | Latest shipment: {t.latest_shipment_date}\n"
                f"Commission charged: EUR {fee} (+ SWIFT EUR {self.state.reference.tariff['swift_fee']}).")

    async def amend_lc(self, ref: str, changes: Dict[str, Any]) -> LetterOfCredit:
        async with self._unit_of_work():
            lc = self.get_deal(ref)
            if not isinstance(lc, LetterOfCredit) or lc.status not in ("ISSUED", "PARTIALLY_DRAWN"):
                raise WorkflowError(f"{ref} cannot be amended in status {getattr(lc, 'status', '?')}")
            n = len(lc.amendments) + 1
            amd = Amendment(number=n, date=self.today, changes=to_jsonable(changes), status="PENDING_APPROVAL")
            lc.amendments.append(amd)
            await self._process_lc_amendment(lc, amd)
            self._save()
            return lc

    async def _process_lc_amendment(self, lc: LetterOfCredit, amd: Amendment):
        t = lc.terms
        ch = amd.changes
        delta = Decimal(str(ch.get("amount_delta", "0")))
        new_expiry = date.fromisoformat(ch["expiry_date"]) if ch.get("expiry_date") else None
        new_ship = date.fromisoformat(ch["latest_shipment_date"]) if ch.get("latest_shipment_date") else None
        if new_expiry and new_expiry <= self.today:
            raise WorkflowError("New expiry date must be in the future")
        if (new_ship or t.latest_shipment_date) > (new_expiry or t.expiry_date):
            raise WorkflowError("Latest shipment date would fall after expiry")
        if lc.outstanding + delta <= 0:
            raise WorkflowError("Amendment would reduce the credit to zero - use cancellation instead")
        step = f"AMENDMENT_{amd.number}"
        if delta > 0:
            extra_eur = await self._eur(lc, delta * (1 + t.tolerance_plus_pct / 100), t.currency)
            if not await self._step_limit(lc, "LC", extra_eur, step=f"{step}_CREDIT", resume=f"AMEND:{amd.number}"):
                return
            await self._book_contingent(lc, "LC", extra_eur, step=step)
        tariff = self.state.reference.tariff
        fee = tariff["lc_amendment_flat"]
        if delta > 0:
            fee += rules.lc_issuance_commission(await self._eur(lc, delta, t.currency), self.today,
                                                new_expiry or t.expiry_date, tariff)
        if new_expiry and new_expiry > t.expiry_date:
            extra_q = rules.quarters_started(lc.issue_date, new_expiry) - rules.quarters_started(lc.issue_date, t.expiry_date)
            if extra_q > 0:
                out_eur = await self._eur(lc, lc.outstanding, t.currency)
                fee += rules.money(out_eur * tariff["lc_issuance_rate_per_quarter_pct"] / 100 * extra_q)
        await self._charge_fee(lc, "LC_AMENDMENT", rules.money(fee))
        amd.previous = to_jsonable({"amount": lc.amount, "outstanding": lc.outstanding, "expiry_date": t.expiry_date,
                                    "latest_shipment_date": t.latest_shipment_date})
        fin = swift.mt707(lc, amd.number, {"amount_delta": delta or None, "expiry_date": new_expiry,
                                           "latest_shipment_date": new_ship, "narrative": ch.get("narrative")},
                          self.today, settings.bank_bic())
        await self._swift(lc, step, "707", t.advising_bank_bic, fin)
        # UCP 600 Art. 10(b): issuing bank is bound from issuance of the amendment; beneficiary may still reject.
        lc.amount += delta
        lc.outstanding += delta
        t.amount = lc.amount
        if new_expiry:
            t.expiry_date = new_expiry
        if new_ship:
            t.latest_shipment_date = new_ship
        amd.status = "PENDING_BENEFICIARY"
        lc.status = "ISSUED" if lc.status.startswith("ON_HOLD") else lc.status
        self._event(lc, step, self.agent_id, "DONE", f"Amendment {amd.number} issued (MT707)", ch)
        await self._notify_client(lc, f"Amendment {amd.number} issued",
                                  f"Amendment {amd.number} to credit {lc.ref} has been sent to the advising bank. "
                                  f"Fee: EUR {rules.money(fee)}. It becomes binding on the beneficiary when accepted (UCP 600 Art. 10).")

    async def beneficiary_amendment_response(self, ref: str, number: int, accepted: bool) -> LetterOfCredit:
        async with self._unit_of_work():
            lc = self.get_deal(ref)
            amd = next((a for a in lc.amendments if a.number == number), None)
            if not amd or amd.status != "PENDING_BENEFICIARY":
                raise WorkflowError("No pending amendment with that number")
            if accepted:
                await self._accept_amendment(lc, amd)
                self._event(lc, f"AMENDMENT_{number}", "advising bank", "DONE", "Beneficiary accepted (MT730)")
            else:
                await self._revert_amendment(lc, amd)
            self._save()
            return lc

    async def _accept_amendment(self, lc: LetterOfCredit, amd: Amendment):
        """Beneficiary's acceptance makes a reduction binding (UCP 600 Art. 10(b)) - only now is the limit freed."""
        amd.status = "ACCEPTED"
        delta = Decimal(str(amd.changes.get("amount_delta") or "0"))
        if delta < 0:
            release_eur = await self._eur(lc, -delta * (1 + lc.terms.tolerance_plus_pct / 100), lc.terms.currency)
            await self._call(lc, f"AMENDMENT_{amd.number}", "tf_credit_limits", "release_limit",
                             {"deal_ref": lc.ref, "amount_eur": release_eur}, "RELEASE_CREDIT_LIMIT")
            lc.limit_utilisation_eur = max(D0, lc.limit_utilisation_eur - release_eur)
            await self._book_contingent(lc, "LC", min(release_eur, self._contingent_open(lc, "LC")), reverse=True,
                                        step=f"AMENDMENT_{amd.number}")

    async def _revert_amendment(self, lc: LetterOfCredit, amd: Amendment):
        prev = amd.previous
        delta = lc.amount - Decimal(prev["amount"])
        lc.amount = Decimal(prev["amount"])
        lc.terms.amount = lc.amount
        lc.outstanding -= delta
        lc.terms.expiry_date = date.fromisoformat(prev["expiry_date"])
        lc.terms.latest_shipment_date = date.fromisoformat(prev["latest_shipment_date"])
        amd.status = "REJECTED"
        if delta > 0:
            extra_eur = await self._eur(lc, delta * (1 + lc.terms.tolerance_plus_pct / 100), lc.terms.currency)
            await self._call(lc, f"AMENDMENT_{amd.number}", "tf_credit_limits", "release_limit",
                             {"deal_ref": lc.ref, "amount_eur": extra_eur}, "RELEASE_CREDIT_LIMIT")
            lc.limit_utilisation_eur -= extra_eur
            await self._book_contingent(lc, "LC", extra_eur, reverse=True, step=f"AMENDMENT_{amd.number}")
        self._event(lc, f"AMENDMENT_{amd.number}", "advising bank", "REJECTED",
                    "Beneficiary rejected the amendment - original terms apply (UCP 600 Art. 10(c))")

    async def present_documents(self, ref: str, presentation: Presentation,
                                review_reasons: Optional[List[str]] = None, files=None,
                                uploaded_by: Optional[str] = None) -> LetterOfCredit:
        async with self._unit_of_work():
            lc = self.get_deal(ref)
            if not isinstance(lc, LetterOfCredit) or lc.status not in ("ISSUED", "PARTIALLY_DRAWN", "DOCUMENTS_DISCREPANT"):
                raise WorkflowError(f"{ref} cannot receive documents in status {getattr(lc, 'status', '?')}")
            presentation.examination_deadline = add_banking_days(presentation.presentation_date, 5)
            lc.presentations.append(presentation)
            self._attach_files(lc, presentation.presentation_id, files, uploaded_by)
            self._event(lc, f"PRESENTATION_{presentation.presentation_id}", presentation.presenting_bank_bic, "DONE",
                        f"Documents received, claim {lc.terms.currency} {presentation.claimed_amount}; examination "
                        f"deadline {presentation.examination_deadline} (UCP 600 Art. 14(b))")
            if review_reasons:  # documents read by IDR with gaps: a document checker verifies them first
                self._raise_exception(lc, "DATA_QUALITY", "Document checker must verify the automatically read documents "
                                      f"before examination (deadline {presentation.examination_deadline}): " +
                                      "; ".join(review_reasons)[:400], f"PRESENTATION:{presentation.presentation_id}")
                await self._notify_internal(lc, "Documents need checking",
                                            "Automatic document reading was incomplete:\n" + "\n".join(review_reasons))
            else:
                await self._examine_presentation(lc, presentation)
            self._save()
            return lc

    async def correct_presentation_documents(self, ref: str, presentation_id: str, documents: List[Any],
                                             corrected_by: str) -> LetterOfCredit:
        """Document checker replaces the automatically read data before the examination resumes."""
        async with self._unit_of_work():
            lc = self.get_deal(ref)
            p = next((x for x in getattr(lc, "presentations", []) if x.presentation_id == presentation_id), None)
            if not p or p.status != "UNDER_EXAMINATION" or not lc.status.startswith("ON_HOLD"):
                raise WorkflowError("Only a presentation on hold for document checking can be corrected")
            p.documents = documents
            self._event(lc, f"PRESENTATION_{presentation_id}", corrected_by, "DONE",
                        f"Document data verified/corrected by document checker ({len(documents)} documents)")
            self._save()
            return lc

    def _lc_open_status(self, lc: LetterOfCredit) -> str:
        return "PARTIALLY_DRAWN" if any(x.status in ("PAID", "ACCEPTED") for x in lc.presentations) else "ISSUED"

    def _drawn(self, lc: LetterOfCredit, exclude: Optional[str] = None) -> Decimal:
        return sum((p.claimed_amount for p in lc.presentations
                    if p.status in ("PAID", "ACCEPTED", "COMPLYING", "DISCREPANT_WAIVED") and p.presentation_id != exclude), D0)

    async def _examine_presentation(self, lc: LetterOfCredit, p: Presentation):
        cust = await self._customer(lc.customer_id)
        step = f"EXAMINATION_{p.presentation_id}"
        disc = rules.examine_ucp600(lc, p, cust.name, self._drawn(lc, p.presentation_id))
        pending = [a for a in lc.amendments if a.status == "PENDING_BENEFICIARY"]
        if pending:
            if not disc:
                for a in pending:
                    await self._accept_amendment(lc, a)
                self._event(lc, step, self.agent_id, "DONE",
                            "Presentation complies with amended terms - amendment(s) deemed accepted (UCP 600 Art. 10(c))")
            else:
                snapshot = lc.model_copy(deep=True)
                for a in reversed(pending):
                    prev = a.previous
                    snapshot.amount = Decimal(prev["amount"])
                    snapshot.terms.expiry_date = date.fromisoformat(prev["expiry_date"])
                    snapshot.terms.latest_shipment_date = date.fromisoformat(prev["latest_shipment_date"])
                    snapshot.terms.amount = Decimal(prev["amount"])
                if not rules.examine_ucp600(snapshot, p, cust.name, self._drawn(lc, p.presentation_id)):
                    for a in reversed(pending):
                        await self._revert_amendment(lc, a)
                    disc = []
        # sanctions re-screening of the shipment data before any payment
        bl = next((d for d in p.documents if d.doc_type == "BILL_OF_LADING"), None)
        places = [str(bl.fields.get("port_of_loading", "")), str(bl.fields.get("port_of_discharge", ""))] if bl else []
        vessel = bl.fields.get("vessel_imo") if bl else None
        parties = [{"name": f"Presenting bank {p.presenting_bank_bic}", "country": p.presenting_bank_bic[4:6], "role": "presenting bank"}]
        if bl and bl.fields.get("carrier"):
            parties.append({"name": bl.fields["carrier"], "country": bl.fields.get("carrier_country", ""), "role": "carrier"})
        if not await self._step_sanctions(lc, parties, places, "", vessel, None, step=f"SANCTIONS_{p.presentation_id}",
                                          resume=f"PRESENTATION:{p.presentation_id}"):
            return
        p.discrepancies = disc
        if not disc:
            p.status = "COMPLYING"
            self._event(lc, step, self.agent_id, "DONE", "Complying presentation (UCP 600 Art. 15)")
            await self._honour(lc, p)
            return
        tariff = self.state.reference.tariff
        p.discrepancy_fee = tariff["discrepancy_fee"]
        auto = set(cust.auto_waive_discrepancy_codes)
        remaining = [d for d in disc if d.code not in auto]
        if not remaining:
            p.status = "DISCREPANT_WAIVED"
            p.waived_by = "STANDING_INSTRUCTION"
            self._event(lc, step, self.agent_id, "DONE",
                        f"Discrepancies {[d.code for d in disc]} waived under the applicant's standing waiver instruction")
            await self._honour(lc, p)
            return
        p.status = "DISCREPANT_AWAITING_APPLICANT"
        p.applicant_decision_deadline = add_banking_days(p.presentation_date, 3)
        lc.status = "DOCUMENTS_DISCREPANT"
        self._event(lc, step, self.agent_id, "DONE", f"{len(disc)} discrepancies found; applicant approached for waiver "
                    f"(UCP 600 Art. 16(b)) until {p.applicant_decision_deadline}",
                    {"discrepancies": [d.model_dump() for d in disc]})
        await self._notify_client(
            lc, "Discrepant documents - your decision is needed",
            f"Documents presented under credit {lc.ref} ({lc.terms.currency} {p.claimed_amount:,}) contain discrepancies:\n" +
            "\n".join(f"- {d.description} [{d.rule}]" for d in disc) +
            f"\n\nIf we do not receive your waiver by {p.applicant_decision_deadline} we will refuse the documents "
            f"(UCP 600 Art. 16) and hold them at the presenter's disposal.",
            {"Accept discrepancies and pay": self.decision_link(lc.ref, p.presentation_id, "waive"),
             "Refuse documents": self.decision_link(lc.ref, p.presentation_id, "refuse")})

    async def reexamine_presentation(self, ref: str, presentation_id: str, by: str) -> LetterOfCredit:
        """The bank withdraws its own discrepancy finding before the client has decided (e.g. a reading or rule error
        was corrected) and examines the documents again: complying -> paid without a discrepancy fee."""
        async with self._unit_of_work():
            lc = self.get_deal(ref)
            p = next((x for x in getattr(lc, "presentations", []) if x.presentation_id == presentation_id), None)
            if not isinstance(lc, LetterOfCredit) or not p or p.status != "DISCREPANT_AWAITING_APPLICANT":
                raise WorkflowError("Only documents that are waiting for the client's decision can be checked again")
            old = [d.code for d in p.discrepancies]
            p.status, p.discrepancies, p.discrepancy_fee, p.applicant_decision_deadline = "UNDER_EXAMINATION", [], D0, None
            lc.status = self._lc_open_status(lc)
            self._event(lc, f"EXAMINATION_{presentation_id}", by, "DONE",
                        f"Documents checked again by {by}; earlier finding {old} withdrawn before the client decided")
            await self._examine_presentation(lc, p)
            self._save()
            return lc

    async def applicant_waiver_decision(self, ref: str, presentation_id: str, waive: bool) -> LetterOfCredit:
        async with self._unit_of_work():
            lc = self.get_deal(ref)
            p = next((x for x in lc.presentations if x.presentation_id == presentation_id), None)
            if not p or p.status != "DISCREPANT_AWAITING_APPLICANT":
                raise WorkflowError("No presentation awaiting the applicant's decision")
            if waive:
                p.status = "DISCREPANT_WAIVED"
                p.waived_by = "APPLICANT"
                self._event(lc, f"WAIVER_{presentation_id}", "tf_client_portal", "DONE", "Applicant waived discrepancies")
                await self._honour(lc, p)
            else:
                await self._refuse(lc, p, "Applicant declined to waive")
            self._save()
            return lc

    async def _refuse(self, lc: LetterOfCredit, p: Presentation, reason: str):
        fin = swift.mt734(lc, p, p.discrepancies, self.today, settings.bank_bic())
        await self._swift(lc, f"REFUSAL_{p.presentation_id}", "734", p.presenting_bank_bic, fin)
        p.status = "REFUSED"
        if lc.status == "DOCUMENTS_DISCREPANT":
            lc.status = "PARTIALLY_DRAWN" if any(x.status == "PAID" for x in lc.presentations) else "ISSUED"
        self._event(lc, f"REFUSAL_{p.presentation_id}", self.agent_id, "DONE",
                    f"Documents refused by MT734 (UCP 600 Art. 16(c)/(d)); {reason}")
        await self._notify_client(lc, "Documents refused",
                                  f"The presentation {p.presentation_id} under {lc.ref} was refused (MT734). "
                                  f"The credit remains available until {lc.terms.expiry_date}.")

    async def _honour(self, lc: LetterOfCredit, p: Presentation):
        t = lc.terms
        if t.available_by in ("SIGHT_PAYMENT",) or (t.available_by == "NEGOTIATION" and not t.usance_days):
            await self._pay_drawing(lc, p)
            return
        ship = rules.shipment_date(p) or p.presentation_date
        p.maturity_date = next_banking_day(ship + timedelta(days=t.usance_days))
        p.status = "ACCEPTED"
        fin = swift.mt732(lc, p, p.maturity_date, settings.bank_bic())
        await self._swift(lc, f"ACCEPTANCE_{p.presentation_id}", "732", p.presenting_bank_bic, fin)
        out_eur = await self._eur(lc, p.claimed_amount, t.currency)
        days = (p.maturity_date - self.today).days
        fee = rules.money(out_eur * self.state.reference.tariff["lc_acceptance_rate_pa_pct"] / 100 * days / 360)
        await self._charge_fee(lc, "ACCEPTANCE_COMMISSION", max(fee, self.state.reference.tariff["lc_payment_min"]))
        # with partial shipments allowed the unused balance stays available for further presentations
        more = t.partial_shipments_allowed and self._drawn(lc) < lc.amount
        lc.status = "PARTIALLY_DRAWN" if more else "ACCEPTED_AWAITING_MATURITY"
        self._event(lc, f"ACCEPTANCE_{p.presentation_id}", self.agent_id, "DONE",
                    f"Deferred payment undertaking / acceptance, maturity {p.maturity_date}")
        await self._notify_client(lc, "Documents accepted - payment at maturity",
                                  f"Documents under {lc.ref} were taken up. {t.currency} {p.claimed_amount:,} will be "
                                  f"debited to your account at maturity on {p.maturity_date}.")

    async def _pay_drawing(self, lc: LetterOfCredit, p: Presentation):
        t = lc.terms
        step = f"PAYMENT_{p.presentation_id}"
        value_date = next_banking_day(self.today)
        drawing_eur = await self._eur(lc, p.claimed_amount, t.currency)
        # release the limit/cash collateral for the drawn part first so the funds are usable
        release_eur = min(drawing_eur, lc.limit_utilisation_eur + lc.cash_collateral_eur)
        await self._call(lc, step, "tf_credit_limits", "release_limit", {"deal_ref": lc.ref, "amount_eur": release_eur},
                         "RELEASE_CREDIT_LIMIT")
        lc.limit_utilisation_eur = max(D0, lc.limit_utilisation_eur - release_eur)
        disc_fee_ccy = D0
        if p.discrepancy_fee and p.status == "DISCREPANT_WAIVED":
            disc_fee_ccy = rules.money(p.discrepancy_fee / self.systems["tf_market_data"].rates()[t.currency])
        proceeds = p.claimed_amount - disc_fee_ccy
        nostro = self.state.reference.nostro_by_currency[t.currency]
        payee = [{"credit": nostro, "amount": proceeds, "narrative": f"Proceeds {lc.ref} to {p.presenting_bank_bic}"}]
        if disc_fee_ccy:
            payee.append({"credit": f"GL_FEE_INCOME_{t.currency}", "amount": disc_fee_ccy,
                          "narrative": f"Discrepancy fee deducted {lc.ref}"})
        commission = rules.lc_payment_commission(drawing_eur, self.state.reference.tariff)
        info = await self._debit_customer_for_payment(lc, p.claimed_amount, t.currency, f"LC drawing {lc.ref}", payee, step,
                                                      fees_eur=commission)
        if t.currency != "EUR":
            # FX: EUR received from customer is sold for the LC currency (bank's position is flat after this)
            await self._post(lc, step, [{"debit": "GL_FX_POSITION_EUR", "credit": "GL_EQUITY_EUR", "amount": info["amount_eur"],
                                         "narrative": "FX deal EUR leg"},
                                        {"debit": f"GL_EQUITY_{t.currency}", "credit": f"GL_FX_POSITION_{t.currency}",
                                         "amount": p.claimed_amount, "narrative": f"FX deal {t.currency} leg"}])
        await self._charge_fee(lc, "LC_PAYMENT_COMMISSION", commission)
        await self._book_contingent(lc, "LC", min(drawing_eur, self._contingent_open(lc, "LC")), reverse=True, step=step)
        fin756 = swift.mt756(lc, p, value_date, proceeds, settings.bank_bic())
        await self._swift(lc, step, "756", p.presenting_bank_bic, fin756)
        corr = self.state.reference.correspondent_bic_by_currency.get(t.currency, p.presenting_bank_bic)
        await self._pay_bank(lc, step, f"{lc.ref}P{len(lc.swift_message_ids)}", p.presenting_bank_ref or lc.ref, value_date,
                             t.currency, proceeds, p.presenting_bank_bic, corr)
        p.status = "PAID"
        p.paid_amount = proceeds
        lc.outstanding = max(D0, lc.outstanding - p.claimed_amount)
        self._event(lc, step, self.agent_id, "DONE",
                    f"Paid {t.currency} {proceeds} value {value_date} (MT756 + cover payment); applicant debited EUR {info['amount_eur']}")
        await self._notify_client(lc, "Debit advice - LC drawing paid",
                                  f"We honoured documents under {lc.ref}: {t.currency} {p.claimed_amount:,} "
                                  f"(EUR {info['amount_eur']:,}) debited to your account, value {value_date}. "
                                  f"Payment commission EUR {commission}." +
                                  (f"\nA post-financing loan of EUR {info['post_financing_eur']:,} was booked."
                                   if info["post_financing_eur"] else ""))
        if lc.outstanding <= 0 or not t.partial_shipments_allowed:
            await self._release_all(lc, "LC", "Credit fully utilised - closed")
            lc.status = "CLOSED"
        else:
            lc.status = "PARTIALLY_DRAWN"

