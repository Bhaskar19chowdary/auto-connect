def register_systems(store: StateStore, vault, mesh, executor) -> Dict[str, BankSystem]:
    """Provisions vault credentials, publishes agent cards and wires handlers (or live URLs)."""
    bus = TradeBus(vault, mesh, executor)
    bus.store = store
    systems: Dict[str, BankSystem] = {}
    for cls in ALL_SYSTEMS:
        system = cls(store, bus)
        env_key = cls.agent_id.upper()
        live_url = os.environ.get(f"TF_SYSTEM_URL_{env_key}", "").strip()
        # every credential field can be set per system: TF_SYSTEM_<FIELD>_<AGENT_ID>, e.g.
        # TF_SYSTEM_AUTH_TYPE_TF_CORE_LEDGER=OAuth2, TF_SYSTEM_OAUTH_CLIENT_SECRET_TF_CORE_LEDGER=env:LEDGER_SECRET,
        # TF_SYSTEM_TRANSPORT_TF_SWIFT_GATEWAY=FILE, TF_SYSTEM_TRANSPORT_TARGET_TF_SWIFT_GATEWAY=/saa/hotfolder/in
        extra = {f: os.environ[f"TF_SYSTEM_{f.upper()}_{env_key}"].strip() for f in VaultCredential.model_fields
                 if f not in ("app_id", "base_url", "token", "allowed_departments")
                 and os.environ.get(f"TF_SYSTEM_{f.upper()}_{env_key}", "").strip()}
        if "reply_timeout_seconds" in extra:
            extra["reply_timeout_seconds"] = float(extra["reply_timeout_seconds"])
        live = bool(live_url) or extra.get("transport", "HTTP").upper() != "HTTP"
        token = os.environ.get(f"TF_SYSTEM_TOKEN_{env_key}", "").strip() or f"tf_{secrets.token_hex(16)}"
        vault.store_credential(VaultCredential(
            app_id=cls.agent_id,
            base_url=live_url or f"inprocess://{cls.agent_id}",
            auth_type=extra.pop("auth_type", "Bearer"),
            token=token,
            allowed_departments=cls.allowed_departments,
            **extra,
        ))
        if not live:
            executor.register_in_process_handler(cls.agent_id, system.handle)
        mesh.register_agent(system.agent_card())
        systems[cls.agent_id] = system
    return systems
