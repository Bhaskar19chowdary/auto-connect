"""
The bank applications the trade finance engine works with.

Each system is a self-contained service with its own API (POST /api/v1/<agent_id>/<operation>)
and its own A2A Agent Card. All traffic goes through the Zero-Trust Vault (RBAC + audit)
and the Universal Executor, and every call is recorded on the A2A mesh ledger - so the
systems also talk to each other directly (e.g. Credit Limits -> Core Ledger to block cash
collateral, Client Portal -> Customer Master -> Email Gateway).

By default every system runs as an in-process simulator backed by BankState. To connect a
real bank system instead, set TF_SYSTEM_URL_<AGENT_ID> (and TF_SYSTEM_TOKEN_<AGENT_ID>) and the
executor will call the live HTTP API with the same contract (see `openapi()` of each system).
"""

