class CreditLimitSystem(BankSystem):
    """Credit facilities: limit check, earmarking, reallocation, cash collateral and release."""
    agent_id = "tf_credit_limits"
    name = "Credit Limit & Collateral Management"
    department = "CREDIT_RISK"
    peers = ["TRADE_FINANCE", "CORE_BANKING"]
    allowed_departments = ["TRADE_FINANCE"]
    operations = {
        "earmark_limit": {
            "description": "Reserves facility headroom for a deal. Covers shortfalls automatically by limit "
                           "reallocation, cash collateral or delegated temporary excess; else rejects.",
            "params": ["customer_id", "product", "amount_eur", "deal_ref", "credit_approved?"],
            "resolves": ["TF_CREDIT_LIMIT_CHECK"],
        },
        "earmark_bank_limit": {"description": "Reserves the counterparty limit of a foreign bank (e.g. for adding our "
                                              "confirmation to its credit)", "params": ["bank_bic", "amount_eur", "deal_ref",
                                                                                         "credit_approved?"]},
        "release_limit": {"description": "Releases (part of) the limit and cash collateral held for a deal",
                          "params": ["deal_ref", "amount_eur?"]},
        "customer_exposure": {"description": "Facilities and utilisation of a customer", "params": ["customer_id"]},
    }

    def _facility(self, customer_id: str, product: str):
        for f in self.state.facilities.values():
            if f.customer_id == customer_id and f.product == product:
                return f
        if product == "SURETY":  # Avalkredit covers both guarantees and sureties
            return self._facility(customer_id, "GUARANTEE")
        raise BusError(422, "NO_FACILITY", f"Customer {customer_id} has no {product} facility", self.agent_id)

    async def op_earmark_limit(self, customer_id: str, product: str, amount_eur, deal_ref: str, credit_approved: bool = False):
        amount = money(amount_eur)
        customer = self.state.customers[customer_id]
        fac = self._facility(customer_id, product)
        result = {"facility_id": fac.facility_id, "amount_eur": amount, "methods": [], "cash_collateral_eur": Decimal("0")}
        shortfall = amount - fac.available
        if shortfall > 0 and customer.allow_limit_reallocation:
            for donor in self.state.facilities.values():
                if donor.customer_id == customer_id and product in donor.can_transfer_to and donor.available >= shortfall:
                    donor.limit -= shortfall
                    fac.limit += shortfall
                    result["methods"].append({"method": "LIMIT_REALLOCATION", "from": donor.facility_id,
                                              "to": fac.facility_id, "amount_eur": shortfall})
                    shortfall = Decimal("0")
                    break
        covered_by_cash = Decimal("0")
        if shortfall > 0 and customer.allow_cash_collateral:
            bal = await self.call("tf_core_ledger", "account_balance", {"account_id": customer.current_account_iban},
                                  "CHECK_CASH_COLLATERAL_CAPACITY")
            credit_balance = _d(bal["free_balance"]) - self.state.accounts[customer.current_account_iban].overdraft_limit
            if credit_balance >= shortfall:
                await self.call("tf_core_ledger", "block_funds", {"account_id": customer.current_account_iban,
                                                                   "deal_ref": deal_ref, "amount": shortfall},
                                "BLOCK_CASH_COLLATERAL")
                covered_by_cash = shortfall
                result["methods"].append({"method": "CASH_COLLATERAL", "account": customer.current_account_iban,
                                          "amount_eur": shortfall})
                shortfall = Decimal("0")
        if shortfall > 0:
            total_limits = sum((f.limit for f in self.state.facilities.values() if f.customer_id == customer_id), Decimal("0"))
            max_excess = total_limits * self.state.reference.temporary_excess_max_pct / 100
            if credit_approved or (customer.risk_rating == "LOW" and shortfall <= max_excess):
                result["methods"].append({"method": "CREDIT_APPROVAL" if credit_approved else "DELEGATED_TEMPORARY_EXCESS",
                                          "amount_eur": shortfall})
                fac.limit += shortfall
                fac.temporary_excess[deal_ref] = fac.temporary_excess.get(deal_ref, Decimal("0")) + shortfall
                shortfall = Decimal("0")
            else:
                raise BusError(422, "CREDIT_LIMIT_INSUFFICIENT",
                               f"{fac.facility_id}: requested {amount}, available {fac.available}; shortfall {shortfall} "
                               f"cannot be covered by reallocation, cash collateral or delegated authority",
                               self.agent_id, {"shortfall_eur": shortfall})
        utilise = amount - covered_by_cash
        fac.utilised += utilise
        fac.earmarks[deal_ref] = fac.earmarks.get(deal_ref, Decimal("0")) + utilise
        result["utilised_eur"] = utilise
        result["cash_collateral_eur"] = covered_by_cash
        result["facility_available_after"] = fac.available
        if not result["methods"]:
            result["methods"].append({"method": "WITHIN_LIMIT", "amount_eur": amount})
        return result

    async def op_earmark_bank_limit(self, bank_bic: str, amount_eur, deal_ref: str, credit_approved: bool = False):
        amount = money(amount_eur)
        key = f"BANK:{bank_bic[:8].upper()}"
        fac = next((f for f in self.state.facilities.values() if f.customer_id == key), None)
        if fac is None:
            if not credit_approved:
                raise BusError(422, "NO_FACILITY", f"No counterparty limit for bank {bank_bic[:8]} - credit approval needed",
                               self.agent_id)
            from .models import Facility  # one-off approval: a deal-specific line that runs off with the deal

            fac = Facility(facility_id=f"FAC-BANK-{bank_bic[:8].upper()}", customer_id=key, product="BANK_CONFIRMATION",
                           limit=Decimal("0"))
            self.state.facilities[fac.facility_id] = fac
        shortfall = amount - fac.available
        if shortfall > 0:
            if not credit_approved:
                raise BusError(422, "CREDIT_LIMIT_INSUFFICIENT",
                               f"{fac.facility_id}: requested {amount}, available {fac.available}", self.agent_id,
                               {"shortfall_eur": shortfall})
            fac.limit += shortfall
            fac.temporary_excess[deal_ref] = fac.temporary_excess.get(deal_ref, Decimal("0")) + shortfall
        fac.utilised += amount
        fac.earmarks[deal_ref] = fac.earmarks.get(deal_ref, Decimal("0")) + amount
        return {"facility_id": fac.facility_id, "utilised_eur": amount, "facility_available_after": fac.available}

    async def op_release_limit(self, deal_ref: str, amount_eur=None):
        released = Decimal("0")
        for fac in self.state.facilities.values():
            held = fac.earmarks.get(deal_ref)
            if held is None:
                continue
            rel = held if amount_eur is None else min(held, money(amount_eur))
            fac.earmarks[deal_ref] = held - rel
            if fac.earmarks[deal_ref] <= 0:
                fac.earmarks.pop(deal_ref)
            fac.utilised -= rel
            released += rel
            # a one-off excess approved for this deal shrinks back as the deal runs off (never a permanent limit)
            excess = fac.temporary_excess.get(deal_ref, Decimal("0"))
            if excess > 0:
                cut = min(excess, rel)
                fac.limit -= cut
                fac.temporary_excess[deal_ref] = excess - cut
                if fac.temporary_excess[deal_ref] <= 0:
                    fac.temporary_excess.pop(deal_ref)
        cash_released = Decimal("0")
        if amount_eur is None or released < money(amount_eur):
            remaining = None if amount_eur is None else money(amount_eur) - released
            for acc in self.state.accounts.values():
                if deal_ref in acc.blocked:
                    r = await self.call("tf_core_ledger", "unblock_funds",
                                        {"account_id": acc.account_id, "deal_ref": deal_ref, "amount": remaining},
                                        "RELEASE_CASH_COLLATERAL")
                    cash_released += _d(r["released"])
        return {"deal_ref": deal_ref, "limit_released_eur": released, "cash_collateral_released_eur": cash_released}

    def op_customer_exposure(self, customer_id: str):
        return {"facilities": [f for f in self.state.facilities.values() if f.customer_id == customer_id]}


