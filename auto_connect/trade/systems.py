class SwiftGatewaySystem(BankSystem):
    """SWIFT Alliance gateway: validates and releases FIN messages, archives the .fin files."""
    agent_id = "tf_swift_gateway"
    name = "SWIFT Alliance Gateway (FIN)"
    department = "PAYMENTS_SWIFT"
    peers = ["TRADE_FINANCE", "CORE_BANKING", "COMPLIANCE_AML"]
    allowed_departments = ["TRADE_FINANCE"]
    operations = {
        "release_message": {"description": "Validates and releases an outgoing FIN message (MT7xx/MT1xx/MT2xx)",
                            "params": ["deal_ref", "mt_type", "receiver_bic", "fin_text"],
                            "resolves": ["TF_SWIFT_RELEASE"]},
    }

    def op_release_message(self, deal_ref: str, mt_type: str, receiver_bic: str, fin_text: str):
        if mt_type.startswith("pacs."):  # ISO 20022 MX: must be well-formed XML with the right message definition
            import xml.etree.ElementTree as ET

            try:
                root = ET.fromstring(fin_text.split("?>", 1)[1] if fin_text.startswith("<?xml") else fin_text)
            except ET.ParseError as e:
                raise ValueError(f"ISO 20022 message is not well-formed XML: {e}")
            if not any(el.tag.endswith("MsgDefIdr") and (el.text or "").startswith(mt_type) for el in root.iter()):
                raise ValueError(f"ISO 20022 message is not a {mt_type}")
            return self._queue_or_release(deal_ref, mt_type, receiver_bic, fin_text)
        if not fin_text.startswith("{1:F01") or f"{{2:I{mt_type}" not in fin_text or not fin_text.rstrip().endswith("-}"):
            raise ValueError("FIN message failed format validation")
        for line in fin_text.split("{4:\n", 1)[1].split("\n"):
            if len(line) > 70:
                raise ValueError(f"Line exceeds 65 chars + tag: {line[:40]}...")
        return self._queue_or_release(deal_ref, mt_type, receiver_bic, fin_text)

    def _queue_or_release(self, deal_ref: str, mt_type: str, receiver_bic: str, text: str):
        msg = SwiftMessage(mt_type=mt_type, sender_bic=settings.bank_bic(), receiver_bic=receiver_bic,
                           deal_ref=deal_ref, text=text)
        self.state.swift_messages[msg.message_id] = msg
        if getattr(self.store, "in_transaction", False):  # outbox: released only once the action is committed
            msg.status = "QUEUED"
            queue_outbox(self.state, "SWIFT", {"message_id": msg.message_id}, deal_ref)
            return {"message_id": msg.message_id, "status": "QUEUED_FOR_RELEASE", "file": None}
        self.release(msg.message_id)
        return {"message_id": msg.message_id, "status": "RELEASED_TO_NETWORK", "file": msg.file_path}

    def release(self, message_id: str) -> str:
        """Hands the message to the SWIFT interface (file drop to the Alliance Access / Lite2 hot folder)."""
        msg = self.state.swift_messages[message_id]
        folder = os.path.join(settings.output_dir(), "swift")
        os.makedirs(folder, exist_ok=True)
        iso = msg.mt_type.startswith("pacs.")
        msg.file_path = os.path.join(folder, f"{msg.deal_ref}_{msg.mt_type if iso else 'MT' + msg.mt_type}_{msg.message_id}"
                                             f".{'xml' if iso else 'fin'}")
        with open(msg.file_path, "w", encoding="utf-8" if iso else "ascii", errors="replace") as f:
            f.write(msg.text)
        msg.status = "RELEASED"
        self.store.mark("swift_messages", message_id)
        return msg.file_path


