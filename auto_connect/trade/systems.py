        n = len(self.state.notifications) + 1
        sent = await self.call("tf_email_gateway", "dispatch_message",
                               {"to": [email], "cc": [rm], "subject": f"[{deal_ref}] {subject}", "body": text,
                                "file_stem": f"{deal_ref}_{n:03d}_{''.join(c for c in subject if c.isalnum())[:40]}"},
                               "SEND_CLIENT_EMAIL")
        rec = {"customer_id": customer_id, "deal_ref": deal_ref, "subject": subject, "body": body, "email": email,
               "eml_file": sent.get("eml_file"), "relayed_via_smtp": sent.get("relayed_via_smtp"),
               "actions": actions or {}, "date": self.state.business_date.isoformat()}
        self.state.notifications.append(rec)
        return rec


