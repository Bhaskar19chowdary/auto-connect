class CustomerMasterSystem(BankSystem):
    """Customer master data and KYC status (core banking CIF)."""
    agent_id = "tf_customer_master"
    name = "Customer Master & KYC (CIF)"
    department = "CUSTOMER_DATA"
    peers = ["TRADE_FINANCE", "COMPLIANCE_AML", "CLIENT_ENGAGEMENT"]
    allowed_departments = ["TRADE_FINANCE", "CLIENT_ENGAGEMENT", "CREDIT_RISK"]
    operations = {
        "get_customer": {"description": "Returns customer master data and whether KYC is valid on a date",
                         "params": ["customer_id", "as_of?"], "resolves": ["TF_KYC_VERIFICATION"]},
        "periodic_reviews_due": {"description": "Customers whose KYC review is due within N days", "params": ["within_days?"]},
    }

    def op_get_customer(self, customer_id: str, as_of: Optional[str] = None):
        c = self.state.customers.get(customer_id)
        if not c:
            raise LookupError(f"Customer {customer_id} not found")
        on = _date(as_of) if as_of else self.state.business_date
        issue = None
        if c.kyc_status != "VERIFIED":
            issue = f"KYC status is {c.kyc_status}"
        elif c.kyc_next_review < on:
            issue = f"KYC periodic review overdue since {c.kyc_next_review}"
        return {"customer": c, "kyc_ok": issue is None, "kyc_issue": issue}

    def op_periodic_reviews_due(self, within_days: int = 30):
        limit = self.state.business_date.toordinal() + int(within_days)
        return {"due": [c for c in self.state.customers.values() if c.kyc_next_review.toordinal() <= limit]}


