COUNTRY_NAMES = {
    "KP": ["north korea", "dprk", "democratic people's republic of korea"],
    "IR": ["iran", "islamic republic of iran"],
    "SY": ["syria", "syrian arab republic"],
    "CU": ["cuba"],
    "BY": ["belarus"],
    "RU": ["russia", "russian federation"],
}


def _names_country(text: str, iso: str) -> bool:
    """True when free text (port, address) names the country, e.g. 'Bandar Abbas, Iran'."""
    import re

    low = (text or "").lower()
    return any(re.search(r"(?<![a-z])" + re.escape(n) + r"(?![a-z])", low) for n in COUNTRY_NAMES.get(iso, []))


# writes in external systems and how to undo them if the action fails afterwards
COMPENSATIONS = {
    ("tf_core_ledger", "post_entries"): lambda p, r: ("post_entries", {
        **p, "entries": [{**e, "debit": e["credit"], "credit": e["debit"], "narrative": f"Reversal: {e.get('narrative', '')}"}
                         for e in p.get("entries", [])], "allow_overdraft_excess": True}),
    ("tf_core_ledger", "block_funds"): lambda p, r: ("unblock_funds", {"account_id": p["account_id"], "deal_ref": p["deal_ref"],
                                                                         "amount": p.get("amount")}),
    ("tf_credit_limits", "earmark_limit"): lambda p, r: ("release_limit", {
        "deal_ref": p["deal_ref"], "amount_eur": r.get("utilised_eur") or p.get("amount_eur")}),
    ("tf_credit_limits", "earmark_bank_limit"): lambda p, r: ("release_limit", {"deal_ref": p["deal_ref"],
                                                                                 "amount_eur": p.get("amount_eur")}),
}
def _undo_release(p, r, state):
    """A limit released in the limit system is reserved again (deal's own line, approval flag set)."""
    deal = state.deals.get(p.get("deal_ref", ""))
    amount = r.get("limit_released_eur") if r.get("limit_released_eur") not in (None, "", "0") else p.get("amount_eur")
    if deal is None or not amount or Decimal(str(amount)) <= 0:
        return None
    if deal.product == "EXPORT_LC":
        return ("earmark_bank_limit", {"bank_bic": deal.terms.issuing_bank_bic, "amount_eur": amount,
                                       "deal_ref": deal.ref, "credit_approved": True})
    return ("earmark_limit", {"customer_id": deal.customer_id, "product": deal.product, "amount_eur": amount,
                              "deal_ref": deal.ref, "credit_approved": True})


COMPENSATIONS_WITH_STATE = {
    ("tf_credit_limits", "release_limit"): _undo_release,
    ("tf_core_ledger", "unblock_funds"): lambda p, r, state: ("block_funds", {
        "account_id": p["account_id"], "deal_ref": p["deal_ref"], "amount": r.get("released") or p.get("amount")}),
}
NOT_COMPENSABLE: set = set()


def queue_outbox(state, kind: str, payload: Dict[str, Any], deal_ref: Optional[str]) -> Dict[str, Any]:
    from .models import new_id, utcnow

    item = {"id": new_id("OUT"), "kind": kind, "status": "PENDING", "deal_ref": deal_ref, "payload": payload,
            "attempts": 0, "created_at": utcnow(), "sent_at": None, "error": None}
    state.outbox[item["id"]] = item
    return item


def _deal_ref_of(subject: str) -> Optional[str]:
    m = re.match(r"\[([A-Z]{3}\d{10})\]", subject or "")
    return m.group(1) if m else None


class SanctionsScreeningSystem(BankSystem):
    """Screens parties, countries, ports, vessels and goods against sanctions/embargo and dual-use lists."""
    agent_id = "tf_sanctions_screening"
    name = "Sanctions & Embargo Screening"
    department = "COMPLIANCE_AML"
    peers = ["TRADE_FINANCE", "PAYMENTS_SWIFT"]
    allowed_departments = ["TRADE_FINANCE", "PAYMENTS_SWIFT"]
    operations = {
        "screen_parties": {
            "description": "Screens a trade transaction (parties, countries, ports, vessel, goods). "
                           "Returns CLEAR, CLEAR_WITH_DISCOUNTED_ALERTS, REVIEW_REQUIRED or BLOCKED.",
            "params": ["deal_ref", "parties", "places?", "goods?", "vessel_imo?", "export_license_ref?"],
            "resolves": ["TF_SANCTIONS_SCREENING"],
        },
    }

    def op_screen_parties(self, deal_ref: str, parties: List[Dict[str, Any]], places: Optional[List[str]] = None,
                          goods: str = "", vessel_imo: Optional[str] = None, export_license_ref: Optional[str] = None):
        ref = self.state.reference
        index = self.reference.index if self.reference else None  # live EU + OFAC lists
        if self.reference is not None and self.reference.enabled and index is None:
            # never screen a real transaction against an incomplete list: the deal waits in the operations queue
            raise BusError(503, "SANCTIONS_LISTS_NOT_LOADED",
                           "EU / OFAC sanctions lists are still loading" if not self.reference.attempted else
                           "EU / OFAC sanctions lists could not be loaded (see /api/v1/tf/reference)", self.agent_id)
        alerts: List[Dict[str, Any]] = []

        def alert(kind, subject, decision, reason, score=None, entry=None):
            alerts.append({"type": kind, "subject": subject, "decision": decision, "reason": reason,
                           "score": round(score, 3) if score is not None else None, "list_entry": entry})

        for p in parties:
            pname, pcountry = p.get("name", ""), (p.get("country") or "").upper()
            if pcountry in ref.embargoed_countries:
                alert("COUNTRY", f"{p.get('role', 'party')}: {pname}", "HIT",
                      f"Country {pcountry}: {ref.embargoed_countries[pcountry]}")
            for region in ref.embargoed_regions:
                if region in (p.get("address", "") or "").lower():
                    alert("REGION", pname, "HIT", f"Address in embargoed region '{region}'")
            for iso, measure in ref.embargoed_countries.items():
                if iso != pcountry and _names_country(p.get("address", ""), iso):
                    alert("COUNTRY", f"{p.get('role', 'party')}: {pname}", "HIT",
                          f"Address names embargoed country {iso}: {measure}")
            for e in ref.sanctions_entities:
                score = max([similarity(pname, e.name)] + [similarity(pname, a) for a in e.aliases])
                if score >= ref.sanctions_hit_threshold and (not pcountry or e.country == pcountry):
                    alert("NAME", pname, "HIT", f"Matches {e.list_name} entry {e.entry_id} '{e.name}'", score, e.entry_id)
                elif score >= ref.sanctions_hit_threshold:
                    alert("NAME", pname, "REVIEW", f"Strong name match with '{e.name}' ({e.list_name}, {e.country}) "
                          f"but party domiciled in {pcountry} - compliance must confirm identity", score, e.entry_id)
                elif score >= ref.sanctions_review_threshold:
                    if e.country != pcountry and pcountry:
                        alert("NAME", pname, "DISCOUNTED",
                              f"Similar to '{e.name}' ({e.country}) but party domiciled in {pcountry}: false positive "
                              f"discounted by secondary identifier (country)", score, e.entry_id)
                    else:
                        alert("NAME", pname, "REVIEW", f"Possible match with '{e.name}' ({e.list_name})", score, e.entry_id)
            if index and pname:
                for score, e in index.search(pname, ref.sanctions_review_threshold):
                    known, same = bool(e.countries), pcountry in e.countries
                    where = "/".join(sorted(e.countries)) or "country unknown"
                    if score >= ref.sanctions_hit_threshold and (same or not pcountry):
                        alert("NAME", pname, "HIT", f"Matches {e.list_name} entry {e.entry_id} '{e.name}' ({where})", score, e.entry_id)
                    elif score >= ref.sanctions_hit_threshold:
                        alert("NAME", pname, "REVIEW", f"Strong name match with '{e.name}' ({e.list_name}, {where}) - "
                              f"compliance must confirm identity", score, e.entry_id)
                    elif known and pcountry and not same:
                        alert("NAME", pname, "DISCOUNTED", f"Similar to '{e.name}' ({e.list_name}, {where}) but party "
                              f"domiciled in {pcountry}: false positive discounted by secondary identifier", score, e.entry_id)
                    else:
                        alert("NAME", pname, "REVIEW", f"Possible match with '{e.name}' ({e.list_name}, {where})", score, e.entry_id)
        for place in places or []:
            low = (place or "").lower()
            for region in ref.embargoed_regions:
                if region in low:
                    alert("PLACE", place, "HIT", f"Port/place in embargoed region '{region}'")
            for iso, measure in ref.embargoed_countries.items():
                if _names_country(place, iso):
                    alert("PLACE", place, "HIT", f"Port/place in embargoed country {iso}: {measure}")
        if vessel_imo and vessel_imo.replace(" ", "").upper() in ref.blocked_vessels:
            alert("VESSEL", vessel_imo, "HIT", "Vessel on sanctions list")
        elif vessel_imo and index and re.sub(r"\D", "", vessel_imo) in index.vessels:
            alert("VESSEL", vessel_imo, "HIT", f"Vessel on {index.vessels[re.sub(r'[^0-9]', '', vessel_imo)]}")
        low_goods = (goods or "").lower()
        for kw in ref.dual_use_keywords:
            if kw in low_goods:
                if export_license_ref:
                    alert("GOODS", kw, "DISCOUNTED", f"Dual-use item covered by export licence {export_license_ref}")
                else:
                    alert("GOODS", kw, "REVIEW", "Possible dual-use item (EU 2021/821) without export licence reference")

        decisions = {a["decision"] for a in alerts}
        if "HIT" in decisions:
            result = "BLOCKED"
        elif "REVIEW" in decisions:
            result = "REVIEW_REQUIRED"
        elif alerts:
            result = "CLEAR_WITH_DISCOUNTED_ALERTS"
        else:
            result = "CLEAR"
        case = {"case_id": f"SCR-{secrets.token_hex(4).upper()}", "deal_ref": deal_ref,
                "screened_on": self.state.business_date.isoformat(), "result": result, "alerts": alerts,
                "parties_screened": len(parties),
                "lists": sorted({e.list_name for e in ref.sanctions_entities}) +
                         (["EU consolidated list (FSF)", "OFAC SDN"] if index else [])}
        self.state.sanctions_cases.append(case)
        return case


