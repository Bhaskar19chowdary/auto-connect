class MarketDataSystem(BankSystem):
    """FX reference rates (replace with the Bloomberg/Refinitiv feed in production)."""
    agent_id = "tf_market_data"
    name = "Market Data - FX Reference Rates"
    department = "TREASURY_MARKETS"
    peers = ["TRADE_FINANCE", "CREDIT_RISK"]
    allowed_departments = ["*"]
    operations = {
        "fx_rate": {"description": "EUR value of one unit of a currency", "params": ["currency"]},
        "convert": {"description": "Converts an amount between currencies", "params": ["amount", "from_currency", "to_currency"]},
    }

    def rates(self) -> Dict[str, Decimal]:
        """Bank's currencies valued at the latest ECB reference rates when loaded, else the stored rates."""
        rates = dict(self.state.reference.fx_eur_per_unit)
        live = self.reference.fx if self.reference else None
        if live:
            rates.update({c: v for c, v in live[1].items() if c in rates})
        return rates

    def as_of(self):
        live = self.reference.fx if self.reference else None
        return live[0] if live else self.state.reference.fx_rates_as_of

    def op_fx_rate(self, currency: str):
        rates = self.rates()
        if currency not in rates:
            raise LookupError(f"No FX rate for {currency}")
        return {"currency": currency, "eur_per_unit": rates[currency], "as_of": self.as_of(),
                "source": "ECB euro reference rates" if self.reference and self.reference.fx else "bank stored rates"}

    def op_convert(self, amount, from_currency: str, to_currency: str):
        rates = self.rates()
        if from_currency not in rates or to_currency not in rates:
            raise LookupError(f"No FX rate for {from_currency}/{to_currency}")
        eur = _d(amount) * rates[from_currency]
        return {"amount": money(eur / rates[to_currency]), "currency": to_currency,
                "rate": (rates[from_currency] / rates[to_currency]).quantize(Decimal("0.000001"))}


