class BusError(Exception):
    def __init__(self, status_code: int, code: str, detail: str, system: str = "", data: Optional[dict] = None):
        super().__init__(f"{system}:{code}: {detail}")
        self.status_code = status_code
        self.code = code
        self.detail = detail
        self.system = system
        self.data = data or {}


class TradeBus:
    """A2A request/response bus over the vault-protected universal executor."""

    def __init__(self, vault, mesh, executor):
        self.vault = vault
        self.mesh = mesh
        self.executor = executor

    def _department(self, agent_id: str) -> str:
        card = self.mesh.get_agent(agent_id)
        return card.banking_department if card else "TRADE_FINANCE"

    router = None  # IntegrationManager, set when the trade engine starts
    store = None  # bank books; while an action's transaction is open, outgoing side effects wait in the outbox
    OUTBOX_OPERATIONS = {("tf_swift_gateway", "release_message"), ("tf_email_gateway", "dispatch_message"),
                         ("tf_client_portal", "notify_client")}
    compensations = None  # list while an action runs: how to undo each write already done in an external system

    async def call(self, sender: str, target: str, operation: str, params: Dict[str, Any],
                   intent: Optional[str] = None, _no_route: bool = False, _from_outbox: bool = False) -> Dict[str, Any]:
        params = to_jsonable(params)
        # A real (not simulated) SWIFT / email system is only called after the action is committed (outbox)
        external = not self.executor.has_in_process_handler(target) or (
            self.router is not None and not _no_route and self.router.active_for(target) is not None)
        if (target, operation) in self.OUTBOX_OPERATIONS and external and not _from_outbox and not _no_route \
                and self.store is not None and getattr(self.store, "in_transaction", False):
            item = queue_outbox(self.store.state, "BUS", {"sender": sender, "target": target, "operation": operation,
                                                          "params": params, "intent": intent}, params.get("deal_ref"))
            return {"message_id": item["id"], "status": "QUEUED_IN_OUTBOX", "outbox_id": item["id"]}
        # A newly connected application that passed its contract tests serves this role
        if self.router is not None and not _no_route:
            binding = self.router.active_for(target)
            if binding is not None and binding.agent_id != sender:
                try:
                    result = to_jsonable(await self.router.call_bound(binding, sender, operation, params, intent))
                    self._record_compensation(sender, target, operation, params, result, _from_outbox)
                    return result
                except BusError as e:
                    from .integration import BINDABLE_ROLES

                    read_only = operation in BINDABLE_ROLES.get(target, {}).get("read_only", set())
                    transient = e.status_code >= 500 or e.status_code in (408, 429) or \
                        e.code in ("NETWORK", "UNPARSEABLE_RESPONSE")
                    if not read_only or not transient:
                        raise
                    await self.router.on_failover(binding, sender, target, operation, e)
                    # fall through: the incumbent system answers (read-only operation, safe to repeat)
        try:
            res = await self.executor.execute_dynamic_call(
                app_id=target,
                endpoint_path=f"/api/v1/{target}/{operation}",
                http_method="POST",
                parameters=params,
                requester_department=self._department(sender),
            )
        except PermissionError as e:
            self.mesh.send_a2a_message(sender, target, intent or operation.upper(), params,
                                       {"error": "ACCESS_DENIED", "detail": str(e)})
            raise BusError(403, "ACCESS_DENIED", str(e), target)
        if isinstance(res.get("data"), dict):
            data = res["data"]
        elif "data" in res:
            data = {"value": res["data"]}
        else:
            data = {"error": res.get("error", "no response")}
        self.mesh.send_a2a_message(sender, target, intent or operation.upper(), params, data or {"status": "NO_CONTENT"})
        status = res.get("status_code", 500)
        if status >= 400:
            raise BusError(status, data.get("code", "NETWORK" if res.get("network_error") else "SYSTEM_ERROR"),
                           data.get("detail") or data.get("error") or str(data), target, data)
        if external:
            self._record_compensation(sender, target, operation, params, data, _from_outbox)
        return data

    def _record_compensation(self, sender, target, operation, params, result, from_outbox):
        """Remembers how to undo a write in an external system, in case the action fails later (saga)."""
        if self.compensations is None or from_outbox:
            return
        rule = COMPENSATIONS.get((target, operation))
        stateful = COMPENSATIONS_WITH_STATE.get((target, operation))
        if stateful is not None:
            undo = stateful(params, result or {}, self.store.state)
            if undo:
                self.compensations.append({"sender": sender, "target": target, "operation": undo[0], "params": undo[1],
                                           "undoes": operation})
        elif rule is not None:
            op, comp_params = rule(params, result or {})
            self.compensations.append({"sender": sender, "target": target, "operation": op, "params": comp_params,
                                       "undoes": operation})
        elif (target, operation) in NOT_COMPENSABLE:
            self.compensations.append({"sender": sender, "target": target, "operation": None, "params": params,
                                       "undoes": operation})


class BankSystem:
    agent_id = ""
    name = ""
    department = ""
    peers: List[str] = []
    allowed_departments: List[str] = ["TRADE_FINANCE"]
    operations: Dict[str, Dict[str, Any]] = {}
    reference = None  # ReferenceDataService (live ECB rates, EU/OFAC lists), set by the trade engine

    def __init__(self, store: StateStore, bus: TradeBus):
        self.store = store
        self.bus = bus

    @property
    def state(self):
        return self.store.state

    async def handle(self, method: str, path: str, params: Dict[str, Any], headers: Dict[str, str]) -> Dict[str, Any]:
        op = path.rstrip("/").split("/")[-1]
        fn = getattr(self, f"op_{op}", None)
        if fn is None:
            return {"status_code": 404, "data": {"code": "UNKNOWN_OPERATION", "detail": f"{self.agent_id} has no operation '{op}'"}}
        try:
            result = fn(**(params or {}))
            if inspect.isawaitable(result):
                result = await result
            return {"status_code": 200, "data": to_jsonable(result)}
        except BusError as e:
            return {"status_code": e.status_code, "data": {"code": e.code, "detail": e.detail, **to_jsonable(e.data)}}
        except (KeyError, LookupError) as e:
            return {"status_code": 404, "data": {"code": "NOT_FOUND", "detail": str(e)}}
        except (ValueError, TypeError) as e:
            return {"status_code": 400, "data": {"code": "BAD_REQUEST", "detail": str(e)}}

    async def call(self, target: str, operation: str, params: Dict[str, Any], intent: Optional[str] = None):
        return await self.bus.call(self.agent_id, target, operation, params, intent)

    # -- discovery artefacts -------------------------------------------
    def agent_card(self) -> AutoGeneratedAgentCard:
        tools = []
        for op, spec in self.operations.items():
            params = spec.get("params", [])
            tools.append(DiscoveredEndpointTool(
                tool_name=op,
                http_method="POST",
                endpoint_path=f"/api/v1/{self.agent_id}/{op}",
                description=spec["description"],
                required_parameters=[p for p in params if not p.endswith("?")],
                optional_parameters=[p[:-1] for p in params if p.endswith("?")],
                can_resolve_issues=spec.get("resolves", []),
                mcp_tool_schema={
                    "type": "object",
                    "properties": {p.rstrip("?"): {"type": "string"} for p in params},
                    "required": [p for p in params if not p.endswith("?")],
                },
            ))
        return AutoGeneratedAgentCard(
            agent_id=self.agent_id,
            application_name=self.name,
            banking_department=self.department,
            system_instruction=f"You operate {self.name}. {self.__doc__.strip() if self.__doc__ else ''}",
            discovered_tools=tools,
            peer_departments_to_collaborate_with=self.peers,
        )

    def openapi(self) -> Dict[str, Any]:
        return {
            "openapi": "3.1.0",
            "info": {"title": self.name, "version": "2.0", "description": (self.__doc__ or "").strip()},
            "paths": {
                f"/api/v1/{self.agent_id}/{op}": {
                    "post": {
                        "summary": spec["description"],
                        "requestBody": {"content": {"application/json": {"schema": {
                            "type": "object",
                            "properties": {p.rstrip("?"): {"type": "string"} for p in spec.get("params", [])},
                        }}}},
                    }
                }
                for op, spec in self.operations.items()
            },
        }


def _d(v) -> Decimal:
    return Decimal(str(v))


def _date(v) -> date:
    return v if isinstance(v, date) else date.fromisoformat(str(v))


