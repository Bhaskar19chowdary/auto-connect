class CoreLedgerSystem(BankSystem):
    """Core banking ledger: double-entry postings, balances, blocked funds (cash collateral)."""
    agent_id = "tf_core_ledger"
    name = "Core Banking Ledger"
    department = "CORE_BANKING"
    peers = ["TRADE_FINANCE", "CREDIT_RISK", "PAYMENTS_SWIFT"]
    allowed_departments = ["TRADE_FINANCE", "CREDIT_RISK"]
    operations = {
        "post_entries": {"description": "Posts balanced double-entry bookings atomically",
                         "params": ["deal_ref", "entries", "value_date?", "allow_overdraft_excess?"],
                         "resolves": ["TF_ACCOUNTING_POSTING"]},
        "account_balance": {"description": "Balance, free balance and blocked amounts of an account", "params": ["account_id"]},
        "block_funds": {"description": "Blocks customer funds as cash collateral for a deal", "params": ["account_id", "deal_ref", "amount"]},
        "unblock_funds": {"description": "Releases cash collateral blocked for a deal", "params": ["account_id", "deal_ref", "amount?"]},
    }

    def op_post_entries(self, deal_ref: str, entries: List[Dict[str, Any]], value_date: Optional[str] = None,
                        allow_overdraft_excess: bool = False):
        accounts = self.state.accounts
        vd = _date(value_date) if value_date else self.state.business_date
        prepared = []
        debits: Dict[str, Decimal] = {}
        for e in entries:
            dr, cr, amt = e["debit"], e["credit"], money(e["amount"])
            if amt <= 0:
                raise ValueError("Posting amount must be positive")
            if dr not in accounts or cr not in accounts:
                raise LookupError(f"Unknown account in posting {dr} / {cr}")
            if accounts[dr].currency != accounts[cr].currency:
                raise ValueError(f"Currency mismatch {dr}({accounts[dr].currency}) / {cr}({accounts[cr].currency})")
            debits[dr] = debits.get(dr, Decimal("0")) + amt
            prepared.append((dr, cr, amt, e.get("narrative", "")))
        for acc_id, total in debits.items():
            acc = accounts[acc_id]
            if acc.owner != "BANK" and not allow_overdraft_excess and acc.free_balance < total:
                raise BusError(422, "INSUFFICIENT_FUNDS",
                               f"Account {acc_id} free balance {acc.free_balance} < {total}", self.agent_id,
                               {"free_balance": acc.free_balance, "required": total})
        ids = []
        for dr, cr, amt, narrative in prepared:
            accounts[dr].balance -= amt
            accounts[cr].balance += amt
            entry = LedgerEntry(booking_date=self.state.business_date, value_date=vd, deal_ref=deal_ref,
                                debit_account=dr, credit_account=cr, amount=amt, currency=accounts[dr].currency,
                                narrative=narrative)
            self.state.ledger.append(entry)
            ids.append(entry.entry_id)
        return {"entry_ids": ids, "posted": len(ids)}

    def op_account_balance(self, account_id: str):
        acc = self.state.accounts[account_id]
        return {"account_id": account_id, "currency": acc.currency, "balance": acc.balance,
                "free_balance": acc.free_balance, "blocked": acc.blocked}

    def op_block_funds(self, account_id: str, deal_ref: str, amount):
        acc = self.state.accounts[account_id]
        amt = money(amount)
        if acc.free_balance - acc.overdraft_limit < amt:
            raise BusError(422, "INSUFFICIENT_FUNDS", f"Cannot block {amt}: credit balance available "
                           f"{acc.free_balance - acc.overdraft_limit}", self.agent_id)
        acc.blocked[deal_ref] = acc.blocked.get(deal_ref, Decimal("0")) + amt
        return {"account_id": account_id, "blocked_for_deal": acc.blocked[deal_ref]}

    def op_unblock_funds(self, account_id: str, deal_ref: str, amount=None):
        acc = self.state.accounts[account_id]
        current = acc.blocked.get(deal_ref, Decimal("0"))
        release = current if amount is None else min(current, money(amount))
        remaining = current - release
        if remaining > 0:
            acc.blocked[deal_ref] = remaining
        else:
            acc.blocked.pop(deal_ref, None)
        return {"account_id": account_id, "released": release, "still_blocked": remaining}


