    @app.post("/api/v1/apps/{agent_id}/invoke")
    async def invoke_application_tool(agent_id: str, payload: Dict[str, Any] = Body(...)):
        """Calls one operation of a connected application (used by the generated operator console)."""
        card = mesh.get_agent(agent_id)
        if not card:
            raise HTTPException(404, f"Unknown agent '{agent_id}'")
        tool = next((t for t in card.discovered_tools if t.tool_name == payload.get("tool_name")), None)
        if not tool:
            raise HTTPException(404, "Unknown tool")
        params = {k: v for k, v in (payload.get("parameters") or {}).items() if v not in ("", None)}
        missing = [p for p in tool.required_parameters if p not in params]
        if missing:
            raise HTTPException(422, f"Missing required parameters: {missing}")
        res = await executor.execute_dynamic_call(app_id=agent_id, endpoint_path=tool.endpoint_path,
                                                  http_method=tool.http_method, parameters=params,
                                                  requester_department=card.banking_department)
        mesh.send_a2a_message("operator_console", agent_id, f"CONSOLE_{tool.tool_name.upper()}", params,
                              res.get("data") if isinstance(res.get("data"), dict) else {"value": res.get("data")})
        return res

