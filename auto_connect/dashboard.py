    @app.get("/api/v1/ecosystem")
    async def get_ecosystem():
        agents = [c.model_dump() for c in mesh.list_agents()]
        mcp_tools = mesh.export_mcp_tool_definitions()
        credentials = vault.list_credentials()
        audit_trail = vault.audit_trail
