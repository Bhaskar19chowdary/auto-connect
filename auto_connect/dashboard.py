    # Trade Finance Operations Engine (LC / guarantees / sureties end to end) + its bank systems
    from .trade.api import mount_trade_api

    app.state.users = users
    mount_trade_api(app, vault, mesh, executor)

    # Optional API key protection (AUTO_CONNECT_API_KEY). Portal decision links are HMAC-signed instead.
    from .settings import api_key as _api_key, payment_message_format

    @app.middleware("http")
    async def _security(request, call_next):
        """Named users + role permissions (production) or the single demo key; every change is audited."""
        path, method = request.url.path, request.method
        guarded = path.startswith(("/api/", "/agents/", "/.well-known/"))
        user = None
        if guarded and users.enabled:
            user = users.authenticate(request.headers.get("X-API-Key"))
            if not user:
                audit.record(user="anonymous", method=method, path=path, status=401)
                return JSONResponse(status_code=401, content={"detail": "Missing or invalid personal X-API-Key"})
            if not allowed(user, method, path):
                audit.record(user=user["user_id"], method=method, path=path, status=403)
                return JSONResponse(status_code=403, content={"detail": f"Your roles {user['roles']} do not allow {method} {path}"})
            request.state.user = user
        elif guarded and _api_key():
            supplied = request.headers.get("X-API-Key") or request.query_params.get("api_key")
            if supplied != _api_key():
                return JSONResponse(status_code=401, content={"detail": "Missing or invalid X-API-Key"})
        response = await call_next(request)
        if method not in ("GET", "HEAD", "OPTIONS"):
            audit.record(user=user["user_id"] if user else "demo-mode", method=method, path=path,
                         status=response.status_code)
        return response

    @app.get("/health")
    async def health():
        return {"status": "UP"}

    @app.get("/ready")
    async def ready():
        eng = app.state.trade_engine
        ref = eng.reference.summary()
