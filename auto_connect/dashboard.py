    @app.post("/api/v1/vault/add")
    async def add_vault_credential(payload: Dict[str, Any] = Body(...)):
        """Adds a bank application credential to the Zero-Trust Vault."""
        app_id = payload.get("app_id")
        if not app_id:
            raise HTTPException(status_code=400, detail="Missing app_id")

        cred = VaultCredential(
            app_id=app_id,
            base_url=payload.get("base_url", "https://api.internal.bank.eu"),
            auth_type=payload.get("auth_type", "Bearer"),
            token=payload.get("token"),
            client_cert=payload.get("client_cert"),
            allowed_departments=payload.get("allowed_departments", ["*"]),
        )
        vault.store_credential(cred)

        # Persist to vault_credentials.json
        vault_file = vault_file_location()
        try:
            vault.save_to_json(vault_file)
        except Exception as e:
            logger.warning(f"Could not persist vault_credentials.json: {e}")

        return {"status": "SUCCESS", "message": f"Credential for {app_id} stored in Zero-Trust Vault"}

