    def _fail(app_id: str, message: str, pipeline: List[Dict[str, Any]], extra: Dict[str, Any] = None):
        vault.remove_credential(app_id)
        mesh.unregister_agent(app_id)
        executor.unregister_in_process_handler(app_id)
        brain.analysis_log.pop(app_id, None)
        _persist_vault()
        return {"status": "ERROR", "message": message, "pipeline": pipeline, **(extra or {})}

    @app.post("/api/v1/apps/connect")
    async def connect_new_application(payload: Dict[str, Any] = Body(...)):
        """
        Connects a bank application.
        - Real application: give its URL (and optionally the exact OpenAPI URL). The description of the API is
          discovered automatically, analysed (Gemini or rules), probed read-only, turned into an agent with
          tools and a console, and - if it fits a trade-engine role and passes contract tests - plugged in.
        - preset_type: connects one of the built-in simulated demo systems.
        """
        app_name = (payload.get("app_name") or "").strip() or "Enterprise Banking Service"
        preset = (payload.get("preset_type") or "custom").strip()
        base_url = (payload.get("base_url") or "").strip().rstrip("/")
        spec_url = (payload.get("spec_url") or "").strip() or None
        auth_type = payload.get("auth_type", "Bearer")
        token = payload.get("token", "")
        client_cert = payload.get("client_cert", "")
        raw_spec = payload.get("raw_spec")
        custom_endpoints = [e for e in (payload.get("custom_endpoints") or []) if e]

        slug = "".join(c if c.isalnum() else "_" for c in app_name.lower()).strip("_")
        app_id = payload.get("app_id") or f"agent_{slug[:30]}"
        if app_id.startswith("tf_"):
            app_id = "agent_" + app_id

        # Step 1: Zero-Trust Security Gate
        extra = {k: payload[k] for k in ("oauth_token_url", "oauth_client_id", "oauth_client_secret", "oauth_scope",
                                          "client_cert_file", "client_key_file", "ca_bundle_file") if payload.get(k)}
        cred = VaultCredential(app_id=app_id, base_url=base_url or "https://api.internal.bank.eu", auth_type=auth_type,
                               token=token, client_cert=client_cert, allowed_departments=["*"], **extra)
        try:
            vault.store_credential(cred)
        except ValueError as err:
            return {"status": "ERROR", "message": str(err),
                    "pipeline": [{"step": "Zero-Trust Security Gate", "detail": f"❌ {err}", "status": "REJECTED_401"}]}
        gate = {"step": "Zero-Trust Security Gate",
                "detail": f"Provisioned {auth_type} credentials in secure vault with department RBAC rules.",
                "status": "VERIFIED"}

        # ---------------- simulated demo system ----------------
        if preset in PRESETS and prod:
            return _fail(app_id, "Simulated demo systems cannot be connected in production", [gate])
        if preset in PRESETS:
            spec, handler = PRESETS[preset]
            _persist_vault()
            executor.register_in_process_handler(app_id, handler)
            card = await brain.analyze_and_assimilate_application_async(spec, app_id)
            if card.discovered_tools:
                probe_tool = card.discovered_tools[0]
                probe_res = await executor.execute_dynamic_call(
                    app_id=app_id, endpoint_path=probe_tool.endpoint_path, http_method=probe_tool.http_method,
                    parameters={p: f"test_{p}" for p in probe_tool.required_parameters},
                    requester_department=card.banking_department)
                if probe_res.get("status_code") in [401, 403]:
                    detail = (probe_res.get("data") or {}).get("error") if isinstance(probe_res.get("data"), dict) else None
                    detail = detail or f"Target bank gateway returned HTTP {probe_res.get('status_code')} Unauthorized."
                    return _fail(app_id, f"Authentication Probe Rejected: {detail}", [
                        gate, {"step": "Target Gateway Authentication Probe", "detail": f"❌ {detail}", "status": "REJECTED_401"}])
            analysis = brain.analysis_log.get(app_id, {})
            engine_txt = f"Gemini ({analysis.get('model')})" if analysis.get("engine") == "GEMINI" else "banking rules engine"
            return {
                "status": "SUCCESS",
                "simulated": True,
                "message": f"Simulated demo system '{app_name}' connected (answers come from a built-in simulator, "
                           f"not the real product).",
                "mode": "SIMULATED_DEMO",
                "pipeline": [
                    gate,
                    {"step": "Schema Introspection & Probing",
                     "detail": f"Extracted {len(card.discovered_tools)} operational endpoints (built-in demo specification).",
                     "status": "VERIFIED"},
                    {"step": "Gemini Semantic Mapping",
                     "detail": f"Classified into '{card.banking_department}' by {engine_txt}.", "status": "VERIFIED"},
                    {"step": "A2A Agent Card Generation",
                     "detail": f"Spawned specialist agent '{card.agent_id}' and published to /.well-known/agent.json.",
                     "status": "VERIFIED"},
                    {"step": "Autonomous Mesh Integration",
                     "detail": "Connected to the mesh (simulated system - calls are answered locally).", "status": "ACTIVE"},
                ],
                "agent_card": card.model_dump(),
                "analysis": analysis,
                "console_url": f"/apps/{app_id}",
            }

        # ---------------- real application, connected by URL ----------------
        if not base_url and not spec_url and not raw_spec:
            return _fail(app_id, "Enter the application's URL (or its OpenAPI URL).", [gate])
        executor.unregister_in_process_handler(app_id)
        pipeline: List[Dict[str, Any]] = [gate]
        try:
            headers = await executor.auth_headers(app_id, "TRADE_FINANCE")
        except PermissionError as e:  # e.g. OAuth token endpoint refused the client credentials
            return _fail(app_id, f"Authentication Probe Rejected: {e}", [gate, {"step": "Identity Provider Token",
                                                                                "detail": f"❌ {e}", "status": "REJECTED_401"}])

        # Step 2: API discovery
        from .onboarding import DiscoveryError, discover_spec, probe
        from .introspector import ApplicationIntrospector

        tried: List[Dict[str, Any]] = []
        manual = False
        if isinstance(raw_spec, dict) and raw_spec.get("paths"):
            spec, found_at = raw_spec, "specification pasted by operator"
        else:
            try:
                spec, found_at, tried = await discover_spec(executor, base_url, spec_url, headers, app_id)
            except DiscoveryError as e:
                tried = e.tried
                if custom_endpoints and not str(e).startswith(("401", "Cannot reach")):
                    manual = True
                    found_at = "endpoints declared manually (no OpenAPI description published)"
                    spec = {"openapi": "3.1.0", "info": {"title": app_name, "version": "1.0"},
                            "paths": {"/" + ep.lstrip("/"): {"post": {"summary": f"{ep} on {app_name}"}} for ep in custom_endpoints}}
                else:
                    status = "REJECTED_401" if str(e).startswith("401") else "NOT_FOUND"
                    return _fail(app_id, str(e), pipeline + [
                        {"step": "API Discovery", "detail": f"❌ {e} (tried {len(tried)} locations)", "status": status}],
                        {"discovery_attempts": tried})
        # if the operator gave only the spec URL, take the base URL from the spec's servers section
        if not base_url:
            servers = spec.get("servers") or []
            base_url = (servers[0].get("url") if servers and isinstance(servers[0], dict) else "") or ""
            if spec.get("host"):
                base_url = f"{(spec.get('schemes') or ['https'])[0]}://{spec['host']}{spec.get('basePath', '')}"
            vault._credentials[app_id].base_url = base_url.rstrip("/")
        pipeline.append({"step": "API Discovery", "detail": f"API description found: {found_at}",
                         "status": "MANUAL" if manual else "VERIFIED"})

        # Step 3: parse + semantic analysis (Gemini if configured, else rules)
        parsed = ApplicationIntrospector.parse_openapi_spec(spec)
        if not parsed["endpoints"]:
            return _fail(app_id, "The API description contains no operations.", pipeline)
        spec.setdefault("info", {})
        if not spec["info"].get("title"):
            spec["info"]["title"] = app_name
        card = await brain.analyze_and_assimilate_application_async(spec, app_id)
        card.application_name = app_name if payload.get("app_name") else card.application_name
        analysis = brain.analysis_log.get(app_id, {})
        if analysis.get("engine") == "GEMINI":
            engine_txt = f"Gemini ({analysis.get('model')})"
        elif analysis.get("gemini_error"):
            engine_txt = f"banking rules engine (Gemini failed: {analysis['gemini_error'][:120]})"
        else:
            engine_txt = "banking rules engine (no Gemini key configured)"
        pipeline.append({"step": "Schema Introspection",
                         "detail": f"{len(parsed['endpoints'])} operations read from the API description.", "status": "VERIFIED"})
        pipeline.append({"step": "Semantic Mapping",
                         "detail": f"Classified as '{card.banking_department}' by {engine_txt}.", "status": "VERIFIED"})
        pipeline.append({"step": "A2A Agent Card Generation",
                         "detail": f"Agent '{card.agent_id}' with {len(card.discovered_tools)} tools published to /.well-known/agent.json.",
                         "status": "VERIFIED"})

        # Step 4: read-only live probe
        pr = await probe(executor, app_id, parsed, card.banking_department, found_at if found_at.startswith("http") else None, headers)
        if pr["auth_rejected"]:
            return _fail(app_id, f"Authentication Probe Rejected: the application returned HTTP {pr['status_code']}",
                         pipeline + [{"step": "Live Authentication Probe", "detail": f"❌ {pr['endpoint']} -> HTTP {pr['status_code']}",
                                      "status": "REJECTED_401"}])
        if pr["unreachable"] or not pr["ok"]:
            return _fail(app_id, f"Live probe failed: {pr['detail']}",
                         pipeline + [{"step": "Live Connectivity Probe", "detail": f"❌ {pr['endpoint']}: {pr['detail']}",
                                      "status": "FAILED"}])
        pipeline.append({"step": "Live Connectivity & Auth Probe",
                         "detail": f"{pr['endpoint'] or 'no call'} -> {pr['status_code'] or '-'} ({pr['detail']})",
                         "status": "VERIFIED" if pr["auth_verified"] else "PARTIAL"})

        # Step 5: plug into the trade finance engine (role detection + live contract tests)
        binding = await app.state.trade_engine.integration.try_bind(card, parsed)
        denied = next((t for t in binding.contract_tests if not t["passed"]
                       and any(f"HTTP {c}" in t["detail"] for c in (401, 403))), None)
        if denied:  # the read-only probe could not test auth (no GET operation) but the live calls were refused
            app.state.trade_engine.integration.unbind(app_id)
            return _fail(app_id, f"Authentication Probe Rejected: {denied['detail']}", pipeline + [
                {"step": "Trade Engine Contract Tests", "detail": f"❌ {denied['detail']}", "status": "REJECTED_401"}])
        pipeline.append({"step": "Trade Engine Binding", "detail": binding.reason,
                         "status": binding.status if binding.status == "ACTIVE" else "STANDALONE"})
        pipeline.append({"step": "Operator Console", "detail": f"Generated at /apps/{app_id}", "status": "ACTIVE"})
        _persist_vault()
        live_apps[app_id] = {"base_url": base_url, "spec_found_at": found_at, "parsed": parsed, "probe": pr,
                             "analysis": analysis, "discovery_attempts": tried}
        return {
            "status": "SUCCESS",
            "message": f"Application '{app_name}' connected live.",
            "mode": "LIVE",
            "pipeline": pipeline,
            "agent_card": card.model_dump(),
            "analysis": analysis,
            "binding": binding.model_dump(),
            "console_url": f"/apps/{app_id}",
        }

