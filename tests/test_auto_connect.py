def test_mesh_issue_matching():
    mesh = A2AEcosystemMesh()
    tool = DiscoveredEndpointTool(
        tool_name="reallocate_sublimit",
        http_method="POST",
        endpoint_path="/sap/credit/realloc",
        description="Transfers sublimit capacity",
        can_resolve_issues=["CREDIT_LIMIT_SHORTFALL", "FACILITY_CAPACITY_BREACH"],
        required_parameters=["amount_eur"],
    )
    card = AutoGeneratedAgentCard(
        agent_id="agent_sap",
        application_name="SAP S/4HANA",
        banking_department="CREDIT_RISK",
        system_instruction="Credit specialist",
        discovered_tools=[tool],
    )
    mesh.register_agent(card)

    matches = mesh.find_agents_for_issue("We have a CREDIT_LIMIT_SHORTFALL of EUR 50k")
    assert len(matches) == 1
    matched_agent, matched_tool = matches[0]
    assert matched_agent.agent_id == "agent_sap"
    assert matched_tool.tool_name == "reallocate_sublimit"

    # Export MCP definitions
    mcp_defs = mesh.export_mcp_tool_definitions()
    assert len(mcp_defs) == 1
    assert "reallocate_sublimit" in mcp_defs[0]["name"]


