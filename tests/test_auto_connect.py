@pytest.mark.asyncio
async def test_legacy_mainframe_screen_assimilation():
    from auto_connect.mock_apps import MAINFRAME_3270_SCREEN

    vault = ZeroTrustVault()
    mesh = A2AEcosystemMesh()
    executor = UniversalAPIExecutor(vault)
    brain = AutonomousEcosystemBrain(vault=vault, mesh=mesh, executor=executor)

    # Ingest the 30-year-old IBM 3270 green screen (Zero API)
    agent_card = brain.assimilate_legacy_screen(
        screen_input=MAINFRAME_3270_SCREEN,
        app_id_hint="agent_mainframe_core_104",
    )

    # Verify agent spawned
    assert agent_card.agent_id == "agent_mainframe_core_104"
    assert "SCREEN 104" in agent_card.application_name
    assert agent_card.banking_department == "CORE_BANKING"
    assert len(agent_card.discovered_tools) == 1

    tool = agent_card.discovered_tools[0]
    assert tool.http_method == "UI_ACTION"
    assert "f3" in tool.endpoint_path
    assert "applicant_acc" in tool.required_parameters
    assert "beneficiary" in tool.required_parameters
    assert "amount_eur" in tool.required_parameters

    # Execute the UI Action dynamically through Universal Executor
    exec_result = await executor.execute_dynamic_call(
        app_id="agent_mainframe_core_104",
        endpoint_path=tool.endpoint_path,
        http_method="UI_ACTION",
        parameters={
            "applicant_acc": "DE89370400440532013000",
            "beneficiary": "IT60X0542811101000000123456",
            "amount_eur": "450000.00",
        },
        requester_department="CORE_BANKING",
    )

    # no live terminal connection exists: the platform must say so instead of pretending a booking happened
    assert exec_result["status_code"] == 501
    assert "No live 3270" in exec_result["data"]["error"]

    # with the demo simulator registered the answer is explicitly marked as simulated
    from auto_connect.mock_apps import mock_mainframe_handler

    executor.register_in_process_handler("agent_mainframe_core_104", mock_mainframe_handler)
    sim = await executor.execute_dynamic_call(app_id="agent_mainframe_core_104", endpoint_path=tool.endpoint_path,
                                              http_method="UI_ACTION", parameters={"applicant_acc": "DE89"},
                                              requester_department="CORE_BANKING")
    assert sim["status_code"] == 200 and sim["data"]["simulated"] is True


@pytest.mark.asyncio
async def test_interactive_app_connect_pipeline_and_disconnect():
    from auto_connect.dashboard import create_app
    import httpx

    app = create_app()
    async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url="http://testserver") as client:
        # Step 1: Connect a new application via the UI onboarding API (e.g. Moody's Analytics)
        res_connect = await client.post("/api/v1/apps/connect", json={
            "app_name": "Moody's Analytics CreditEdge",
            "base_url": "https://api.moodys.com/v2",
            "auth_type": "API_KEY",
            "token": "moodys_secret_key_7718",
            "preset_type": "moodys",
        })
        assert res_connect.status_code == 200
        data = res_connect.json()
        assert data["status"] == "SUCCESS"
        assert len(data["pipeline"]) == 5
        agent_id = data["agent_card"]["agent_id"]

        # Verify pipeline steps
        step_names = [p["step"] for p in data["pipeline"]]
        assert "Zero-Trust Security Gate" in step_names
        assert "A2A Agent Card Generation" in step_names
        assert "Autonomous Mesh Integration" in step_names

        # Step 2: Test ping the newly connected app
        res_test = await client.post(f"/api/v1/apps/{agent_id}/test")
        assert res_test.status_code == 200
        test_data = res_test.json()
        assert test_data["status"] == "SUCCESS"
        assert test_data["execution_result"]["status_code"] == 200

        # Step 3: Run orchestrate - the newly connected app automatically joins the workflow
        res_orch = await client.post("/api/v1/orchestrate", json={
            "problem": "Examine L/C dossier DOS-2026-8831 and assess counterparty default probability."
        })
        assert res_orch.status_code == 200
        orch_data = res_orch.json()
        # Moody's agent should be in the execution steps!
        executing_agents = [s["executing_agent_id"] for s in orch_data["steps"]]
        assert any("moody" in a.lower() for a in executing_agents)

        # Step 4: Disconnect the application
        res_del = await client.delete(f"/api/v1/apps/{agent_id}")
        assert res_del.status_code == 200
        del_data = res_del.json()
        assert del_data["status"] == "SUCCESS"


@pytest.mark.asyncio
async def test_zero_trust_rejects_wrong_tokens():
    """Verifies that fake, dummy, or invalid tokens are rejected with 401 Unauthorized."""
    from auto_connect.dashboard import create_app
    import httpx

    app = create_app()
    async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url="http://test") as client:
        # 1. Reject explicit dummy tokens
        for bad_token in ["wrong", "fake", "dummy", "invalid", "12345", "wrong_token_xyz"]:
            res = await client.post("/api/v1/apps/connect", json={
                "app_name": "Test Suspicious App",
                "auth_type": "Bearer",
                "token": bad_token,
            })
            assert res.status_code == 200
            data = res.json()
            assert data["status"] == "ERROR"
            assert "401 UNAUTHORIZED" in data["message"]
            assert data["pipeline"][0]["status"] == "REJECTED_401"

        # 2. Reject empty token
        res_empty = await client.post("/api/v1/apps/connect", json={
            "app_name": "Test Missing Token App",
            "auth_type": "Bearer",
            "token": "",
        })
        assert res_empty.json()["status"] == "ERROR"
        assert "401 UNAUTHORIZED" in res_empty.json()["message"]




