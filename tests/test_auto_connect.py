def test_zero_trust_vault_rbac():
    vault = ZeroTrustVault()
    vault.store_credential(VaultCredential(
        app_id="sap_app",
        base_url="https://sap.internal",
        auth_type="Bearer",
        token="secret_token_123",
        allowed_departments=["CREDIT_RISK", "TRADE_FINANCE"],
    ))

    # Authorized department
    cred = vault.get_credential("sap_app", "CREDIT_RISK")
    assert cred is not None
    assert cred.token == "secret_token_123"

    headers = vault.build_auth_headers("sap_app", "TRADE_FINANCE")
    assert headers["Authorization"] == "Bearer secret_token_123"
    assert headers["X-Requester-Department"] == "TRADE_FINANCE"

    # Unauthorized department must be rejected
    cred_unauth = vault.get_credential("sap_app", "HR_PAYROLL")
    assert cred_unauth is None

    with pytest.raises(PermissionError):
        vault.build_auth_headers("sap_app", "HR_PAYROLL")

    # Audit log verification
    assert len(vault.audit_trail) >= 3


